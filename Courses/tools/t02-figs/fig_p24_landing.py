    para(f, BX + 18, R1_Y + 46, BW - 36,
         "<g>跟这两块硬件<b>无关</b> —— 换成别的两块照样用。"
         "这四句是这门课真正能迁移的部分。</g>", "xxs", 14)

    y = R1_Y + 86
