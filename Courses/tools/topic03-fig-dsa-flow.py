r"""专题三 · DSA 一步是怎么走的 ——&nbsp;**现场点名要的那张图**。

════════════════════════════════════════════════════════════════════
2026-09-14 R62 R7 新画。现场原话（一字不改）：
════════════════════════════════════════════════════════════════════
  「然后 DSA 到底是你要画图讲，你就像那 DeepSeek 论文里边那样画图讲。
    **它到底是怎么样算的这个 Top 二零四八呀？然后怎么省的这个显存呢？
    然后 trade off 是什么呀？然后需求的算力又增加了什么这个稀疏的访问呢？**」

⭐ 四个问题，四块画面 ——&nbsp;**一一对上，一个都不含糊**：
  ① top-2048 怎么挑出来的  →&nbsp;三步流水线 ＋ 索引器那条式子
  ② 那 2048 在整幅画面里多大 →&nbsp;一条按真比例画的带子
  ③④ 省了什么 / 没省什么 / 多花了什么 →&nbsp;三栏账

⛔⛔ **第二问的答案是「不省」，必须当面说清楚。**
  「稀疏 →&nbsp;省显存」是个极自然的误会：要能从历史里挑，就得**把历史全留着**。
  ⭐ 判据：**一个方案最值得讲的，往往是它<u>没有</u>解决的那一栏。**
    这一栏空着，正好把第八章「那就都要」逼出来。

════════════════════════════════════════════════════════════════════
📌 出处（全部一手核过，2026-09-14）
════════════════════════════════════════════════════════════════════
· **闪电索引器（lightning indexer）的形式**：
  `I[t,s] = Σ_j w[t,j] · ReLU( q[t,j] · k[s] )`，之后取 `top-k(I)`，
  `k = 2048`（公开实现里的取值）。
  ——&nbsp;DeepSeek-V3.2 技术报告（arXiv 2512.02556）与公开代码。
  ⭐ 注意两个细节都不是装饰：**ReLU 不是 softmax**（它只拿来排序，
  不做加权平均，所以「和为 1」根本不必要），**头数很少**。

· **「事后稀疏省不到时间」与「不连续访存用不了 FlashAttention」**：
  NSA 论文（arXiv 2502.11089）§2.1 / §2.2 逐条点名。原文：
  token 粒度的选择要从 KV cache 里加载大量单个 token，
  「**This non-contiguous memory access prevents efficient adaptation of
  fast attention techniques like FlashAttention**」。
  ⭐ 这就是现场问的「稀疏的访问」那一问的硬出处。

· **1.56%**：2048 ÷ 131072。⚠️ 是算出来的，不是测出来的。

⛔ 不要往这张图里塞 DSA 的**训练**故事（师徒 / KL 热身）——&nbsp;
  那是另一张图（fig3-dsa-why）的活。**一张图只回答一个问题。**
"""
from topic03_draw import (Fig, BL, OR, GR, RD, GY, PU, INK, GY2, LINE, LINE2,
                          BG2, BR)

W = 1400
L_CTX = 131072
TOPK = 2048
PCT = 100.0 * TOPK / L_CTX          # 1.5625


def main():
    f = Fig(W, "DSA 一步的三段流水线：闪电索引器用一个很轻的打分函数扫过全部历史，"
               "取分数最高的 2048 个，再只对这 2048 个做完整的注意力；"
               "以及三栏账：省了每步要算要搬的量、一点显存都没省、"
               "多花了索引器的全程打分和挑中之后的不连续访存")
    f.marks = set()
    y0 = f.header(
        "DSA 走一步 ——&#160;<tspan font-weight=\"700\">那 2048 个是怎么挑出来的</tspan>",
        "⭐ 三步，<tspan font-weight=\"700\">每一步都便宜；真正贵的那一步，"
        "根本没在全长上做</tspan>",
        [(BL, "轻：索引器扫全程"), (OR, "挑中的 2048"), (GY2, "没被读到的"),
         (RD, "代价")])

    # ══════════════════════════════════════════════════════════════
    # ① 三步流水线
    # ══════════════════════════════════════════════════════════════
    PH = 376
    py = f.panel(0, y0, W, PH, "① 一步之内发生了什么", BL,
                 sub="从左往右读 ——　注意前两步都还没碰真正的 K/V，只在跟「分数」打交道",
                 tint="#d6e4fb")
    ay = py + 26

    # ── 当前这个字 ────────────────────────────────────────────────
    # ⛔ 原来这里还有一条往右下的箭头，指向**一个不存在的下路** ——　
    #   真正的注意力发生在挑完之后，不是跟索引器并排跑。图上没有的东西不许画箭头指。
    f.cell(24, ay + 92, 108, 62, "当前这个字", "它的 q", INK, "#fff", size=15)
    f.line(132, ay + 122, 176, ay + 74, BL, 1.8)

    # ── 上路：闪电索引器 ─────────────────────────────────────────
    IX, IW = 182, 412
    f.box(IX, ay + 12, IW, 112, "#e8f0fe", BL, 8)
    f.t(IX + 16, ay + 40, "⚡ 闪电索引器", BL, True, 21)
    f.t(IX + 16, ay + 66, "给<tspan font-weight=\"700\">每一个</tspan>历史 token 打一个分",
        GY, size=16)
    f.t(IX + 16, ay + 96,
        "I[t,s] ＝ Σ<tspan baseline-shift=\"sub\" font-size=\"11\">j</tspan> "
        "w[t,j] · ReLU( q[t,j] · k[s] )", BL, True, 15, mono=True)
    f.t(IX + 16, ay + 146, "⭐ 它便宜在三处：", BL, True, 17)
    for i, s_ in enumerate((
            "头很少（不是主注意力那 128 个头）",
            "用 ReLU 不用 softmax ——　只排序，不做加权平均",
            "低精度就够（它只要把顺序排对）")):
        f.t(IX + 34, ay + 174 + i * 24, "· " + s_, GY, size=16)

    # ⛔ 这一格是整张图的题眼：便宜 ≠ 不做
    f.box(IX, ay + 250, IW, 62, "#fce8e6", RD, 8)
    f.t(IX + 16, ay + 278, "⛔ 但它<tspan font-weight=\"700\">必须扫过全部历史</tspan>",
        RD, True, 18)
    f.t(IX + 16, ay + 300, "一个都不能跳 ——　不扫完，就不知道该跳谁", GY, size=16)

    f.elbow(IX + IW, ay + 68, IX + IW + 44, ay + 68, BL, 2.0, r=1)

    # ── 中路：分数条 → top-k ─────────────────────────────────────
    SX, SW = 622, 352
    f.t(SX, ay + 10, "② 一整排分数，挑出最高的 2048 个", INK, True, 18)
    # 分数条：24 根，随机高度的示意（固定写死，不能用随机）
    HS = [18, 41, 9, 52, 26, 7, 63, 14, 33, 5, 47, 11,
          22, 58, 8, 30, 12, 44, 6, 37, 16, 50, 10, 28]
    KEEP = {3, 6, 13, 21, 10, 17}          # 被选中的那几根
    BX, BW, BG_ = SX, 13, 1.6
    for i, hgt in enumerate(HS):
        x = BX + i * (BW + BG_)
        on = i in KEEP
        f.box(x, ay + 108 - hgt, BW, hgt, "#fbbc04" if on else "#e8eaed",
              OR if on else LINE2, 2)
    f.line(BX - 6, ay + 112, BX + 24 * (BW + BG_), ay + 112, GY2, 1.1,
           arrow=False)
    f.t(SX, ay + 134, "⭐ 橙色那几根 ＝ 分数进了前 2048", OR, True, 16)
    f.t(SX, ay + 156, "灰色的 ——　这一步之后就再也不碰了", GY2, size=16)

    f.box(SX, ay + 178, SW, 50, "#fef7e0", OR, 8)
    f.t(SX + SW / 2.0, ay + 209, "top-2048 选择器", OR, True, 20, "middle")
    f.t(SX, ay + 250, "⚠️ 挑的是<tspan font-weight=\"700\">位置</tspan>，不是内容 ——",
        GY, size=16)
    f.t(SX, ay + 272, "选完才去仓库里把这 2048 份取出来。", GY, size=16)
    f.t(SX, ay + 300, "⛔ 而它们<tspan font-weight=\"700\">散落在各处</tspan>，"
        "不是连着的一块。", RD, True, 16)

    f.elbow(SX + SW, ay + 203, SX + SW + 34, ay + 203, OR, 2.0, r=1)

    # ── 右路：稀疏注意力 ─────────────────────────────────────────
    RX, RWD = 1012, 364
    f.box(RX, ay + 12, RWD, 216, "#fff", GR, 8)
    f.t(RX + 16, ay + 42, "③ 只对这 2048 个做真正的注意力", GR, True, 19)
    f.t(RX + 16, ay + 68, "（V3.2 里就是完整的 MLA）", GY2, size=16)
    for r in range(4):
        for c in range(12):
            on = (r * 12 + c) % 7 == 3
            f.box(RX + 20 + c * 27, ay + 88 + r * 27, 22, 22,
                  "#e6f4ea" if on else "#f8f9fa", GR if on else "#eceff1", 3)
    f.t(RX + 16, ay + 214, "⭐ 贵的那一步，只在 1.56% 的格子上做", GR, True, 17)

    f.box(RX, ay + 244, RWD, 68, BG2, LINE2, 8)
    f.t(RX + 16, ay + 270, "所以整段注意力的账", INK, True, 17)
    f.t(RX + 16, ay + 292,
        "从 <tspan font-weight=\"700\">L × L</tspan> 变成 "
        "<tspan font-weight=\"700\">L × 2048</tspan>", GY, size=16)
    f.t(RX + 16, ay + 312, "⭐ 长文越长，赚得越多", GR, True, 16)

    # ══════════════════════════════════════════════════════════════
    # ② 2048 到底有多大：按真比例画一条带子
    # ══════════════════════════════════════════════════════════════
    y1 = y0 + PH + 18
    PH2 = 172
    p2 = f.panel(0, y1, W, PH2, "② 2048 在 128K 里是多大一块", OR,
                 sub="这一条按真比例画 ——　上面那 24 根柱子是示意，这一条不是",
                 tint="#fbeecb")
    by = p2 + 30
    TW = 1320
    f.box(40, by, TW, 34, "#e8eaed", LINE2, 4)
    f.box(40, by, max(3.0, TW * PCT / 100.0), 34, "#fbbc04", OR, 4)
    f.t(40, by + 58, "⭐ 2048 ÷ 131072 ＝ <tspan font-weight=\"700\">1.56%</tspan>"
        "　——　橙色那一小条就是每一步真正读进来的量", OR, True, 17)
    f.t(40, by + 84, "⛔ 剩下那 98.4% <tspan font-weight=\"700\">还好端端地躺在显存里</tspan>"
        "　——　它们只是这一步没被读，不是没被存。", RD, True, 17)
    f.t(40, by + 108, "📌 顺带一个定义直接推出来的事实：历史不足 2048 时，"
        "top-2048 就是全选 ——　短上下文下 DSA 就是普通 MLA，稀疏根本没启动。",
        GY, size=16)

    # ══════════════════════════════════════════════════════════════
    # ③ 三栏账：省 / 没省 / 多花
    # ══════════════════════════════════════════════════════════════
    y2 = y1 + PH2 + 18
    PH3 = 330
    CW, GAP = 440, 30
    COLS = (
        (GR, "✅ 省下来的", "每一步要算、要搬的那些格子", [
            "注意力那一段从 <b>L×L</b> 变成 <b>L×2048</b>。",
            "128K 下就是 <b>只读 1.56%</b>。",
            "⭐ 上下文越长，省得越多 ——",
            "　 因为省的是<b>跟长度成正比</b>的那一段。",
        ]),
        (RD, "⛔ 一点没省的", "显存 ——　而且还多了一成", [
            "<b>KV cache 一个字节都没少。</b>",
            "⛔ 道理很硬：<b>要能从历史里挑，</b>",
            "　 <b>就得把历史全留着。</b>",
            "⛔⛔ <b>而且索引器自己还要一份</b>：",
            "　 128 维 × FP8 × 61 层 × 128K",
            "　 ＝ <b>0.95 GiB</b>，<b>比 V3 还多存约一成</b>。",
        ]),
        (BR, "⚠️ 反而多花的", "三笔，而且一笔比一笔疼", [
            "① <b>索引器要给所有历史打分</b>，一个都不能跳。",
            "② <b>它那 0.95 GiB，每一步都要整条读完</b> ——",
            "　 ⛔ <b>是挑中那 2048 个（0.13 GiB）的 7 倍。</b>",
            "③ <b>挑中的 2048 个散落在各处</b>，搬起来碎。",
            "⭐ 所以这一支后来都在缩第 ② 笔：",
            "　 <b>几层共用一个索引器</b>。",
        ]),
    )
    for i, (col, ttl, sub, rows) in enumerate(COLS):
        x = 10 + i * (CW + GAP)
        tp = f.panel(x, y2, CW, PH3, ttl, col, sub=sub,
                     tint={GR: "#d7ecdc", RD: "#fadad6", BR: "#fbeecb"}[col])
        for k, ln in enumerate(rows):
            ln = ln.replace("<b>", "<tspan font-weight=\"700\">") \
                   .replace("</b>", "</tspan>")
            f.t(x + 20, tp + 34 + k * 30, ln, GY, size=17, w=CW - 40)

    # ── ③ 底下补一句：为什么「不规整」这件事值得单独拿出来说 ────────
    # ⛔ 这一格原来是手画的 box，压在三栏面板的下沿上 ——　盖住了第三栏最后一行。
    #   ⭐ 判据两条：**横跨多栏的块要放在那几栏外面**；而且**这种块就该用 band** ——
    #     手画 box 会被越界自检算进上一个面板，报一个假警告。
    yy = y2 + PH3 + 16
    yy = f.band(yy, "bad", "⭐⭐ 这两笔多花的，正好把这一支后来的样子定下来了", [
        "省 FLOPs 谁都会 ——　在纸上少算 98% 的格子而已。"
        "可只要那些格子<tspan font-weight=\"700\">散落在显存各处</tspan>，"
        "<tspan font-weight=\"700\">要搬的字节一点没少，时间就一点没省</tspan>。",
    ])
    yy += 16

    yy = f.band(yy, "info", "⭐⭐ 回到现场那四问，答案一句一条", [
        "<tspan font-weight=\"700\">怎么挑的</tspan>："
        "一个很轻的打分器扫过全部历史，取分数最高的 2048 个位置。",
        "<tspan font-weight=\"700\">省了显存吗</tspan>："
        "<tspan font-weight=\"700\">没有，一个字节都没省。</tspan>"
        "省的是每一步真正读进来、算进去的那一部分。",
        "<tspan font-weight=\"700\">trade-off 是什么</tspan>："
        "拿「可能漏掉某个重要的」换「只读 1.56%」——　"
        "而漏不漏，是靠训练让打分器去对齐真注意力的分布。",
        "<tspan font-weight=\"700\">多花了什么算力</tspan>："
        "索引器的全程打分（轻，但随长度涨）＋ 挑中之后的<tspan "
        "font-weight=\"700\">不连续访存</tspan>（这一笔更疼）。",
    ])
    yy = f.src(yy + 16,
               "索引器的式子 I[t,s] ＝ Σ w·ReLU(q·k) 与 top-k＝2048 "
               "出自 DeepSeek-V3.2 技术报告（arXiv 2512.02556）及其公开实现",
               "「不连续访存用不上 FlashAttention」逐条出自 NSA 论文 "
               "（arXiv 2502.11089）§2.2：token 粒度的选择要从 KV cache 里"
               "加载大量单个 token，"
               "「this non-contiguous memory access prevents efficient "
               "adaptation of fast attention techniques like FlashAttention」",
               "⚠️ 1.56% ＝ 2048 ÷ 131072，是<tspan font-weight=\"700\">算出来的"
               "</tspan>；上排 24 根柱子的高低与选中位置是<tspan "
               "font-weight=\"700\">示意</tspan>，不对应任何一次真实打分")
    f.save("fig3-dsa-flow.svg", yy + 6)


main()
