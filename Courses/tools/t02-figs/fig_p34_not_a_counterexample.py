def build():
    f = Fig(W, H, "CUDA Graph 不构成反例：它自身要求形状静态、它补的是 TPU 架构上"
                  "不存在的问题、而且它一个晶体管也省不掉")
    f.title("那为什么这<tspan font-weight=\"700\">不算反例</tspan>"
            "　—— 三条理由，指向同一个方向")
    f.legend([(YL, "① 它自己也交静态税"), (GN, "② TPU 不需要它"),
              (RD, "③ 硬件一点没省")])
    _cards(f)
    _update(f)
    _land(f)
    _src(f)
    return f.out()


