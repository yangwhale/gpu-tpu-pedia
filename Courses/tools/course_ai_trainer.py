# -*- coding: utf-8 -*-
r"""每一讲正文开头那一格：**讲义真正的用法是整份丢给 AI** —— 一份定义，全课共用。

⭐⭐⭐ 2026-09-23 现场（原话）：
  「这个地方的重点是告诉人们，把这个讲义丢给 AI，就可以得到一个什么背景和知识
    都懂得透彻、又知道该怎么讲的 Trainer Agent，帮助你去自学。」
  紧接着：「这个观点给前面几个专题也写上。」

⛔ 我第一版在专题四写的是「讲义＝给讲课的人用的」—— **那是它的出身，不是它的用处。**
  按那个说法，不打算上台的人看一眼就划走了，而他恰恰是最该拿走它的人。
⭐⭐ 判据：**介绍一份材料，写它能给读者什么，不要写它当初为谁而写。**
  这两个在作者脑子里是同一件事，在读者那儿完全不是。

⛔⛔ 2026-09-23 第二轮，现场原话：「那个你能正经说话吗？不要讲道理好不好？
  就是简要地说结论就行了。这是干什么用的就好，不要 AI 味又回来了，那么重。」
  ⭐ 第一版犯的是同一类毛病，而且很典型：**反问句起头、破折号堆叠、
    「正是任何一个通用 AI 没有的东西」这种收束。** 它在替一段介绍性文字做论证。
  ⛔ 判据：**一格「这是什么、干什么用」的说明，只报事实，不要论证。**
    论证是给有异议的人写的；这里的读者还没形成异议，他只想知道这玩意儿干嘛的。
  ⚠️ 所以这一版的规矩：三句话，不用反问，不用「不是 A 是 B」，
    不放 ⭐／⛔，加粗只留「怎么讲 / 自己上台讲 / 自学」几个词。

⛔⛔ 为什么这段话要单独成一个模块，而不是七个页面各写各的：
  这句话是**课程层面的一个主张**，不是某一讲的细节。它一定会改措辞，
  而改的时候不会有人记得它散在七个地方 —— 漏掉的那几页不会报错，
  只是继续说着旧版本。
  ⭐ 所以：文字只在这儿，落地方式两种 ——
    · 脚本生成的页面直接 `+ AIT.note(...) +` 拼进去；
    · **手写维护**的页面（`topic-01.html` / `topic-02-L300.html`）没有脚本，
      只能把渲染结果粘进 HTML。
  ⚠️ 粘贴的那两份靠 `tools/lint-ai-trainer.py` 守着：
    改了这里而没回去重粘，构建**会红**。宁可红，不要静默各说各的。
"""

# 正文页 → 它那一讲的讲义。⛔ 新增一讲要在这儿登记，否则 lint 扫不到它。
DECKS = (
    ("topic-01.html",      "topic-01-lecture.html"),
    ("topic-02.html",      "topic-02-L200-lecture.html"),
    ("topic-02-L300.html", "topic-02-L200-lecture.html"),
    ("topic-03.html",      "topic-03-lecture.html"),
    ("topic-03-L300.html", "topic-03-L300-lecture.html"),
    ("topic-04.html",      "topic-04-lecture.html"),
    ("topic-08.html",      "topic-08-lecture.html"),
)

# ⛔ 这段里**不要出现 `%`** —— 有一个页面（topic02-build-L200）的模板走
#   `'''…''' % URL` 格式化，粘进去的文本里带 % 会当场炸掉，而且报的错跟这段无关。
_TPL = '''<div class="wrap"><div class="note" id="ai-trainer">
  <p><b>这一讲另有一份<a href="__L__">讲义</a>（授课稿）。</b></p>
  <p>讲义写的是<b>怎么讲</b>：每一段的目的、讲到哪里该停、常见的误解、
    被问到了怎么答。内容本身在你现在看的这份正文里。</p>
  <p>两个用法。<b>自己上台讲</b>：照着讲义讲，台词、切图、时间都写着。
    <b>自学</b>：把讲义整份丢给 AI，你会得到一个既有这一讲全部背景、
    也知道该怎么讲的助教，让它带你走一遍。</p>
</div></div>'''

assert "%" not in _TPL, "这段文本里不能有 % —— 有个页面的模板走 % 格式化"


def note(lecture_href):
    """渲染这一格。`lecture_href` 是同目录下那份讲义的文件名。"""
    assert lecture_href.endswith(".html"), lecture_href
    assert lecture_href in [l for _, l in DECKS], \
        "%r 没在 DECKS 里登记" % lecture_href
    return _TPL.replace("__L__", lecture_href)
