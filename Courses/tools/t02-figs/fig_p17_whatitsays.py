"""图 P-17 —— 换一个问法，就换一个倍数。

P-15 给了一个倍数，P-16 说明它是怎么挣来的。这一张负责**收口** ——
因为一个 1.31 倍放出去之后，会被引用成十种不同的意思。

  甲　换一个问法就换一个倍数 —— 1.31 / 2.06 / 答不上来
  乙　FP8 在两边的兑现率 —— 第二组数据
  底　能说的只有一句，抄走就能用

**甲那三根条为什么必须画在一起。** 分开讲的时候，
「同精度差 1.31 倍」和「各自最好差 2.06 倍」听起来像两个互相矛盾的结论；
并排放在同一根轴上，它们就变成同一件事的两种问法。
**第三根条是虚的、末端画问号** —— 那是第 ④ 档（每美元 / 每瓦），
我们答不了。让「答不了」在图上占一根条的位置，
比在脚注里写一句「本文不涉及」有用得多。

⛔ **这张图返工过两次，两次改的都是「说过头」。**

**返工一：乙格原来叫「第二条独立证据链」，这是过度声称。**
原话是「两边的 FP8 峰值都正好是 BF16 的 2 倍，兑现率却一边 +59.3% 一边 +1.3%，
所以差的不是硅片」。但**低兑现率完全可以是硬件原因** ——
算力翻倍而 HBM 带宽没翻倍，FP8 就吃不满，那是硅片不是软件。
它跟 P-15 乙格共用同一个未经检验的前提：峰值与实测之间的缺口都算软件。
现在降级成「**第二组数据，不是第二条独立推理**」，并在图上写出可证伪条件。

**返工二：+59.3% 那个数不是同批次比较，已换成 +50.6%。**
GB300 的 C2 配置带 `--mbs 2 --gbs 4096`，**global batch 是 BF16 冠军 A1 的两倍**。
仓库自己把这 59.3% 拆开过：精度 **+50.6%**（A1 854.0 → C1 1,285.9，
同 GBS 2048、同 MBS 1）× MBS2 解锁 **+5.8%**，1.506 × 1.058 = 1.593 ✓。
而对面 v7 的 +1.3% 反而是在**更小**的 batch 上测的（pdbs 11，BF16 那边是 12）。
**乙格现在用 C1 的 +50.6%，口径才对得上；C2 只作脚注。**

⭐ **乙格改用「槽 + 填充」重画，跟 P-15 甲格是同一套视觉语言。**
它讲的正是「许诺 vs 兑现」—— 全课最该用槽的地方。
两边的 FP8 槽都正好是各自 BF16 槽的 2 倍（硬件许诺一模一样），
可 GB300 那根填充跟着长了一大截，v7 那根几乎贴着原地没动。
**结论直接从图里跳出来，落点那两行字因此可以少写一半。**

⚠️ **甲② 那两个 FP8 不是同一种 FP8**，图上必须写：
GB300 走 `fp8_mx`（硬件 block scaling），v7 走 `absmax` 生产配方。
而且我们**只对自己那一侧做了收敛审查**（v7 的 `fixed` 校准版 727.0 / 5,235
因为伤收敛被剔除），没对 GB300 那条路问同一个问题 ——
**审收敛的尺子只用在自己身上，是不对称的严谨。**

丙格（四条不能拿它说的话）已拆出去独立成 **P-18**，原因有二：
① 这张图五个信息区挤一屏，密度过高；
② 讲课时要先只放 P-17、问一句「你觉得这个倍数还缺什么」，
   等台下自己说出几条，再放 P-18 —— **一张静态图做不到分段揭示**。
拆开之后边界从四条扩到六条，每条还能标出它把倍数往哪边推。

数据出处（全部本仓库）：
  · BF16 6,242 / 4,770 —— 见 P-15
  · FP8 同批次：GB300 C1（fp8_mx，GBS 2048 / MBS 1）1,285.9 / 9,396，+50.6%
    v7 生产配方（FP8 native FSDP128 + absmax + pdbs 11）670.8 / 4,830，+1.3%
  · FP8 各自最优：GB300 C2（fp8_mx + MBS 2 + GBS 4096）1,360.4 / 9,945
    （另有 v7 `fixed` 校准 727.0 / 5,235，⚠️ 伤收敛、不可交付，不用它比）
  · FP8 峰值 4,614 / 5,000 —— 均为各自 BF16 峰值的 2 倍，见 P-12
"""
from common import Fig, para, BL, RD, GN, INK, SUB, LINE, GREY, FILL

W = 1400
TOP = 84

R1_Y = TOP + 40
R1_H = 372

AX, AW = 20, 760
BX, BW = 792, 588

BAND_Y = R1_Y + R1_H + 24
H = BAND_Y + 136

# 甲：(问法, GB300 值, v7 值, 倍数, 倍数条比例, 颜色, 说明)
ASK = [("① 都跑 BF16（上一张图那组）", "6,242", "4,770", "1.31×", 1.31, GN,
        "<g>两边同精度、同 seq、同 64 个单元。<b>口径最接近的一问</b>"
        "—— 仍有六条边界，见 P-18。</g>"),
       ("② 两边各自用最擅长的精度", "9,945", "4,830", "2.06×", 2.06, RD,
        "<g>GB300 换 <code>fp8_mx</code>，v7 换 <code>absmax</code> 生产配方。"
        "<b>倍数从 1.31 跳到 2.06 —— 但这两个不是同一种 FP8，batch 也差 2.9 倍。</b></g>"),
       ("③ 每美元 / 每瓦", "—", "—", "答不了", 0, GREY,
        "<r><b>牌价查得到，但采购价是谈出来的；两边的功耗也没有可比口径。</b></r>"
        "<g>而这两样恰恰是采购真正要的 —— 见上一节第 ④ 档。</g>")]
MMAX = 2.4

# 乙：同批次的 FP8 兑现率 —— (名字, BF16 峰值, BF16 实测, FP8 峰值, FP8 实测, 涨幅, 色)
FP8 = [("GB300", 2500, 854.0, 5000, 1285.9, "+50.6%", BL),
       ("TPU v7", 2307, 662.3, 4614, 670.8, "+1.3%", GN)]
FSC = 5000.0


def build():
    f = Fig(W, H, "同一组实测换三种问法得到三个不同答案：同精度 1.31 倍、"
                  "各自最优精度 2.06 倍、每美元每瓦答不了；"
                  "以及 FP8 在两边的兑现率一边 +50.6% 一边 +1.3%")
    f.title("这组数能说什么　—— <tspan font-weight=\"700\" fill=\"#d93025\">"
            "换一个问法，就换一个倍数</tspan>")
    f.legend([(GN, "口径最接近的一问"), (RD, "换精度之后"),
              (GREY, "答不了 —— 而「答不了」也要占一格")])

    _ask(f)
    _fp8(f)
    _band(f)
    f.t(W - 20, H - 12,
        "三个问法用的是同一批实测 · tok/s / 计算单元 · "
        "同一个 Hunyuan3-295B-A21B · seq 4096 · 各 64 个单元 · "
        "不能拿它说的话见 P-18",
        "xxs", GREY, "end")
    return f.out()


# ══════════════════════════════════════════════════════════════════════
def _ask(f):
    f.rect(AX, R1_Y, AW, R1_H, "#fff", LINE, 1.2, 10)
    f.t(AX + 18, R1_Y + 26, "甲　·　同一批实测，三个问法", "sec")
    para(f, AX + 18, R1_Y + 46, AW - 36,
         "<g>三根条同一根轴。<b>分开讲，①② 听起来像互相矛盾的两个结论；"
         "并排放，它们只是同一件事的两种问法。</b></g>", "xs", 16)

    BARX, BARW = 430, 244
    y = R1_Y + 88
    for name, g, v, mult, r, c, note in ASK:
        f.rect(AX + 18, y, AW - 36, 84, FILL[c] if c != GREY else "#fff",
               c, 1.4, 8)
        para(f, AX + 32, y + 22, 380, "<b>%s</b>" % name, "xs", 15, c)
        para(f, AX + 32, y + 42, 380, note, "xxs", 14)

        f.rect(AX + BARX, y + 12, BARW, 20, "#fff", LINE, 1.0, 3, "4 3")
        if r:
            f.rect(AX + BARX, y + 12, BARW * r / MMAX, 20, FILL[c], c, 1.6, 3)
            f.t(AX + BARX + BARW * r / MMAX + 10, y + 27, mult, "numb", c)
            f.t(AX + BARX, y + 52, "GB300 %s  ÷  v7 %s  tok/s" % (g, v),
                "xxs", SUB)
        else:
            f.t(AX + BARX + BARW / 2, y + 27, "？", "numb", GREY, "middle")
            f.t(AX + BARX + BARW + 10, y + 27, mult, "numb", GREY)
            f.t(AX + BARX, y + 52, "牌价 ≠ 成交价 · 功耗无可比口径", "xxs", SUB)
        y += 92


# ══════════════════════════════════════════════════════════════════════
def _fp8(f):
    f.rect(BX, R1_Y, BW, R1_H, FILL[BL], BL, 1.4, 10)
    f.t(BX + 18, R1_Y + 26, "乙　·　同一张空头支票，两边兑现得完全不同", "sec")
    para(f, BX + 18, R1_Y + 46, BW - 36,
         "<g>浅槽＝峰值，深段＝实测 —— 和 P-15 甲格同一套画法。"
         "<b>两边的 FP8 槽都正好是各自 BF16 槽的 2 倍。</b></g>", "xs", 16)

    LX, LW = BX + 32, 400          # 槽满程对应 FSC = 5,000
    y = R1_Y + 88
    for name, pbf, bf, pfp, fp, gain, c in FP8:
        f.rect(BX + 18, y, BW - 36, 92, "#fff", c, 1.4, 8)
        f.t(BX + 32, y + 22, name, "box", c)
        f.t(BX + BW - 32, y + 24, gain, "numb", GN if "50" in gain else RD,
            "end")
        for j, (label, pk, ms) in enumerate((("BF16", pbf, bf),
                                             ("FP8 ", pfp, fp))):
            by = y + 36 + j * 26
            f.rect(LX, by, LW * pk / FSC, 18, FILL[SUB], GREY, 1.0, 3)
            f.rect(LX, by, LW * ms / FSC, 18, FILL[c], c, 1.6, 3)
            f.t(LX - 8, by + 13, label, "xxs", SUB, "end")
            f.t(LX + LW * ms / FSC + 8, by + 13, "%.1f" % ms, "xxs", c)
            f.t(LX + LW * pk / FSC + 8, by + 13,
                "槽 %s" % format(pk, ","), "xxs", GREY)
        y += 100

    f.rect(BX + 18, R1_Y + 292, BW - 36, 64, "#fff", RD, 1.4, 8)
    yy = para(f, BX + 32, R1_Y + 311, BW - 64,
              "<b>⭐ 支票一样大，一边兑了一半，一边几乎没兑。</b>"
              "<g>（同 GBS 2048 / MBS 1 的 C1；各自最优的 C2 是 +59.3%，"
              "但它把 batch 也翻倍了。）</g>", "xs", 15)
    para(f, BX + 32, yy + 1, BW - 64,
         "<r><b>⚠️ 但这不能证明「差的是软件」</b></r>"
         "<g>：算力翻倍而 HBM 带宽没翻倍，FP8 一样吃不满 —— <b>那是硅片。"
         "我们没有能排除这一点的数据。</b></g>", "xxs", 13)


# ══════════════════════════════════════════════════════════════════════
def _band(f):
    f.rect(20, BAND_Y, 1360, 112, FILL[GN], GN, 1.4, 10)
    f.t(38, BAND_Y + 28, "⭐ 去掉 P-18 那六条之后，还能说的只剩这一句 —— 抄走就能用", "sec")
    y = BAND_Y + 54
    y = para(f, 38, y, 1324,
             "<b>「在 Hunyuan3-295B-A21B、seq 4096、各 64 个计算单元、"
             "<r>以 2026 年 8 月两边的软件栈</r>，GB300 的每卡吞吐是 v7 每芯片的 "
             "<r>1.31 倍</r>（6,242 对 4,770 tok/s）；换成 TFLOP/s 口径是 1.29 倍，"
             "其中 <r>1.084 倍</r>来自峰值差（2,500 对 2,307），其余不来自峰值。」</b>",
             "xs", 19)
    para(f, 38, y + 2, 1324,
         "<g>一句话里有<b>模型 · 规模 · 时间 · 单位 · 分解</b>五个槽位，"
         "而且分解那一段说的是「不来自峰值」不是「来自软件」—— <b>后者我们没证明。</b></g>"
         "<r><b>比「GPU 快 30%」长了五倍，但半年后它还能被查。</b></r>", "xs", 19)


if __name__ == "__main__":
    import sys
    open(sys.argv[1] if len(sys.argv) > 1 else "out/fig_p17_whatitsays.svg",
         "w", encoding="utf-8").write(build())
