# -*- coding: utf-8 -*-
r"""外传 图 X-5 · **扩散一步在干什么** —— 它为什么正好是这颗芯片要的那种活。

════════════════════════════════════════════════════════════════════
⭐ 这一张补的是 X-4 没说的另一半
════════════════════════════════════════════════════════════════════
X-4 说清了「强度够高，所以带宽不是瓶颈」——&nbsp;那是**算术**上的匹配。
这一张说**结构**上的匹配，而这一条恰好对上 X-3 里那个「片上谁做主」：

    v6e 片上全部由**编译期**决定（CMEM ＝ 0，没有硬件缓存兜底）。
    ⭐ 这个设计有个**前提**：形状得是固定的、计划得排得出来。
    ⛔ 前提不成立时，它没有后手 ——&nbsp;这也是专题二反复讲的那件事。

**而扩散模型把这个前提喂得满满的：**

  ① **没有 KV cache** ——&nbsp;每一步只吃上一步的结果，不吃历史
  ② **形状从头到尾不变** ——&nbsp;第 1 步和第 50 步的张量一模一样
  ③ **同一段计算重复几十次** ——&nbsp;编译一次，五十步全复用

⭐⭐ 三条合起来：**扩散是「我早就知道你要跑什么」的极端情形。**
   自回归 LLM 恰好相反 ——&nbsp;它每一步的 KV 都更长，形状步步在变。

⛔ 边界：这张图**不讲扩散的数学**（加噪去噪那一套）。L100 二十分钟，
  台下要的是「它对硬件提了什么要求」，不是「它为什么能生成图片」。
  数学那一半在专题十一，那是一小时的 L300。
"""
from topic03_draw import (Fig, wpx, _sz, LINE, LINE2,
                          BL, OR, GR, RD, GY, GY2, PU, CY, INK)

W = 1400


def main():
    f = Fig(W, "左边是自回归 LLM：一个 token 一个 token 产出，KV cache 越来越长，"
               "形状每步都在变；右边是扩散模型：整张图一起动，走五十步，"
               "步与步之间只传一张大小不变的 latent，没有 KV cache，形状从头到尾一样")
    f.marks = set()
    y = f.header(
        '扩散一步在干什么 ——&#160;'
        '<tspan font-weight="700">同一段计算，原样跑五十遍</tspan>',
        '⭐ 这一张不讲扩散的数学，只讲它<tspan font-weight="700">对硬件提了什么要求</tspan>：'
        '没有 KV cache、形状不变、同一段重复几十次。',
        [(RD, "自回归 LLM：形状步步在变"), (BL, "扩散：形状从头到尾一样")])

    COL_W = (W - 40) / 2.0
    top = y + 6

    # ══════════════════ 左：自回归 LLM ══════════════════
    ly = f.panel(0, top, COL_W, 300, "自回归 LLM", RD,
                 sub="一个 token 一个 token", tag="每步都不一样")
    f.t(16, ly + 24, "每一步都要带上前面所有的 KV ——&#160;它一直在长",
        GY, size=_sz(11), w=COL_W - 32)
    for i in range(5):
        yy = ly + 40 + i * 44
        f.t(16, yy + 16, "第 %d 步" % (i + 1), GY2, size=_sz(11))
        # KV 条：越来越长
        # ⛔ 起始宽度原来是 40 —— 放不下「KV × 1」那六个字，红块压上来了。
        #   ⭐ 最短的那一格才是要校的那一格；照着最长的定宽度必然漏掉它。
        bw = 68 + i * 60
        f.box(84, yy + 6, bw, 16, "#fce8e6", RD, 3, 0.8)
        f.t(84 + 8, yy + 18, "KV × %d" % (i + 1), "#a50e0e", size=_sz(11))
        f.box(84 + bw + 8, yy + 6, 26, 16, RD, RD, 3)
        f.t(84 + bw + 8 + 34, yy + 18, "新 token", GY2, size=_sz(11))
    f.t(16, ly + 40 + 5 * 44 + 6,
        "⛔ <tspan font-weight=\"700\">形状每一步都变</tspan>"
        "——&#160;编译好的那一份，下一步就不合用了",
        "#a50e0e", size=_sz(11), w=COL_W - 32)

    # ══════════════════ 右：扩散 ══════════════════
    RX0 = COL_W + 40
    ry = f.panel(RX0, top, COL_W, 300, "扩散模型", BL,
                 sub="整张图一起动，走 N 步", tag="每步一模一样")
    f.t(RX0 + 16, ry + 24,
        "每一步只吃上一步的结果 ——&#160;传过去的东西大小不变",
        GY, size=_sz(11), w=COL_W - 32)
    for i in range(5):
        yy = ry + 40 + i * 44
        lab = "第 %d 步" % (i + 1) if i < 4 else "第 50 步"
        f.t(RX0 + 16, yy + 16, lab, GY2, size=_sz(11))
        f.box(RX0 + 84, yy + 6, 170, 16, "#e8f0fe", BL, 3, 0.8)
        f.t(RX0 + 84 + 8, yy + 18, "latent　大小不变", "#174ea6", size=_sz(11))
        if i < 4:
            f.line(RX0 + 268, yy + 14, RX0 + 300, yy + 14, GY2, 1.2)
            f.t(RX0 + 308, yy + 18, "同一段计算", GY2, size=_sz(11))
        else:
            f.t(RX0 + 268, yy + 18, "……一共五十遍", GY2, size=_sz(11))
    f.t(RX0 + 16, ry + 40 + 5 * 44 + 6,
        "⭐ <tspan font-weight=\"700\">编译一次，五十步全部复用</tspan>"
        "——&#160;而且没有一条 KV cache 要养",
        "#174ea6", size=_sz(11), w=COL_W - 32)

    y = top + 300 + 22

    # ── 三条对照 ────────────────────────────────────────────────
    ROWS = (
        ("步与步之间传什么", "越来越长的 KV cache", "一张大小不变的 latent",
         "⭐ 扩散这一侧根本没有「历史」这个概念"),
        ("张量形状", "每一步都在变", "从头到尾一个形状",
         "⛔ 这一条直接决定编译好的东西能不能复用"),
        ("同一段计算跑几次", "每步都得重排", "原样跑五十遍",
         "⭐ 编译那笔固定开销，被摊到五十步上"),
    )
    hy = y
    f.box(0, hy, W, 30 + len(ROWS) * 54, "#fff", LINE, 8)
    f.colhead(16, hy + 20, "问的是同一件事")
    f.colhead(360, hy + 20, "自回归 LLM")
    f.colhead(760, hy + 20, "扩散模型")
    f.line(0, hy + 30, W, hy + 30, LINE, 1, arrow=False)
    for i, (k, a, b, note) in enumerate(ROWS):
        yy = hy + 30 + i * 54
        if i:
            f.line(0, yy, W, yy, LINE2, 1, arrow=False)
        f.t(16, yy + 24, k, INK, bold=True, size=_sz(12))
        f.box(348, yy + 10, 4, 34, RD, RD, 2)
        f.t(364, yy + 24, a, "#a50e0e", size=_sz(12))
        f.box(748, yy + 10, 4, 34, BL, BL, 2)
        f.t(764, yy + 24, b, "#174ea6", size=_sz(12))
        f.t(1060, yy + 24, note, GY2, size=_sz(11), w=W - 1076)
    y = hy + 30 + len(ROWS) * 54 + 22

    # ── 落点 ────────────────────────────────────────────────────
    y = f.band(y, "ok",
               "把这三条接回上一张芯片图 ——&#160;它们要的正是 v6e 给的",
               ['v6e 片上<tspan font-weight="700">没有硬件缓存兜底</tspan>'
                '（CMEM ＝ 0），放什么全由编译期写死。'
                '这个设计有个前提：<tspan font-weight="700">形状得固定、计划得排得出来</tspan>。',
                '⭐ 而扩散把这个前提<tspan font-weight="700">喂得满满的</tspan>：'
                '形状不变、没有历史要养、同一段跑五十遍 ——&#160;'
                '编译期能知道的，它全都提前告诉你了。',
                '⭐⭐ 所以「合适」是两层意思叠在一起：'
                '<tspan font-weight="700">算术上</tspan>强度够高，'
                '窄带宽没成为瓶颈（上一张）；'
                '<tspan font-weight="700">结构上</tspan>形状全静态，'
                '编译优先这套打法拿到了它最想要的输入（这一张）。'])

    y = f.src(y + 18,
              '「没有 KV cache、每步独立、形状静态」这三条是扩散模型的结构事实，'
              '本课专题十一有完整推导；这一张只取它们对硬件的三个后果',
              '⛔ 本图不含任何 benchmark 数 ——&#160;它讲的是结构匹配，不是快慢。'
              '扩散的数学（加噪 / 去噪 / latent / VAE）属于专题十一，那是一小时的深潜。')
    f.save("figx-5.svg", y + 6)


main()
