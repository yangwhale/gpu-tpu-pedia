# -*- coding: utf-8 -*-
r"""专题三 · §6.2b「凭什么只看 2048 个就够」

⭐⭐⭐ 2026-09-13 **整张重画**，换成一个人人都懂的画面：**查资料。**

   现场原话：「DSA 他又是怎么想的？为什么选 top 2048 就足够？
   太远的那个序列距离，也未必都跟你有关系。」

   ① **「能不能只看一小部分」** ——&nbsp;画一面**书墙**：十三万本书，
      这一次真正用得上的**只有一小格**。经验事实，而且先于 DSA。
   ② **「那怎么知道该看谁」** ——&nbsp;**这是个鸡生蛋**：
      「要知道哪本有用，得先读了」vs「可读完正是我想省的」。
      ⭐⭐ DSA 的解法画成**师徒**：让**真注意力当老师**，
      训一个**便宜的小徒弟**（索引器）去模仿老师的判断 ——&nbsp;
      徒弟不需要懂内容，**只要把书排对顺序**。
   ③ **「徒弟凭什么快」** ——&nbsp;三样减法：头少、打分简单、算得糙。

⛔ 诚实口径：**论文没有给 k 的消融。** 2048 这个具体数字，
   能说的只有「128K 下占 1.6%」和「历史短于 2048 时 top-k 就是全选」。
"""
from topic03_draw import (Fig, BL, OR, GR, RD, GY, PU, INK, GY2, LINE, LINE2,
                          BG2)

W = 1400


def main():
    K, CTX = 2048, 131072
    frac = K * 100.0 / CTX
    warm = 1000 * 16 * CTX / 1e9              # 热身：1000 步 × 16 条 × 128K
    spars = 15000 * 480 * CTX / 1e9           # 稀疏期：15000 步 × 480 条 × 128K
    assert abs(frac - 1.5625) < 1e-6

    f = Fig(W, "凭什么只看 2048 个就够：把它想成查资料 —— 一面十三万本的书墙，"
               "这一次用得上的只有一小格；难的是怎么知道该看谁，那是个鸡生蛋，"
               "DSA 的解法是让真注意力当老师，训一个便宜的小徒弟去模仿它的排序")
    f.marks = set()
    y0 = f.header(
        "凭什么只看 2048 个就够",
        "把它想成<tspan font-weight=\"700\">查资料</tspan>："
        "书墙很长，可这一次真正用得上的只有几本",
        [(GR, "只用一小格"), (RD, "鸡生蛋"), (BL, "让老师教徒弟"),
         (OR, "徒弟凭什么快")])

    # ══════════ ① 一面书墙，只用一小格 ══════════════════════════
    PH = 252
    py = f.panel(0, y0, W, PH, "① 先说一个经验事实 ——　书墙很长，用得上的很少",
                 GR, sub="H2O 2023 量出来的")

    wy = py + 24
    SX, SW, N = 56, 1046, 70
    f.t(SX, wy + 22, "这一步能看到的历史：131,072 个 token", GY, True, 19)
    f.box(SX, wy + 32, SW, 78, BG2, LINE2, 6)
    for i in range(N):
        f.box(SX + 8 + i * 14.7, wy + 40, 10, 62,
              GR if i in (23, 24) else "#dfe3e7", "none", 2)
    f.box(SX + 8 + 23 * 14.7 - 4, wy + 34, 38, 74, "none", GR, 4, 2.2)
    cxx = SX + 8 + 23.5 * 14.7
    f.line(cxx, wy + 118, cxx, wy + 142, GR, 1.6)
    f.t(cxx, wy + 166, "真正用得上的", GR, True, 19, "middle")
    f.t(cxx, wy + 192, "就这么一小格", GR, True, 19, "middle")

    f.box(1136, wy + 32, 224, 160, "#e6f4ea", GR, 10)
    f.t(1248, wy + 80, "2,048 个", GR, True, 26, "middle")
    f.t(1248, wy + 118, "＝ %.2f%%" % frac, GR, True, 24, "middle")
    f.t(1248, wy + 156, "剩下那 98.4%", GY, size=15, anchor="middle")
    f.t(1248, wy + 180, "几乎分不到权重", GY, size=15, anchor="middle")

    # ══════════ ② 鸡生蛋 ＋ 师徒 ════════════════════════════════
    y1 = y0 + PH + 18
    PH2 = 330
    py2 = f.panel(0, y1, W, PH2, "② 难的不是「少看」，是「怎么知道该看谁」",
                  RD, sub="一个鸡生蛋，和 DSA 的解法")

    ey = py2 + 18
    f.box(56, ey + 26, 556, 128, "#fce8e6", RD, 10)
    f.t(80, ey + 62, "要知道哪本书有用 ——　得先把它读了", RD, True, 21)
    f.t(80, ey + 98, "可「每本都读一遍」正是我想省掉的事", GY, size=18)
    f.t(80, ey + 132, "⛔ 又转回来了", RD, True, 20)
    f.path([(592, ey + 60), (634, ey + 90), (592, ey + 120)], RD, 2.0)

    f.t(676, ey + 14, "DSA 的解法：让老师带一个便宜的徒弟", BL, True, 21)
    f.box(676, ey + 26, 296, 128, "#e8f0fe", BL, 10)
    f.t(696, ey + 62, "老师 ＝ 真注意力", BL, True, 20)
    f.t(696, ey + 96, "它当然知道哪本有用", GY, size=16)
    f.t(696, ey + 128, "——　但它贵", GY2, size=15)

    f.line(988, ey + 90, 1040, ey + 90, BL, 1.8)
    f.t(1014, ey + 72, "照着学", BL, True, 16, "middle")

    f.box(1064, ey + 26, 296, 128, "#fff", GR, 10)
    f.t(1084, ey + 62, "徒弟 ＝ 索引器", GR, True, 20)
    f.t(1084, ey + 96, "不需要懂内容", GY, size=16)
    f.t(1084, ey + 128, "只要把书排对顺序", GR, True, 18)

    f.box(56, ey + 176, 1304, 122, "#fff", BL, 10)
    f.t(80, ey + 212, "⭐⭐ 关键是「怎么算徒弟学得像不像」——　"
        "不是让它猜，是<tspan font-weight=\"700\">对着老师的答案打分</tspan>",
        BL, True, 21)
    f.t(80, ey + 248, "热身阶段<tspan font-weight=\"700\">全模型冻住</tspan>、"
        "注意力照常密集地算，只训徒弟去拟合老师那张分布（损失就是 KL）。",
        GY, size=17)
    f.t(80, ey + 282, "热身 %.1fB token　→　稀疏期再训 %.1fB token"
        % (warm, spars), INK, True, 19)

    # ══════════ ③ 徒弟凭什么便宜 ════════════════════════════════
    y2 = y1 + PH2 + 18
    PH3 = 216
    py3 = f.panel(0, y2, W, PH3, "③ 徒弟凭什么便宜 ——　三样减法",
                  OR, sub="它只排序，不做加权平均")

    gy_ = py3 + 20
    for i, (big, small, why) in enumerate([
        ("64 头", "主注意力是 128 头", "人手减一半"),
        ("ReLU 打分", "不用 softmax", "只排序，就不必「和为 1」"),
        ("FP8", "精度更糙", "排序不需要那么准"),
    ]):
        bx = 56 + i * 338
        f.box(bx, gy_ + 18, 306, 130, "#fff", OR, 10)
        f.t(bx + 22, gy_ + 58, big, OR, True, 24)
        f.t(bx + 22, gy_ + 94, small, GY, size=16)
        f.t(bx + 22, gy_ + 128, why, GY2, size=15)

    f.box(1070, gy_ + 18, 290, 130, "#fff", PU, 10)
    f.t(1092, gy_ + 54, "⚠️ 还有一条硬的", PU, True, 19)
    f.t(1092, gy_ + 86, "它必须搭 MQA 模式", PU, True, 19)
    f.t(1092, gy_ + 116, "否则 kernel 上不划算 ——", GY, size=15)
    f.t(1092, gy_ + 140, "旋钮①② 在这儿被硬件绑住了", GY2, size=14)

    # ══════════ 落点 ════════════════════════════════════════════
    yy = y2 + PH3 + 20
    yy = f.band(yy, "info", "⭐ 带走一条套路：要省掉一个贵的东西，先让它自己说出答案", [
        "<tspan font-weight=\"700\">再训一个便宜的去复制那个答案。</tspan>"
        "DSA 的索引器不是「一个猜谁重要的启发式」——&#160;"
        "它是<tspan font-weight=\"700\">主注意力分布的一个廉价复制品</tspan>。",
        "⭐ 这个套路到处都能用：蒸馏、投机解码、各种预测器 ——&#160;"
        "都是「贵的当老师，便宜的当徒弟，拿老师的输出当标准答案」。",
    ])

    yy = f.band(yy + 14, "warn", "那 2048 这个数怎么来的 —— 老实说：论文没给消融", [
        ("能说的只有三件事：① 128K 下它占 <tspan font-weight=\"700\">{0:.2f}%</tspan>；"
         "② 两个公开口径（H2O「前 5%→95%」、Chen「前 20%→70%」）在 1.56% 处"
         "分别给 93% 和 40% ——&#160;<tspan font-weight=\"700\">差一倍多</tspan>；"
         ).format(frac),
        "③ <tspan font-weight=\"700\">历史不足 2048 时，top-2048 就是全选</tspan> ——&#160;"
        "这是定义直接推出来的，所以短上下文下 DSA 就是普通 MLA，"
        "<tspan font-weight=\"700\">稀疏只在长上下文才启动</tspan>。",
        "⚠️ 别把「95% 稀疏」当普适常数 ——&#160;那是 H2O 在它测的那批模型上量的，"
        "Chen 2024 在别的模型上量到「前 20% 只覆盖 70%」。"
        "⭐ <tspan font-weight=\"700\">两个都发表了，两个都对 ——&#160;对的是各自那批模型。</tspan>",
    ])

    yy = f.band(yy + 14, "ok", "暗线第三次出现：事后压 vs 从头按压缩训", [
        "H2O 是<tspan font-weight=\"700\">事后</tspan>的 ——&#160;"
        "一个 KV 驱逐策略，不改训练，随时可开关。",
        "DSA 是<tspan font-weight=\"700\">从头</tspan>的 ——&#160;热身 %.1fB ＋ "
        "稀疏期 <tspan font-weight=\"700\">%.1fB token</tspan> 的继续训练，"
        "模型是在「我会被稀疏」这个前提下学出来的。" % (warm, spars),
        "⭐ 三次了：Eigen Attention 对 MLA、GQA 对 MLA、H2O 对 DSA。"
        "<tspan font-weight=\"700\">同一条暗线，第三个分支。</tspan>",
    ])

    yy = f.src(yy + 16,
               "① 出自 H2O：Zhang 等 arXiv 2306.14048（「over 95% sparse」"
               "与累计注意力分数的幂律分布，均为原文表述）",
               "②③ 出自 DeepSeek-V3.2-Exp 技术报告 §1–§2.1：KL 对齐、冻结主模型热身、"
               "跨头求和后 L1 归一、梯度断开、ReLU「for throughput consideration」、"
               "index_topk=2048、索引器 64 头且跑在 FP8 上",
               "⚠️ 「书墙 / 师徒」是<tspan font-weight=\"700\">本课的比喻</tspan>；"
               "⛔ <tspan font-weight=\"700\">k 的消融论文没有给</tspan> ——&#160;"
               "2048 这个数只能说它占多少、以及短序列下等于全选")
    f.save("fig3-dsa-why.svg", yy + 6)


main()
