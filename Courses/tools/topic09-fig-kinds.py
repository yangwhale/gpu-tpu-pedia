# -*- coding: utf-8 -*-
r"""专题九 · 第五节补的两张图（第二次迁移的新材料）。

fig9-kinds  回答：两边对不上，差有几种？—— 三种：只换了加法顺序（噪声，不修，用尺子兜住）；
            丢了精度（16 位和 32 位的交界、累加怎么分段 —— 大头在这）；语义不同（公式、定义不一样，必须对齐）。
            底下一条：第二次迁移查清的 26 条根因，按本课归类各几条。
            数据：对齐记录的根因一览（alignments 上一级的 ROOT-CAUSES.md）每一行的「根因（边界）」一栏；归类是本课做的。
fig9-embed  回答：TPU 上哪一处最容易真出问题？—— 词嵌入梯度。
            左：机制（推断自编译后的程序）：词嵌入的反向是把每个 token 的梯度散加回它那一行；
                FSDP 下每张卡只管表的一部分列、不用跨卡求和；纯数据并行时每张卡各加一份整表，再在 BF16 里跨卡求和。
            右：第 1 步词嵌入梯度离 CPU FP64 的距离（实测，TPU 自比）。
"""
import math

from topic03_draw import Fig, BL, OR, GR, RD, GY, INK, GY2, LINE, PU
import topic09_numbers as N

W = 1400

# ── 26 条根因的本课归类（对齐记录根因一览，第 1–26 行；括号里是那一行「根因」栏的原标注）──────────────
#   精度：第 2（第 2、4、8、5 类）3（第 7 类）4（第 1 类）10（第 11 类）11（第 13 类）13（第 12、13 类）14（第 13 类）
#         16（编译器省掉的舍入）17（第 11 类）18（第 13 类延伸）19（舍入位置）20（舍入次数）21（第 3 类）22（第 3 类）
#         23（第 10 类）24（第 5 类变体）26（第 7 类）＝ 17 条
#   语义：第 1（设置）7（优化器语义）8（bug，语义）9（语义）12（统计量取法）15（算法边界）25（记录写法）＝ 7 条
#   两样都有：第 5（输出头单遍 BF16 是精度；整层重算重选路由是语义）＝ 1 条
#   顺序：第 6（多路残差四路相加：配对相加 vs 依次相加）＝ 1 条 —— 它也被对上了，但只为「照 GPU」，标对齐专用
KINDS_COUNT = {"精度": 17, "语义": 7, "两样都有": 1, "顺序": 1}
assert sum(KINDS_COUNT.values()) == 26

# ── 词嵌入梯度离 CPU FP64 的 rel_L2（第 1 步，TPU 自比；对齐记录 MATRIX B1、B1d、B1f、C1、E13 与各臂结果文件的 step1_rows）──
EMB = [("GPU（三份中位数）", 4.17e-3, GY2),
       ("TPU 默认：FSDP 8", 4.00e-3, BL),
       ("纯数据并行 8（BF16 跨卡求和）", 1.51e-2, RD),
       ("纯数据并行、不做梯度累积", 2.92e-2, RD),
       ("关掉编译器的省舍入", 1.09e-1, RD),
       ("纯数据并行 ＋ 词嵌入梯度 FP32 累加", 3.79e-3, GR),
       ("FSDP ＋ 词嵌入梯度 FP32 累加", 3.81e-3, GR)]
REF = max(EMB[0][1], EMB[1][1])
assert abs(EMB[2][1] / REF - 3.62) < 0.01 and abs(EMB[4][1] / REF - 26.1) < 0.1 and abs(EMB[3][1] / REF - 7.0) < 0.05


def fig_kinds():
    f = Fig(W, "三张卡片。第一张：只换了加法顺序，两边精度一样，差是噪声，不修，用噪声尺子兜住；认法是离 64 位真值没有变远。"
               "第二张：丢了精度，一个值在 16 位和 32 位之间换挡时一侧多舍了一次，或者长求和没有分段；认法是离真值变远，或者五格表里有一格不同；要修。"
               "第三张：语义不同，两边的公式或定义不一样；认法是读代码对公式；必须对齐。"
               "底下一条横条：第二次迁移查清的 26 条根因，本课归类后精度 17 条、语义 7 条、两样都有 1 条、顺序 1 条。")
    y0 = f.header("两边对不上，差只有三种",
                  "先分清是哪一种，再决定修不修：顺序是噪声，精度要定责，语义必须对齐",
                  [(GY2, "顺序"), (RD, "精度"), (PU, "语义"), (OR, "两样都有")])
    CW, GAP, CH = 448, 28, 330
    cards = [
        (GY2, "① 只换了加法顺序", "a ＋ b ＋ c　vs　a ＋ (b ＋ c)", "精度一样，舍入落在不同的地方",
         ["怎么认：超出噪声，可离 FP64 没变远", "怎么办：不修，噪声尺子兜住"]),
        (RD, "② 丢了精度", "16 → 32 → 16，一侧多舍一次", "或者一次很长的求和没有分段",
         ["怎么认：离 FP64 变远；五格表有一格不同", "怎么办：定责，离真值远的那边修"]),
        (PU, "③ 语义不同", "x ÷ (1 − βᵗ)　vs　x", "两边写的根本不是同一个公式",
         ["怎么认：读代码对公式，差常常很大", "怎么办：必须对齐，参照找不到就不算"]),
    ]
    for k, (col, title, formula, sub, lines) in enumerate(cards):
        x = k * (CW + GAP)
        py = f.panel(x, y0, CW, CH, title, col)
        f.box(x + 24, py + 26, CW - 48, 86, "#fff", col, 8, sw=1.4)
        f.t(x + CW / 2, py + 64, formula, col, True, 17, "middle", mono=True)
        f.t(x + CW / 2, py + 94, sub, GY, size=13, anchor="middle")
        # 小示意：顺序＝两条一样粗的线换位置；精度＝一条线在中间变细；语义＝两条线走不同的路
        gy = py + 160
        if k == 0:
            f.path([(x + 40, gy), (x + 210, gy), (x + 240, gy + 30), (x + 408, gy + 30)], GY, 3, arrow=False)
            f.path([(x + 40, gy + 30), (x + 210, gy + 30), (x + 240, gy), (x + 408, gy)], BL, 3, arrow=False)
        elif k == 1:
            f.line(x + 40, gy + 15, x + 408, gy + 15, GY, 6, arrow=False)
            f.line(x + 40, gy + 45, x + 170, gy + 45, BL, 6, arrow=False)
            f.line(x + 170, gy + 45, x + 270, gy + 45, BL, 1.6, arrow=False)
            f.line(x + 270, gy + 45, x + 408, gy + 45, BL, 6, arrow=False)
            f.t(x + 220, gy + 32, "16 位", RD, True, 13, "middle")
        else:
            f.path([(x + 40, gy + 22), (x + 408, gy + 22)], GY, 3, arrow=False)
            f.path([(x + 40, gy + 22), (x + 150, gy + 22), (x + 240, gy + 58), (x + 408, gy + 58)], BL, 3, arrow=False)
        for i, ln in enumerate(lines):
            f.t(x + 24, py + 250 + i * 26, ln, INK if i else GY, i == 1, 14)
        f._pan = None
    # 底条：26 条根因的归类
    by = y0 + CH + 30
    f.t(0, by + 18, "第二次迁移查清的 26 条根因（本课归类）", INK, True, 15)
    bx, bw = 0, W
    x = bx
    order = [("精度", RD), ("两样都有", OR), ("语义", PU), ("顺序", GY2)]
    for name, col in order:
        n = KINDS_COUNT[name]
        w = bw * n / 26.0
        f.box(x, by + 32, w - 3, 34, col, col, 4)
        f.t(x + w / 2, by + 55, ("%s %d" % (name, n)) if n > 2 else "%d" % n, "#fff", True, 14, "middle")
        x += w
    f.t(W - 4, by + 88, "「两样都有」「顺序」各 1 条", GY, size=13, anchor="end")
    yb = f.band(by + 104, "ok", "差的大头是精度：一个值在 16 位和 32 位之间换挡、一次长求和没分段；顺序只是噪声", [
        "所以排查先分类：离真值没变远就别修；变远了，去五格表里找那一格；公式不一样，先把公式对上。",
        "代价：归类是本课按根因一栏的标注做的，界线上的条目（例如为了照 GPU 才对上的加法顺序）各人可能分得不同。",
    ])
    yb = f.src(yb + 10,
               "📌 第二次迁移的根因一览一共 26 行，每行「根因」一栏都标了它属于哪一类边界或语义；本课据此归成四堆：精度 17（16/32 位交界、矩阵乘精度档、"
               "长求和、超越函数与优化器里的实现精度、编译器省掉的舍入）、语义 7（设置、优化器公式、两处 bug、统计量取法、算法边界、记录写法）、"
               "两样都有 1（输出头单遍 BF16 是精度，整层重算重选路由是语义）、顺序 1（四路相加配对还是依次，对上它只为照 GPU）。",
               "⚠️ 归类是本课做的，对齐记录里没有这四个数。")
    f.save("fig9-kinds.svg", yb + 14)


def fig_embed():
    f = Fig(W, "两块。左块示意词嵌入的反向：每个 token 的梯度要散加回词表里它那一行。FSDP 下每张卡只管表的一部分列，自己加完就是最终结果；"
               "纯数据并行时每张卡各加一份整表，再把八份在 BF16 里跨卡相加，每加一次舍一次。"
               "右块是第 1 步词嵌入梯度离 64 位真值的距离，对数刻度：GPU 4.17e-3，TPU 默认 4.00e-3；纯数据并行 1.51e-2，远 3.6 倍；"
               "不做梯度累积 2.92e-2，7 倍；关掉编译器的省舍入 1.09e-1，26 倍；打开词嵌入梯度 FP32 累加以后回到 3.8e-3。")
    y0 = f.header("TPU 上最容易真出问题的一处：词嵌入梯度",
                  "左：反向怎么算（推断自编译后的程序）；右：第 1 步词嵌入梯度离 CPU FP64 的距离（实测，对数刻度，一格十倍）",
                  [(BL, "TPU 默认"), (RD, "改了以后变远"), (GR, "FP32 累加以后")])
    PH = 400
    LW = 600
    py = f.panel(0, y0, LW, PH, "Ⓐ 一行要加很多次：在哪加、用什么精度加", BL)
    # FSDP：表按列切成 4 份（示意），每张卡只散加自己那几列
    f.t(24, py + 32, "FSDP：每张卡管几列，自己加完就是结果", INK, True, 14)
    for c in range(4):
        x = 30 + c * 66
        f.box(x, py + 46, 60, 100, "#e8f0fe", BL, 4)
        f.t(x + 30, py + 102, "卡%d" % c, BL, True, 13, "middle")
    f.t(310, py + 92, "不用跨卡求和", GR, True, 14)
    f.t(310, py + 116, "融合块里在 FP32 里加", GY, size=13)
    # 纯数据并行：每张卡一份整表，BF16 all-reduce
    y2 = py + 186
    f.t(24, y2, "纯数据并行：每张卡加一份整表，再跨卡相加", INK, True, 14)
    for c in range(4):
        x = 30 + c * 40
        f.box(x, y2 + 14 + c * 6, 120, 70, "#fff", BL, 4)
    f.t(96, y2 + 64, "×8 份", BL, True, 13, "middle")
    f.line(276, y2 + 60, 302, y2 + 60, RD, 2.2)
    f.box(306, y2 + 30, 260, 60, "#fce8e6", RD, 6)
    f.t(436, y2 + 56, "BF16 跨卡求和", RD, True, 15, "middle")
    f.t(436, y2 + 78, "每加一次舍一次", RD, size=13, anchor="middle")
    f.t(24, py + PH - 46, "关掉省舍入：连卡内的散加也每加一次舍一次", RD, True, 14)
    f._pan = None
    RX = LW + 24
    py2 = f.panel(RX, y0, W - RX, PH, "Ⓑ 第 1 步词嵌入梯度离 FP64 多远（实测）", RD)
    lx0, lx1 = RX + 300, W - 90
    lo, hi = 2e-3, 2e-1

    def X(v):
        return lx0 + (math.log10(v) - math.log10(lo)) / (math.log10(hi) - math.log10(lo)) * (lx1 - lx0)
    for v in (3e-3, 1e-2, 3e-2, 1e-1):
        f.line(X(v), py2 + 14, X(v), py2 + PH - 70, LINE, 0.8, arrow=False)
        f.t(X(v), py2 + PH - 50, ("%g" % v), GY, size=13, anchor="middle")
    for i, (lab, v, col) in enumerate(EMB):
        y = py2 + 28 + i * 44
        f.t(lx0 - 12, y + 18, lab, INK if col != GY2 else GY, col in (RD,), 13, "end")
        f.box(lx0, y + 4, X(v) - lx0, 22, col, col, 3)
        ratio = v / REF
        f.t(X(v) + 8, y + 20, ("%.2e" % v).replace("e-0", "e-") + (("　%.1f 倍" % ratio) if ratio > 1.2 else ""), col if col != GY2 else GY, ratio > 1.2, 13)
    f._pan = None
    yb = f.band(y0 + PH + 20, "ok", "词表那一行要被很多 token 加很多次；哪里在 BF16 里加，误差就在哪里攒起来", [
        "修法只有一条：让词嵌入梯度在 FP32 里累加。纯数据并行、关省舍入都回到 GPU 的水平，步时几乎不变。",
        "代价：这个开关原本跟「数据并行 ＋ 梯度累积」撞上一个编译器的真 bug，修掉以后才可用（第十节讲）。",
    ])
    yb = f.src(yb + 10,
               "📌 实测（第二次迁移，小尺寸模型，TPU v5p 自比，第 1 步训练梯度对 CPU FP64 的 rel_L2）：GPU 三份中位数 4.17e-3；TPU golden（FSDP 8，微批 1 × 累积 2）4.00e-3；"
               "纯数据并行 8 1.51e-2（3.6 倍，倍数按 max(golden, GPU) 算）；纯数据并行、每设备微批 2 × 累积 1 2.92e-2（7.0 倍）；关 excess precision 1.09e-1（26 倍）；"
               "纯数据并行 ＋ 词嵌入梯度 FP32 累加（修复后的代码）3.79e-3；FSDP ＋ 同一开关 3.81e-3。其余 204 个张量在纯数据并行时离 FP64 跟 golden 一样近（比值中位数 0.99）。",
               "⚠️ 左块的机制是从编译后程序里张量的形状和算子推断的：FSDP 时每张卡上的词嵌入表是 [词表, 隐藏维 ÷ 8]，没有这份梯度的跨卡求和；"
               "纯数据并行时是整表，梯度在累积循环里每个微批做一次 BF16 加法的 all-reduce。卡数、列数画成 4 是示意。")
    f.save("fig9-embed.svg", yb + 14)


fig_kinds()
fig_embed()
