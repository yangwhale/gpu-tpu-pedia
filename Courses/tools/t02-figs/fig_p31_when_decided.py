"""图 P-31 —— GPU 那六层，每一层是「什么时候」定下来的。

**这张图是来还债的。** 3.3 的小节标题写着「哪几层是运行时才定的」，
可原来那两张图<b>一张都没标出来</b> —— G-3 讲的是每层钉在哪块硅上，
T-3 讲的是 TPU 有哪两行是空的。承诺了运行时／编译期这条轴，却没画。
讲课时只能口头补，文档里的人看不到。

**画之前先拆一个混在一起的问题。** 「这一层什么时候定的」其实是<b>两个问题</b>：
① 这一组是<b>怎么划出来的</b>；② 它<b>什么时候落到硬件上、谁挑它执行</b>。
不拆开就会得出「GPU 全是运行时」这种错结论 —— 实际上<b>划分六行全是「开跑之前就定死」</b>，
一行例外都没有。<b>注意这里不能写成「编译期」</b>：block/grid 的大小是主机启动时
传进来的参数，完全可以是运行时算出来的；只有 thread 到 lane、32 个打一包这类
才真是硬件写死的规则。两者的共同点是<b>芯片自己不在运行时决定</b>。真正留到运行时的只有两个决定，而且性质完全不同：
<b>一个只在启动那一下发生一次，另一个每个时钟周期都在发生。</b>

**这张图的落点是把那两个决定和上一节的硬件对上。** 上一节说 TPU 核里少了五样东西
（warp 调度器、记分板、几十份常驻上下文……），这里给出它们存在的唯一理由：
<b>它们全部是为了第二个决定服务的。</b>决定没了，部件就同时失去存在理由 ——
这才是 3.2 和 3.3 是同一件事的第二个视角。

**⚠️ 出处口径。** 「block 落到哪个 SM 由硬件决定、程序员指定不了、块间执行顺序
不作保证」「warp 调度器每周期从驻留 warp 里挑一个能发的」都是 CUDA 编程模型的
公开说法。而<b>「运行时只剩两个决定」这个归纳是我从表里读出来的</b>，
不是谁的原话 —— 底带写明了。
"""
from common import Fig, para, BL, GN, RD, YL, PU, TL, INK, SUB, GREY, FILL

W = 1400

AX_Y, AX_H = 84, 100                        # ① 先拆开那个混在一起的问题
TB_Y, TB_H = AX_Y + AX_H + 22, 396          # ② 六层 × 两个问题
SUM_Y, SUM_H = TB_Y + TB_H + 22, 150        # ③ 运行时只剩两个决定
TPU_Y, TPU_H = SUM_Y + SUM_H + 22, 112      # ④ TPU：两个都没有
SRC_Y, SRC_H = TPU_Y + TPU_H + 22, 100      # ⑤ 出处
H = SRC_Y + SRC_H + 20

# 表格几何
C0_X, C0_W = 34, 206
C1_X, C1_W = 250, 480
C2_X, C2_W = 742, 622
HDR_H, ROW_H = 34, 50

# 三档时机。**颜色就是全图的语法**，别改：
#   绿 = 开跑之前就定死  ·  橙 = 启动那一下定一次  ·  红 = 每个时钟周期都在定
# ⚠️ 绿**不等于「编译期」**。block/grid 的大小是主机启动时给的参数，完全可以是
#    运行时算出来的；只有 thread 到 lane、32 个打一包这类才是硬件写死的规则。
#    两者的共同点是**芯片自己不在运行时决定**，这才是绿色真正的含义。
FIXED, LAUNCH, CYCLE = GN, YL, RD

# 六行。每行：层名、英文、划分（时机, 文案）、落地/挑选（时机, 文案）
LAYERS = [
    ("线程", "thread", (FIXED, "<b>硬件写死的规则</b>：线程号到 lane 的对应是算出来的，不由谁分配"),
     (FIXED, "<g>不单独调度</g> —— 它跟着自己所在的 warp 走，没有自己的命运")),
    ("warp", "warp", (FIXED, "<b>硬件写死的规则</b>：连号的 32 个线程打成一包，改不了"),
     (CYCLE, "<b>每个时钟周期都在挑</b>：调度器从驻留的几十个 warp 里，"
             "挑一个<b>数据已经到位</b>的发射出去")),
    ("warp 组", "warpgroup", (FIXED, "<b>硬件写死的规则</b>：连号的 4 个 warp，Hopper 起给矩阵指令用"),
     (FIXED, "<g>不单独调度</g> —— 跟着组成它的那几个 warp")),
    ("线程块", "block / CTA", (FIXED, "<b>启动参数给定</b>：一块多少线程由主机传进来，<b>跑起来就不再变</b>"),
     (LAUNCH, "<b>启动那一下，硬件分发器挑一个 SM 放进去</b> —— "
              "<b>程序员指定不了</b>，落下之后也不迁走")),
    ("cluster", "thread block cluster", (FIXED, "<b>启动参数给定</b>：簇里几块由主机传进来，之后不变"),
     (LAUNCH, "启动时，硬件在<b>同一个 GPC 里</b>挑出那几个 SM")),
    ("grid", "grid", (FIXED, "<b>启动参数给定</b>：一共几块由主机传进来，之后不变"),
     (LAUNCH, "启动时铺开。<b>块与块之间的先后顺序，规范里明说不作保证</b>")),
]


def build():
    f = Fig(W, H, "GPU 六层并行抽象里，分组方式在核跑起来之前就全部定死；"
                  "真正留到运行时的只有两个决定：启动时把块放到哪个 SM，"
                  "以及每个周期挑哪个 warp 发射")
    f.title("那六层，到底<tspan font-weight=\"700\">什么时候</tspan>定下来"
            "　—— 划分全在开跑之前，<tspan font-weight=\"700\">运行时只剩两个决定</tspan>")
    f.legend([(FIXED, "开跑之前就定死"), (LAUNCH, "启动那一下定一次"),
              (CYCLE, "每个时钟周期都在定")])
    _axis(f)
    _table(f)
    _summary(f)
    _tpu(f)
    _src(f)
    return f.out()


# ══════════════════════════════════════════════════════════════════════
# 不拆这一步，后面整张表都会读错 —— 「什么时候定」其实问的是两件事。
def _axis(f):
    f.rect(20, AX_Y, 1360, AX_H, FILL[BL], BL, 1.6, 10)
    f.t(38, AX_Y + 26, "🔍 先把「什么时候定的」拆成两个问题 —— 混着问一定得出错结论",
        "sec", BL)
    y = para(f, 38, AX_Y + 50, 1324,
             "<b>问题一：这一组是怎么划出来的？</b>（谁跟谁算一组）　　"
             "<b>问题二：它什么时候落到硬件上、谁挑它执行？</b>（这一组什么时候真的开跑）", "xs", 18)
    para(f, 38, y + 2, 1324,
         "混着问，会得出「GPU 反正都是运行时」这种印象。<r>拆开看完全不是</r> —— "
         "<b>问题一在下表里六行全是绿的</b>：要么是硬件写死的规则，"
         "要么是启动前主机给定的参数 —— <b>没有一行是芯片在运行时自己决定的</b>。", "xs", 18)


# ══════════════════════════════════════════════════════════════════════
def _table(f):
    f.rect(20, TB_Y, 1360, TB_H, "#fff", GREY, 1.6, 10)

    hy = TB_Y + 44
    f.t(38, TB_Y + 26, "📋 六层 × 两个问题　（底色＝时机）", "sec")
    f.rect(C0_X, hy, 1380 - 20 - C0_X, HDR_H, FILL[GREY], None, 0, 4)
    f.t(C0_X + 12, hy + 22, "这一层", "box", SUB)
    f.t(C1_X + 12, hy + 22, "① 这一组是怎么划出来的", "box", SUB)
    f.t(C2_X + 12, hy + 22, "② 什么时候落到硬件上 · 谁挑它执行", "box", SUB)

    y = hy + HDR_H + 4
    for name, en, (c1, s1), (c2, s2) in LAYERS:
        f.t(C0_X + 12, y + 22, name, "box", INK)
        f.t(C0_X + 12, y + 38, en, "xxs", GREY)
        for x, w, c, s in ((C1_X, C1_W, c1, s1), (C2_X, C2_W, c2, s2)):
            f.rect(x, y + 4, w, ROW_H - 10, FILL[c], c, 1.0, 5)
            # ⚠️ max_lines=2 是硬约束：行高固定 50，第三行会压到下一行去。
            #    改文案时先在这儿数一遍，别指望渲染出来能看出来 —— 它不报错。
            para(f, x + 10, y + 22, w - 20, s, "xs", 16, max_lines=2)
        f.line(C0_X, y + ROW_H, 1360, y + ROW_H, "#eef0f2", 1.0)
        y += ROW_H


# ══════════════════════════════════════════════════════════════════════
# 全图的落点：把两个决定和「上一节少掉的那批部件」钉在一起。
CARDS = [
    (LAUNCH, "决定一　·　这个块放哪个 SM", "启动时，一次",
     "整个 kernel 启动的时候发生一次，之后这块就钉在那儿不动了。",
     "代价很小：<b>一个工作分发器，加上每个 SM 的一本资源账</b>（还剩多少寄存器、"
     "多少共享内存）。<g>频率低，硬件不必为它常备什么。</g>"
     "<b>顺带解释一件事</b>：CUDA 里没有「把这块放到 3 号 SM」这种写法 —— "
     "<b>不是漏了，是这层抽象故意不交给你</b>。"),
    (CYCLE, "决定二　·　下一拍发哪个 warp", "每个周期，永不停",
     "只要核在跑，这个决定<b>每个时钟周期都要做一次</b>，而且要在一拍之内做完。",
     "<r>代价是全部：</r>要<b>记分板</b>盯着谁的数据到了，要<b>几十个 warp 槽</b>让人排队，"
     "要<b>所有上下文常驻在寄存器里</b>不能换出 —— <b>不然「立刻切一个」就无从谈起。</b>"),
]


def _summary(f):
    for i, (c, ttl, tag, a, b) in enumerate(CARDS):
        x, w = 20 + i * 692, 668
        f.rect(x, SUM_Y, w, SUM_H, FILL[c], c, 1.6, 9)
        f.t(x + 16, SUM_Y + 26, ttl, "box", c)
        f.t(x + w - 16, SUM_Y + 26, tag, "xxs", SUB, anchor="end")
        y = para(f, x + 16, SUM_Y + 52, w - 32, a, "xs", 18)
        f.line(x + 16, y + 6, x + w - 16, y + 6, c, 0.8, dash="3 3")
        para(f, x + 16, y + 26, w - 32, b, "xs", 18)


# ══════════════════════════════════════════════════════════════════════
