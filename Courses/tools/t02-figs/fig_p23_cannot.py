# ══════════════════════════════════════════════════════════════════════
def _axis(f):
    """一条横贯的箭头，把四堆变成一条轴：越往右越不是靠多干活能补的。"""
    f.line(X0 + 40, AXIS_Y, W - X0 - 40, AXIS_Y, GREY, 2.0, "aK")
    f.rect(W // 2 - 232, AXIS_Y - 11, 464, 22, "#fff", None, 0, 4)
    f.t(W // 2, AXIS_Y + 4,
        "越往右，越不是「多干点活」就能补上的", "xs", SUB, "middle")


def _col(f, x, cat):
    ttl, c, how, note, items = cat
    body = "#f1f3f4" if c == GREY else FILL[c]
    edge = c

    f.rect(x, R1_Y, CW, R1_H, "#fff", LINE, 1.2, 10)
    f.rect(x, R1_Y, CW, HDR, body, None, 0, 10)
    f.rect(x, R1_Y + HDR - 10, CW, 10, body, None, 0, 0)
    f.rect(x, R1_Y, 5, R1_H, edge, None, 0, 3)
    f.line(x, R1_Y + HDR, x + CW, R1_Y + HDR, LINE, 1.2)

    f.t(x + 18, R1_Y + 24, ttl, "box", INK if c == GREY else c)
    f.t(x + 18, R1_Y + 44, how, "lbl", INK if c == GREY else c)
    f.t(x + 18, R1_Y + 61, note, "xxs", SUB)

    y = R1_Y + HDR + 8
    for name, ref, first in items:
        _item(f, x, y, name, ref, first, c)
        y += IH


def _item(f, x, y, name, ref, first, c):
    """一条 = 条目 + 出处徽章。三种状态整格换底，不能只换个字：
       first=False 课件上承认过 · first=None 只在备忘里 · first=True 从来没想到。"""
    fc = {True: FILL[RD], None: FILL[YL]}.get(first, "#fcfcfd")
    sc = {True: RD, None: YL}.get(first, LINE)
    f.rect(x + 12, y, CW - 24, IH - 10, fc, sc, 1.6 if first is not False else 1.1, 8)

    yy = para(f, x + 24, y + 19, CW - 48, name, "lbl", 15)

    cc = {True: RD, None: YL}.get(first, GREY if c == GREY else c)
    # 中日韩字宽 ≈ 字号，拉丁 ≈ 0.55 字号。一律按 8.2 算会让「只在备忘里 · 课件没写」
    # 这种全中文标签**撑出框外**（上一版就是这么溢出的），所以按字符类别分开估。
    wid = sum(11.0 if ord(ch) > 0x2E80 else 5.9 for ch in ref) + 16
    f.rect(x + 24, yy + 5, min(wid, CW - 48), 19,
           FILL[cc] if cc != GREY else "#f1f3f4", cc, 1.1, 4)
    f.t(x + 32, yy + 18, ref, "xxs", cc if cc != GREY else SUB)


