"""图 P-18 —— 六条不能拿这个倍数说的话，外加一条兜底。

这一格原来是 P-17 的丙格。拆出来是因为讲课流程本身要求它独立：
**先只放 P-17，问一句「你觉得这个倍数还缺什么」，等台下自己说出几条，
再放这一张。** 一张静态图做不到分段揭示 —— 这是拆图唯一的、也是充分的理由。

拆开之后腾出的空间做了两件原来做不了的事：

  ① 边界从四条扩到六条 —— 补上**互联拓扑**和**软件成熟度**，
     这两条恰恰是台下最可能站起来说的，原来一条都没接住
  ② 每条都标出**它把倍数往哪边推**

⭐ **第 ② 件事是这张图真正的设计。** 一张只列「注意事项」的清单是防守性的，
读者会当成免责声明跳过去。**一旦每条都标了方向，它就变成一张可以做加减法的表** ——
读者能自己数：六条里四条利于 GB300、两条利于 v7。
**那个 1.31 倍因此有了一个方向，而不只是一个警告。**

⚠️ **每条方向都必须能查，标错方向比不标更糟。** 逐条的依据：

  ① batch —— GB300 2,048 对 v7 等效 1,536（问②：4,096 对 1,408，差 2.9 倍）。
     大 batch 摊薄固定开销 → 利于 GB300。
     但要写清：**v7 的 pdbs 是被 94.74 GiB 顶住的，不是被让的** ——
     所以这一条本身就是一种硬件差异，不是纯粹的口径偏置。
  ② 拓扑与规模 —— 64 个单元时 GB300 全在**一个 NVL72 域内**（域内无距离），
     v7 是 4x4x4 环面（对角要绕好几跳）。而跑的是 192 专家 MoE + EP32，
     吃的正是 all-to-all —— **第 4 节整节论证的就是 all-to-all 是唯一在两种
     拓扑上表现分岔的原语**，而且第 4 节的核心论点是 TPU 的价值在 72 颗以外。
     **换句话说，64 这个规模是 GPU 的主场。** → 利于 GB300
  ③ 重算策略 —— GB300 侧 `--recompute-granularity none`，重算**全关**
     （吃到 230 GB / 288 GB）；v7 侧 `remat_policy=custom` + offload
     （91.94 / 94.74 GiB）。**这不是同一件事**，两边的图脚都写「不落盘 checkpoint」
     很容易被读成重算策略也一样。 → 利于 GB300
  ④ 软件成熟度 —— P-16 乙格讲过，但那张图会被单独截走，**边界清单里必须也有一条**。
     整节结论是「差距和软件有关」，那么「软件会变」就是这个结论最重要的边界。
     → 利于 GB300，且**随时间变**
  ⑤ 频率档 —— v7 的 662.3 含 `dvfs_p_state=7`，单独值 +8.6%，
     第 6 节的口径认为它属于硬件工作点不是调优。GB300 侧没动过等价旋钮。
     → **利于 v7**（这是我们自己的数，主动写出来）
  ⑥ 每芯片 vs 每 GPU —— v7 一颗 chip 是 **2 个 device**，GB300 一张卡是 1 个。
     按 device 比就是「1 颗 v7 die 对 1 整张 GB300」，v7 更吃亏。
     **所以本课选的「每芯片对每 GPU」已经是 v7 能拿到的最好口径。**
     → 利于 v7
     （⚠️ 别顺手写「两边 die 数相等」：本课只考据过 B200 是双 die 封装，
       **没有考据过 GB300 用的 B300**，不要把 B200 的结论套过去。）

⚠️ **兜底那一条为什么不给方向。** 「只有一个模型、一个规模」不是偏置，
是**适用范围**。但第 7 节正文承诺过「三张图之后你会发现它是硬约束」，
所以底带不能只是把这句话重说一遍 —— 它得**演示这个倍数会怎么动**。
用的是第 4 节自己给出的预测：**过了 72 颗，GB300 一侧要跨出 NVLink 域，
而 v7 的环面继续线性延伸** —— 这一节测的 64，正好停在分岔点之前。

数据出处：全部同 P-15 / P-16 / P-17；重算策略见两边各自的启动参数，
GB300 侧 `sweep.sh` 的 V4 基准行，v7 侧快速上手文档 §4.1 完整参数集。
"""
