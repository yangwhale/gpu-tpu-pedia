# -*- coding: utf-8 -*-
"""图 P-8 —— 静态化之后，账单长什么样：三笔钱，和一个不会过期的比例。

上一张图说清了「为什么难」，这一张说「难在哪、多难」。
**没有这一张，上一张就只是个哲学论断。**

选这三笔而不是别的，是因为它们的**复发周期各不相同** ——
一次性支出叫成本，**周期性支出才叫账单**，这是整个比喻的唯一支点。
所以周期写进了三个格子的**标题**里，不放在最后的落点带里：
组织原则出现在被组织的内容之后，等于没有组织原则。

  ① 编译时间   —— **每次启动**都付
  ② 缓存那 16 次 —— **在上游修好之前，每次启动白付**，缓存盘做得再持久也救不回来
  ③ 调参表     —— **每多一个组合付一次**，而组合是五个维度的乘积

排序的轴是**「谁能替你把它减掉」**：缓存能减掉一半 → 上游修好第二笔就消失 →
第三笔**没人能替你做**。所以它压轴，而且它是三笔里唯一**不可约**的一笔。

**最该被带走的是第三笔那个比例。** 编译分钟数明年换代就变，
`4147 ÷ 1926 = 2.15` 这个比值不会 —— 它量的正是
「复杂度流到人手上之后有多重」。所以它上了图标题。

三笔都不会出现在任何一张「TPU 支持 vLLM 吗」的对照表里 ——
**对照表回答的是能不能，账单回答的是要多少。**

第二笔额外挂着一条方法论：查缓存命中时，最顺手的那个字符串**确实是 0**，
于是人会得到一个虚假的安心。**这是「空结果不等于没有」在这门课里的第二次出现**
（第一次在第 4 节，我们拿一个走错路的对照项去证明链路够用）。
「查了一盏不会亮的灯，然后把没亮当成没问题」是本节最容易被复述出去的一句，
所以它被提到了落点带，跟主结论平起平坐 —— 第一版把它压在最窄那格底部的
26 px 窄条里，用 10 px 字，那是把最好的一句话藏起来。

⚠️ 数字来源：`tpu/vllm-torchtpu/QUICKSTART.md`（时间与缓存）和同目录
`README.md`（行数）。**不是 runlog** —— 第一版图例写成「两份 runlog」，是错的。
"""
from common import Fig, para, BL, RD, GN, YL, PU, INK, SUB, LINE, GREY, FILL

W = 1400
TOP = 84

R1_Y = TOP + 40
R1_H = 340
AX, AW = 20, 796
BX, BW = 836, 544

R2_Y = R1_Y + R1_H + 30
R2_H = 258

BAND_Y = R2_Y + R2_H + 30
H = BAND_Y + 152

# ── 甲：时间轴 ──────────────────────────────────────────────────
# 画成时间轴而不是柱状图，是因为要说的不是「哪个久」，
# 是「加起来还剩不剩得下一次实验」—— 那是一条**长度**的事，不是高度。
PX0 = AX + 138
PXW = AW - 138 - 40
MINS = 66.0


def _mx(m):
    return PX0 + PXW * m / MINS


# 窗口到底多长，**我们自己的文档里有三个读数**：正文多处写 60 分钟，
# 另有两处写 55，还有一处按 29＋24 隐含 53。所以这里不画一条线，画一条**灰带**。
# 第一版在 55 画了条硬线，让冷启动「差 42 秒跑不完」—— 那个 42 秒是我画出来的，
# 不是量出来的。源文档说的「差一点点」指的是 2 分 42 秒。
WIN_LO, WIN_HI = 53.0, 60.0

CELL = 26.7            # 一个 benchmark cell：26 分 42 秒
COLD_PREP, WARM_PREP = 29.0, 18.0
TO_READY = 19.0        # 397B「编译到 server ready」

# ── 乙：缓存 ────────────────────────────────────────────────────
PROBE = [
    ("最顺手的那个判据", "Compiling a graph for compile range",
     "0", GREY, "看起来全命中"),
    ("真正该查的那个", "Compiling model again",
     "16", RD, "读不回来，退化成重编"),
]

# ── 丙：调参表 ──────────────────────────────────────────────────
# 颜色不是装饰：第 3 节已经把 蓝＝编译器能自动做 / 紫＝只能人来做 定死了。
# 调参表是全课最纯粹的「只能人来做」，所以整格走紫，只有 kernel.py 留蓝。
# 第一版整格是蓝的 —— 等于说这活儿编译器能帮忙，正好说反。
LINES = [("kernel.py　　　　算法本身　<g>（编译器打交道的对象）</g>", 1926, BL),
         ("tuned_block_sizes.py　v3 的调参表", 4147, PU),
         ("tuned_block_sizes.py　v2 的那份　<g>—— 上一代芯片的表，一行都不能复用</g>", 1493, PU)]
LMAX = 4400

NEST = ["芯片代", "page size", "q／kv 精度组合", "head 配置", "上下文长度"]


def build():
    f = Fig(W, H, "静态形状带来的三笔实测成本：每次启动的编译时间、缓存读不回来导致的重复编译、"
                  "以及按五个维度穷举的 block size 调参表，其中调参表是算法本身的 2.15 倍")
    f.title("静态化之后，账单长什么样　—— <tspan font-weight=\"700\" fill=\"#d93025\">"
            "三笔钱，和一个不会过期的比例 2.15×</tspan>")
    # legend 只留真正的颜色键。「数字出处」是脚注，不是色卡 —— 放右下角。
    f.legend([(RD, "还要付的"), (GREY, "已经省掉的"), (PU, "只能人来做（沿用第 3 节的约定）")])

    _timeline(f)
    _cache(f)
    _tuning(f)
    _band(f)
    f.t(W - 20, H - 12,
        "数字出处：tpu/vllm-torchtpu/ 的 QUICKSTART.md（时间、缓存）与 README.md（行数）",
        "xxs", GREY, "end")
    return f.out()


# ══════════════════════════════════════════════════════════════════════
def _timeline(f):
    f.rect(AX, R1_Y, AW, R1_H, FILL[RD], RD, 1.4, 10)
    f.t(AX + 18, R1_Y + 26,
        "第一笔　·　编译时间　<tspan font-weight=\"700\" fill=\"#d93025\">【每次启动付】</tspan>"
        "　—— 它不是「等一会儿」，是「这次实验做不做得成」", "sec")
    para(f, AX + 18, R1_Y + 46, AW - 36,
         "<g>Qwen3.5-397B-A17B-FP8，v7 4 芯片。跑完一个 benchmark cell 要 26 分 42 秒，"
         "而机器有使用时间窗口。</g>"
         "<r>这个窗口多长，我们自己文档里有三个读数（53 ／ 55 ／ 60）</r>—— "
         "<b>所以下面画的是一条带，不是一条线。</b>"
         "<g>　讲了一路的「先问口径」，我们自己也没能幸免。</g>", "xs")

    # ── 窗口画成灰带，不画硬线 ──────────────────────────────────
    # 「我们自己的文档里，这个数有三个读数」本身就是这门课要讲的东西，
    # 所以它必须是可见的宽度，不能被我挑一个数糊过去。
    gy, gh = R1_Y + 70, 132
    f.rect(_mx(WIN_LO), gy, _mx(WIN_HI) - _mx(WIN_LO), gh, "#eceff1", None, 0, 0)
    f.line(_mx(WIN_LO), gy, _mx(WIN_LO), gy + gh, GREY, 1.2, dash="5 4")
    f.line(_mx(WIN_HI), gy, _mx(WIN_HI), gy + gh, GREY, 1.2, dash="5 4")
    f.t((_mx(WIN_LO) + _mx(WIN_HI)) / 2, gy - 8, "使用窗口 53～60", "lbl", INK, "middle")

    for i, (name, prep, split, note) in enumerate([
            ("冷启动", COLD_PREP, TO_READY,
             "19 ＋ 10 ＋ 26′42″ ＝ <r>55′42″ —— 落在灰带里，"
             "「跑不跑得完」取决于你信哪个读数</r>"),
            ("热启动", WARM_PREP, None,
             "<g>（编译缓存已就位）</g>18 ＋ 26′42″ ＝ <b>44′42″，三个读数都塞得进</b>")]):
        y = R1_Y + 92 + i * 58

        f.t(AX + 18, y + 20, name, "box", INK)
        if split:
            # 拆成两段，是为了让「缓存削掉的是哪一段」有个可指的东西，
            # 顺手也把台下必然会做的那道减法（29 − 19 = ?）当场补平。
            f.rect(_mx(0), y, _mx(split) - _mx(0), 28, RD, None, 0, 5)
            f.t(_mx(split / 2), y + 19, "编译到 server ready 19 分", "lbl", "#fff", "middle")
            f.rect(_mx(split), y, _mx(prep) - _mx(split), 28, GREY, None, 0, 5)
            f.t(_mx((split + prep) / 2), y + 19, "其余 10 分", "xxs", "#fff", "middle")
        else:
            f.rect(_mx(0), y, _mx(prep) - _mx(0), 28, GREY, None, 0, 5)
            f.t(_mx(prep / 2), y + 19, "准备 18 分　·　这一段我们没拆", "lbl", "#fff", "middle")

        # cell 那一段原来是白底实心框，**把窗口虚线整段盖住了** ——
        # 这张图唯一想让人看见的那个交点，恰好是被自己的图元糊掉的。
        # 现在改 fill="none"，灰带从底下透出来。
        c = RD if split else GN
        f.rect(_mx(prep), y, _mx(prep + CELL) - _mx(prep), 28, "none", c, 1.4, 5)
        f.t(_mx(prep + CELL / 2), y + 19, "跑一个 cell", "lbl", c, "middle")

        para(f, AX + 18, y + 46, AW - 46, note, "xs")

    for m in (0, 15, 30, 45, 60):                     # 刻度
        f.line(_mx(m), R1_Y + 206, _mx(m), R1_Y + 211, GREY, 1)
        f.t(_mx(m), R1_Y + 225, "%d 分" % m, "xxs", SUB, "middle")

    f.rect(AX + 18, R1_Y + 246, AW - 36, 82, "#fff", RD, 1.2, 8)
    y = para(f, AX + 32, R1_Y + 266, AW - 64,
             "<b>「编译到 server ready」：0.6B 约 7 分 ／ 35B 约 15 分 ／ 397B 19 分。</b>"
             "<b>增长比想象中温和</b> —— 397B 只比 35B 多 4 分钟，"
             "<r>但「温和」不等于「不要紧」</r>：要紧的是它落在窗口的哪一边。", "xs", 17)
    # 台下一定会拿 18 去减 10。与其让他自己算出个洞，不如当场把洞指出来。
    para(f, AX + 32, y + 3, AW - 64,
         "<g>顺带一个我们答不上来的：热启动那 18 分，比冷启动扣掉编译后剩的 10 分还多 8 分钟。"
         "第二笔那 16 次重编是头号嫌疑 —— <b>但没量过就是没量过。</b></g>", "xs", 17)


# ══════════════════════════════════════════════════════════════════════
def _cache(f):
    f.rect(BX, R1_Y, BW, R1_H, FILL[YL], YL, 1.4, 10)
    f.t(BX + 18, R1_Y + 26,
        "第二笔　·　缓存救不全　<tspan font-weight=\"700\" fill=\"#d93025\">"
        "【修好之前每次白付】</tspan>", "sec")
    para(f, BX + 18, R1_Y + 48, BW - 36,
         "把编译产物放持久盘之后，<b>88 个正常读回</b>；"
         "另有 <r>16 次读不回来、退化成重新编译</r>。"
         "<g>8 个 worker 各中招 2 次 —— 4 芯片 ＝ 8 个 device，一个 worker 一个。</g>", "xs", 17)

    y = R1_Y + 120
    for lbl, needle, val, c, verdict in PROBE:
        f.rect(BX + 18, y, BW - 36, 62, "#fff", c, 1.2, 7)
        f.t(BX + 32, y + 20, lbl, "lbl", INK)
        f.t(BX + 32, y + 39, needle, "mono", c)
        f.t(BX + BW - 32, y + 22, val, "numb", c, "end")
        # 这两行结论原来是 10 px。common.py 自己注释着 10 px「投影到大屏基本读不出来」，
        # 而它们恰恰是这一格的判决书。升到 12 px 加粗。
        f.t(BX + BW - 32, y + 52, verdict, "lbl", c, "end")
        y += 70

    f.rect(BX + 18, R1_Y + 266, BW - 36, 28, "#fff", YL, 1.2, 6)
    para(f, BX + 30, R1_Y + 284, BW - 60,
         "<b>这是个 bug，不是设计如此</b> —— 上游修好它就消失。"
         "<g>（值多少分钟，我们没量）</g>", "xs")


# ══════════════════════════════════════════════════════════════════════
def _tuning(f):
    f.rect(20, R2_Y, 1360, R2_H, FILL[PU], PU, 1.4, 10)
    f.t(38, R2_Y + 26,
        "第三笔　·　调参表　<tspan font-weight=\"700\" fill=\"#d93025\">【每多一个组合付一次】</tspan>"
        "　—— 写 kernel 只是一半工作，另一半是<tspan font-weight=\"700\" fill=\"#8430ce\">"
        "按五个维度穷举</tspan>", "sec")
    para(f, 38, R2_Y + 48, 1324,
         "<g>取样：<code>ragged_paged_attention/v3/</code> 这一个目录 —— "
         "kernel 目录里最大的一块（10,744 行）。</g>", "xs")

    # 左：行数条形。**长度按行数等比**，否则这张图的论点（表比代码长）就不成立
    bx, bw0 = 60, 470
    for i, (name, n, c) in enumerate(LINES):
        y = R2_Y + 78 + i * 46
        para(f, bx, y + 13, 560, name, "lbl", 15, INK)
        f.rect(bx, y + 20, bw0 * n / LMAX, 18, c, None, 0, 4)
        f.t(bx + bw0 * n / LMAX + 10, y + 34, "%s 行" % format(n, ","), "num", c)

    para(f, bx, R2_Y + 226, 640,
         "<r>算法只有 1,926 行，配套的调参表 4,147 行 —— 是它的 2.15 倍。</r>"
         "<b>三笔里唯一不会过期的就是这个比值。</b>", "xs")

    # 右：五层嵌套 → 两个数
    nx = 700
    f.t(nx, R2_Y + 90, "那 4,147 行是一张五层嵌套的表：", "lbl", INK)
    cw = 118
    for i, k in enumerate(NEST):
        x = nx + i * (cw + 10)
        f.rect(x, R2_Y + 102, cw, 40, "#fff", PU, 1.2, 7)
        para(f, x + 8, R2_Y + 120, cw - 16, "<b>%s</b>" % k, "xs", 14)
        if i < len(NEST) - 1:
            f.line(x + cw + 1, R2_Y + 122, x + cw + 8, R2_Y + 122, PU, 1.3, "aP")

    # 「芯片代」那一维不是抽象的：左边 v2 那根柱子就是它的实证。
    # 不说这一句，v2 就只是一根没有理由的柱子 —— 典型的「作者知道，听众不知道」。
    f.t(nx + cw / 2, R2_Y + 158, "（左边 v2 那根柱子，就是这一维的实证）", "xxs", PU, "middle")

    f.line(nx + 2.5 * (cw + 10), R2_Y + 146, nx + 2.5 * (cw + 10), R2_Y + 172, PU, 1.4, "aP")
    f.rect(nx, R2_Y + 174, 5 * cw + 4 * 10, 34, "#fff", RD, 1.4, 7)
    para(f, nx + 12, R2_Y + 195, 5 * cw + 4 * 10 - 24,
         "⇒ 两个数：<code>num_kv_pages_per_block</code> · <code>num_queries_per_block</code>",
         "xs")
    para(f, nx, R2_Y + 226, 640,
         "<r>任何一维变了都要重调，而且没人能替你做。</r>"
         "<b>估「支持一个新模型要多久」的时候，这个比例得直接算进排期。</b>", "xs")


# ══════════════════════════════════════════════════════════════════════
def _band(f):
    f.rect(20, BAND_Y, 1360, 124, FILL[BL], BL, 1.4, 10)
    f.t(38, BAND_Y + 28, "两句话", "sec")
    y = BAND_Y + 54
    for seg in [
            "<r>这三笔，一笔都不会出现在任何一张「TPU 支持 vLLM 吗」的对照表里。</r>"
            "<b>对照表回答的是「能不能」，账单回答的是「要多少」</b> —— "
            "评估一条移植路线的时候，<b>后者才是你真正要签字的那个数</b>。",
            "<r>⚠️ 而查账本身也会骗人：</r>"
            "<b>查了一盏不会亮的灯，然后把「没亮」当成「没问题」。</b>"
            "<g>（这门课第二次遇到它 —— 第 4 节我们拿一个走错路的对照项，"
            "证明了链路够用。）</g>"]:
        y = para(f, 38, y, 1324, seg, "xs", 19) + 4


if __name__ == "__main__":
    import sys
    open(sys.argv[1] if len(sys.argv) > 1 else "out/fig_p8_statictax.svg",
         "w", encoding="utf-8").write(build())
