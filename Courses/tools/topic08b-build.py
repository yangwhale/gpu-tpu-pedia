def _banned_hits(text):
    hits = set()
    for n in sorted({n for _h, n in _BANNED}):
        want = {h for h, k in _BANNED if k == n}
        for k in range(len(text) - n + 1):
            if hashlib.sha256(text[k:k + n].encode("utf-8")).hexdigest()[:12] in want:
                hits.add(text[k:k + n])
    return hits


