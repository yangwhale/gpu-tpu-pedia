# -*- coding: utf-8 -*-
"""图 P-28 —— 数据到底怎么搬：不是一条总线轮流用，是几条各自 128 宽的通路。

**这张图是被一个具体的误解逼出来的，而那个误解非常合理。** 讲完 P-27
（一套 vreg、三个门）之后，最自然的下一个问题是：那它们是不是全都串在
那 128 条 lane 上、时分复用、大家商量好谁开谁关？——**一半对，一半错，
而错的那一半会把后面所有关于「什么时候会卡」的判断都带偏。**

对的那一半：<b>确实有争用，确实要排</b>。
错的那一半：<b>争的不是一条共享总线，是端口和发射位</b>；而且
<b>「商量」发生在编译期，芯片上没有仲裁器</b>。

所以这张图分三步走：先把「总线模型」和「端口模型」并排画出来正面对掉；
再把四个单元各自的接法摊开（它们不一样，而且不一样的原因各不相同）；
最后落到那条分水岭上 —— 撞车不存在，因为它在编译期就被消灭了。

**⚠️ 出处口径。** 端口那个数（约 9 读 7 写）是<b>我从公开资料里两个数推的，
不是原话</b>，图上把推导链写出来了。真实硬件通常靠分体省端口，
公开资料没说怎么分 —— 这条也写在图上，不要略掉。
"""
from common import Fig, para, BL, GN, RD, YL, PU, TL, INK, SUB, GREY, FILL

W = 1400

MOD_Y, MOD_H = 84, 246          # ① 总线模型 vs 端口模型
BAD_X, BAD_W = 20, 604
GOOD_X, GOOD_W = 656, 724

DRV_Y, DRV_H = MOD_Y + MOD_H + 22, 96      # ② 端口预算的推导
WAY_Y, WAY_H = DRV_Y + DRV_H + 22, 250     # ③ 四种接法
LAND_Y, LAND_H = WAY_Y + WAY_H + 22, 112   # ④ 落点
H = LAND_Y + LAND_H + 20

# 四种接法。每张卡必须回答同一组问题，读者才能横着对比：
# 走不走横向、延不延迟、要不要队列、为什么要队列。
# 「要不要队列」这一栏是全图的机关 —— 三个单元都有队列，理由两两不同。
WAYS = [
    (GN, "VPU　·　逐元素", "就地", [
        ("横向？", "不需要，lane 内自己算自己"),
        ("延迟", "约 2 周期"),
        ("队列", "<g>不用</g>"),
    ], "最短的一条路：从 vreg 出来，进本 lane 的 ALU，回 vreg。"
       "全程没离开那一竖条。<b>逐元素算子便宜，真正的原因就是"
       "它一步都没有出去。</b>"),
    (PU, "超越函数单元", "竖着，但深", [
        ("横向？", "不需要，也是 lane 内"),
        ("延迟", "<r>几十周期</r>，流水线深"),
        ("队列", "<b>要</b>　←　因为<b>慢</b>"),
    ], "exp、rsqrt 这类。它跟 VPU 一样是竖着接的，"
       "<b>但不能占着发射位干等</b>：推进去，先干别的，好了再捞。"),
    (TL, "XLU　·　跨 lane", "横着，且共享", [
        ("横向？", "<r>要</r>，这是唯一横着走的门"),
        ("延迟", "<r>几十周期</r> ＋ <r>排队</r>"),
        ("队列", "<b>要</b>　←　因为<b>共享</b>"),
    ], "全核只有一两个，谁都得从这儿过。"
       "<r>贵的是「出一趟再回来」这个往返，不是那一次加法。</r>"),
    (RD, "MXU　·　矩阵乘", "喂不满，要攒", [
        ("横向？", "阵列自带，不占 XLU"),
        ("延迟", "攒够了才乘一次"),
        ("队列", "<b>要</b>　←　进料和出料<b>都要</b>"),
    ], "一次运算是 <b>8×128 乘 128×128</b>。左边那个正好是一个 vreg，"
       "可<b>权重那一侧有 128 行，一个 vreg 只给得出 8 行</b> —— "
       "<b>差 16 倍</b>，只能分好多趟送。"),
]


def build():
    f = Fig(W, H, "TPU 核内的数据搬运：不是所有部件挂在一条 128 位总线上时分复用，"
                  "而是寄存器堆开出有限条各自 128 宽的端口")
    f.title("数据到底怎么搬　—— <tspan font-weight=\"700\">128 是每条通路的宽度，"
            "不是一条总线的车道数</tspan>")
    f.legend([(GREY, "① 常见的错模型：共享总线"), (PU, "② 实际：端口"),
              (GN, "lane 内"), (TL, "跨 lane"), (RD, "攒够才算")])
    _bad(f)
    _good(f)
    _derive(f)
    for i, args in enumerate(WAYS):
        _way(f, i, *args)
    _land(f)
    return f.out()


# ══════════════════════════════════════════════════════════════════════
# 左panel：把读者脑子里那张图**原样画出来**，再打叉。
# 只写一句「不是总线」没有用 —— 得让他看见自己想的是什么。
def _bad(f):
    f.rect(BAD_X, MOD_Y, BAD_W, MOD_H, FILL[GREY], GREY, 1.4, 10, dash="5 4")
    f.t(BAD_X + 18, MOD_Y + 28, "❌ 很自然、但不对的那张图：一条总线，大家挂上面",
        "sec", SUB)

    # 一条粗横线，所有人并联挂上去 —— 经典的 party-line 总线
    by = MOD_Y + 108
    f.line(BAD_X + 30, by, BAD_X + BAD_W - 30, by, GREY, 7.0)
    f.t(BAD_X + BAD_W - 30, by - 12, "「128 条车道」", "xxs", SUB, anchor="end")

    hangs = [(0, "vreg 0", PU), (1, "vreg 1", PU), (2, "…共 64", PU),
             (3, "VPU", GN), (4, "MXU", RD)]
    for i, name, c in hangs:
        x = BAD_X + 52 + i * 104
        f.line(x + 38, by, x + 38, by - 34, GREY, 1.6)
        f.rect(x, by - 62, 76, 28, "#fff", GREY, 1.2, 5)
        f.t(x + 38, by - 43, name, "xxs", SUB, anchor="middle")

    y = para(f, BAD_X + 18, by + 30, BAD_W - 36,
             "这张图会推出两个结论：<b>同一周期只能有一个人说话</b>，"
             "而且<b>芯片上得有个仲裁器在现场协调谁开谁关</b>。", "xs", 18)
    y = para(f, BAD_X + 18, y + 4, BAD_W - 36,
             "<r>两个结论都不成立。</r>寄存器堆从来不是这么接的 —— "
             "它开的是<b>端口</b>，不是挂总线。", "xs", 18)
    para(f, BAD_X + 18, y + 6, BAD_W - 36,
         "这张图之所以看着对，是因为「128」这个数确实到处都在。"
         "<b>但它在每一处都是「宽度」，不是「份额」</b> —— "
         "没有谁需要从这 128 里分一块走。", "xs", 18)


# ══════════════════════════════════════════════════════════════════════
# 右panel：端口模型。每条通路画成一条「带子」，里面三根细线暗示它本身就宽。
def _good(f):
    f.rect(GOOD_X, MOD_Y, GOOD_W, MOD_H, FILL[PU], PU, 1.8, 10)
    f.t(GOOD_X + 18, MOD_Y + 28, "✅ 实际：一个寄存器堆，开出有限条端口", "sec", PU)

    # 左边的 vreg 堆
    rx, ry, rw, rh = GOOD_X + 20, MOD_Y + 48, 118, 168
    f.rect(rx, ry, rw, rh, "#fff", PU, 1.8, 8)
    f.t(rx + rw / 2, ry + 26, "vreg 堆", "box", PU, anchor="middle")
    f.t(rx + rw / 2, ry + 46, "64 个", "xxs", SUB, anchor="middle")
    for i in range(6):
        f.rect(rx + 18, ry + 60 + i * 17, rw - 36, 12, FILL[PU], PU, 0.7, 2)

    # 四条端口带子
    ports = [(GN, 0, "读口", "→ VPU"), (GN, 1, "读口", "→ VPU"),
             (TL, 2, "写口", "← 结果回填"), (BL, 3, "装填口", "← 便签本")]
    px = rx + rw + 8
    pw = 214
    for c, i, kind, dst in ports:
        y = ry + 8 + i * 40
        f.rect(px, y, pw, 20, FILL[c], c, 1.2, 4)
        for k in range(3):
            f.line(px + 6, y + 5 + k * 5, px + pw - 6, y + 5 + k * 5, c, 0.7)
        f.t(px + pw + 8, y + 14, kind, "xxs", c)
        f.t(px + pw + 52, y + 14, dst, "xxs", SUB)

    para(f, GOOD_X + 18, ry + rh + 16, GOOD_W - 36,
         "<b>每一条端口本身就是 128 lane 宽</b> —— 128 不是要分给大家用的车道，"
         "<b>它是每条通路的宽度</b>。真正有限的是<b>端口有几条</b>。"
         "<g>（端口具体是什么线、为什么加不起 —— P-30 拆开画。）</g>", "xs", 18)


# ══════════════════════════════════════════════════════════════════════
def _derive(f):
    f.rect(20, DRV_Y, 1360, DRV_H, FILL[YL], YL, 1.6, 10)
    f.t(38, DRV_Y + 26, "🔢 那到底有几条？公开资料没直说 —— 但给了能推的两个数", "sec")
    y = para(f, 38, DRV_Y + 50, 1324,
             "① 每周期发 <b>4 条</b>向量指令，每条<b>吃 2 个 vreg、写 1 个</b>　→　"
             "读 8、写 4。　　② 每周期从便签本<b>装 3 个</b> vreg、<b>写回 1 个</b>　→　"
             "再加写 3、读 1。　　<b>合计约 9 读、7 写。</b>", "xs", 18)
    para(f, 38, y + 2, 1324,
         "<r>⚠️ 这是推的，不是原话</r> —— 两个乘数都出自公开资料，加法是我做的。"
         "而且真实硬件常靠<b>分体</b>省端口，具体怎么分公开资料没说。", "xxs", 17)


# ══════════════════════════════════════════════════════════════════════
def _way(f, i, c, ttl, tag, rows, foot):
    x, w = 20 + i * 344, 326
    f.rect(x, WAY_Y, w, WAY_H, FILL[c], c, 1.4, 9)
    f.t(x + 14, WAY_Y + 24, ttl, "box", c)
    f.t(x + w - 14, WAY_Y + 24, tag, "xxs", SUB, anchor="end")

    y = WAY_Y + 44
    for k, v in rows:
        f.t(x + 14, y + 12, k, "xxs", SUB)
        para(f, x + 74, y + 12, w - 88, v, "xs", 16)
        y += 30
    f.line(x + 14, y + 2, x + w - 14, y + 2, c, 0.8, dash="3 3")
    para(f, x + 14, y + 22, w - 28, foot, "xs", 17)


# ══════════════════════════════════════════════════════════════════════
def _land(f):
    f.rect(20, LAND_Y, 1360, LAND_H, FILL[BL], BL, 1.8, 10)
    f.t(38, LAND_Y + 28, "⭐ 那「撞车」呢？—— 它不存在，因为它在编译期就被消灭了",
        "sec", BL)
    y = para(f, 38, LAND_Y + 54, 1324,
             "TPU 是 <b>VLIW</b>：一个指令包里，<b>每类操作有几个固定的位置</b>，"
             "编译器往里填。填不下就多排一个周期。"
             "<b>芯片上没有一个运行时的仲裁器在现场商量谁先走</b> —— "
             "冲突不是被解决的，是被<b>提前排掉、根本没机会发生</b>。", "xs", 19)
    para(f, 38, y + 2, 1324,
         "<r>GPU 正相反：靠运行时的记分板和 warp 调度器现场决定。</r>"
         "这就是这门课一直在回的那条分水岭 —— <b>谁在运行时挑活。</b>", "xs", 19)


if __name__ == "__main__":
    import io
    io.open("out/fig_p28_ports.svg", "w", encoding="utf-8").write(build())
    print("ok fig_p28_ports")
