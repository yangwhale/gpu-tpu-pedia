def _sched():
    """「一小时怎么分」那张表 —— 时间轴由 min 累加算出来，不手写。

    可跳过的那一讲（opt）时间打括号，但**仍然占用时间轴** —— 表读的是
    「全都讲」的情况。跳过之后是多少，由 _sched_total() 另算一句写在表下面，
    免得读者自己减。
    """
    rows, t = [], 0
    for L in LEC:
        a, t = t, t + L["min"]
        span = ("（%d–%d）" % (a, t)) if L["opt"] else ("%d–%d" % (a, t))
        rows.append('      <tr><td>%s</td><td>%s</td><td>%s</td></tr>'
                    % (span, L["what"], L["land"]))
    return "\n".join(rows)


