def build():
    f = Fig(W, H, "六条不能拿 1.31 倍这个结论说的话，每条都标出它把倍数"
                  "往哪一边推：四条利于 GB300，两条利于 TPU v7")
    f.title("不能拿它说的话　—— <tspan font-weight=\"700\" fill=\"#d93025\">"
            "六条，每条都标出它往哪边推</tspan>")
    f.legend([(RD, "这一条把倍数推高（利于 GB300）· 共 4 条"),
              (GN, "这一条把倍数压低（利于 TPU v7）· 共 2 条"),
              (GREY, "底带那条没有方向 —— 它是适用范围，不是偏置")])

    _cards(f)
    _band(f)
    f.t(W - 20, H - 12,
        "这一张是 P-17 的续页 —— P-17 问「这个倍数还缺什么」，这一张是答案",
        "xxs", GREY, "end")
    return f.out()


# ══════════════════════════════════════════════════════════════════════
def _cards(f):
    for i, (num, name, dirn, dc, c, body) in enumerate(CAV):
        x = 20 + (i % 3) * (CW + 14)
        y = R1_Y + (i // 3) * (CH + 16)
        f.rect(x, y, CW, CH, "#fff", c, 1.6, 9)

        f.rect(x, y, CW, 30, FILL[c], c, 1.4, 9)
        f.rect(x, y + 20, CW, 10, FILL[c], None, 0, 0)
        f.t(x + 14, y + 21, num, "box", c)
        f.t(x + 36, y + 21, name, "lbl", INK)

        # 方向 chip —— 这张图的核心设计。宽度按字宽估，CJK 10px / ASCII 5.6px
        txt = "→ " + dirn
        cw2 = 26 + sum(10.0 if ord(ch) > 0x2000 else 5.6 for ch in txt)
        f.rect(x + CW - cw2 - 12, y + 40, cw2, 22, FILL[dc], dc, 1.4, 11)
        f.t(x + CW - cw2 / 2 - 12, y + 55, txt, "xxs", dc, "middle")

        para(f, x + 14, y + 78, CW - 28, body, "xxs", 14)


