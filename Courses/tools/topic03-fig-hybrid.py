# -*- coding: utf-8 -*-
r"""专题三 · §八「混合：配比是一条轴，而两头都不好」

⭐⭐⭐ 2026-09-13 **整张重画**，换成一个带过团队的人都懂的画面：
   **一个组里，几个普通员工配一个资深。**

   · **便宜的层** ＝ 普通员工：只看手边那块记事板，反应快、便宜，
     但**查不了全部档案**。
   · **贵的层** ＝ 资深：**能翻全部历史**，什么都查得到，但慢、占地方。

   ① **两头都不好**：全是资深 → 贵得离谱，而且 ⭐ **消融里它居然还不是最好的**；
      全是普通员工 → 长了就兜不住（§二 那条 L2M 条件说的是**状态必须变大**）。
   ② **配比是一条轴**，各家落在哪，**一个模型一个点**堆在对数轴上 ——&nbsp;
      ⭐⭐ 最有意思的两件事：**最高的一摞在 3:1（十四家占五家）**，
      而 **1:1 上那两个清一色是滑窗族 ——&nbsp;线性混合最省也从 3:1 起步。**
   ③ **为什么资深不用配很多** ——&nbsp;因为他查到的东西
      **会顺着流程传给后面所有人**，不用每个人自己去查一遍。
"""
import math

from topic03_draw import (Fig, BL, OR, GR, RD, GY, PU, INK, GY2, LINE, LINE2,
                          BG2, wpx)

W = 1400


def main():
    f = Fig(W, "混合：把一层层想成一个组 —— 几个普通员工配一个资深。"
               "全是资深贵得离谱而且消融里还不是最好，全是普通员工长了兜不住；"
               "十四家的配比画成点阵，最高的一摞在三比一共五家，没有一家超过七比一，"
               "一比一上那两家都是滑窗族，线性混合最省也从三比一起步")
    f.marks = set()
    y0 = f.header(
        "混合 ——　几个普通员工，配一个资深",
        "<tspan font-weight=\"700\">便宜的层</tspan> ＝ 只看手边记事板的普通员工；"
        "<tspan font-weight=\"700\">贵的层</tspan> ＝ 能翻全部档案的资深",
        [(GR, "普通员工"), (BL, "资深"), (RD, "两头都不好"),
         (PU, "② 格：线性混合（旋钮③那一支）"),
         (OR, "② 格：滑窗 / 局部混合（旋钮②那一支）")])

    # ══════════ ① 两头都不好 ════════════════════════════════════
    PH = 350
    py = f.panel(0, y0, W, PH, "① 为什么不能只用一种人", RD,
                 sub="两头都试过，两头都不好")

    ay = py + 24

    def team(x, n_cheap, n_pro, col, title, good, bad):
        f.box(x, ay + 26, 420, 200, "#fff", col, 10)
        f.t(x + 24, ay + 64, title, col, True, 23)
        for i in range(n_cheap):
            f.box(x + 24 + i * 46, ay + 84, 36, 44, "#e6f4ea", GR, 6)
            f.t(x + 42 + i * 46, ay + 112, "普", GR, True, 17, "middle")
        for i in range(n_pro):
            f.box(x + 24 + (n_cheap + i) * 46, ay + 84, 36, 44, "#e8f0fe",
                  BL, 6)
            f.t(x + 42 + (n_cheap + i) * 46, ay + 112, "资", BL, True, 17,
                "middle")
        f.t(x + 24, ay + 162, good, GY, size=17, w=376)
        f.t(x + 24, ay + 196, bad, RD, True, 17, w=376)

    # ⚠️ 2026-09-14 R41：这句原来是「⛔ 贵得离谱 ——　而且消融里它还不是最好的」，
    #   量准字宽之后才发现它超出 376px 的框 2 个像素 ——&#160;⛔ 和 —— 两个字符
    #   在旧的宽度表里都被当成 0.55 个字宽，少算了将近 20px。破折号本身
    #   已经有「而且」的意思，删掉两个字比放宽框干净。
    team(56, 0, 8, RD, "全是资深", "什么都查得到",
         "⛔ 贵得离谱 ——　消融里它还不是最好的")
    team(500, 8, 0, RD, "全是普通员工", "又快又省",
         "⛔ 一长就兜不住：板子大小是固定的")
    team(944, 6, 2, GR, "混着用", "大部分人快，少数几个能查全部",
         "✅ 今天所有人的选择")

    f.t(56, ay + 258, "⭐⭐ 左边那个结果最反直觉：Kimi 的消融里 "
        "<tspan font-weight=\"700\">0:1（全是资深）反而表现不好</tspan> ——&#160;"
        "⚠️ 原文只有这一句定性描述，没公开数值", INK, True, 17)
    f.t(56, ay + 286, "如果混合只是「拿便宜的换点钱」，那全用贵的应该最好才对。"
        "它不是 ——&#160;说明<tspan font-weight=\"700\">加便宜层不只是省钱</tspan>。",
        GY, size=17)

    # ══════════ ② 配比轴 ════════════════════════════════════════
    y1 = y0 + PH + 18
    PH2 = 408
    py2 = f.panel(0, y1, W, PH2, "② 那到底几个配一个 ——　各家都落在哪",
                  GR, sub="横轴：便宜层 : 贵层（对数刻度）·　一个点 ＝ 一个模型")

    # ⭐ 轴的位置由**点阵的高度**倒推，不是拍的：最高那摞 5 个点，
    #   每点间距 DY，轴要留在它们下面。改了 DY 或来了新模型，这里跟着走。
    RD_, DY = 9, 25
    by = py2 + 36 + 4 * DY + 30
    ax0, ax1 = 120, W - 120

    def at(k):
        return ax0 + (ax1 - ax0) * math.log(k) / math.log(8.0)

    # ⛔ 轴线**必须画在建议区间那块底色之后** ——&#160;底色是一个实心矩形，
    #   先画轴后画它，轴会被那一段盖掉（原来底色只能停在轴线上，就是为了躲这个）。
    #   现在底色要一路铺到两条区间条下面，顺序就得反过来。

    # ══════════════════════════════════════════════════════════════
    # ⭐⭐⭐ R48（2026-09-14）：这一格原来是**一根轴 ＋ 一张名单**。
    #
    # ⛔⛔ 最重的一条：**颜色看着像在编码什么，其实什么都不编码。**
    #   原来五个刻度分别给了 OR / GR / GR / OR / BL 三种颜色，
    #   而这三种颜色跟「这些模型属于哪一族」毫无关系 ——&#160;纯粹是为了相邻两个
    #   不同色。读者会去猜那个颜色的含义，猜不出来，然后**不再相信这张图的配色**。
    #   （同型：R2-D「三张图的编码在反驳自己」。）
    #
    # ⛔ 第二条：**刻度不承载「有几个模型」。** 3:1 上站着 5 个模型、
    #   6:1 上只有 1 个，而两个刻度画得一模一样大。于是落点带那句
    #   「大家都在哪」——&#160;一句**关于分布的话**——&#160;在图上完全没有对应物，
    #   读者只能回去读那张名单，自己在脑子里数。
    #
    # ⭐ 改法：**把名单立起来变成点阵**。一个模型一个点，按配比堆在轴上方；
    #   颜色改成编码**唯一真正成立的那个分组**：便宜的那层是线性，还是滑窗/局部。
    #   于是三件事同时变成看得见的：
    #     ① 哪个配比人最多（3:1 那摞最高）
    #     ② 两端空着（轴的头尾各 1/8 一个点都没有）
    #     ③ 两族在中段重叠（紫、橙两条区间条的交叠段）
    #
    # ⚠️⚠️ **家族归属不是我分的，是从课程自己已经核过的地方取的。**
    #   §8.4 各家速查表逐家写了拧的是哪个旋钮：Qwen3.5 / Kimi Linear / K3 /
    #   GLM-5.3F / Ling-3.0-flash / Ling 2.6 / MiniMax-01 都是 ③ 线性，
    #   小米那两款是 ② 稀疏（SWA，窗口 128）。表里没列的五个
    #   （Gemma 2 / gpt-oss-120b / Gemma 3/4 / Llama 4 Scout / Jamba）
    #   由落点带自己那句「线性混合 3:1 / 5:1 / 7:1、滑窗混合 1:1 / 3:1 / 5:1 / 6:1」
    #   唯一确定：3:1 上那个滑窗的只能是 Scout，7:1 上三个都得是线性族。
    #   ⛔ 这是**课程内部两处已有断言的交集**，不是我另外查来的新事实 ——
    #     所以图上标的是「按 §8.4」，没有另立出处。
    # ══════════════════════════════════════════════════════════════
    LIN, SWA = "线性", "滑窗 / 局部"
    MODELS = [                               # (配比, 型号, 族)
        (1, "Gemma 2",        SWA), (1, "gpt-oss-120b",   SWA),
        (3, "Kimi Linear",    LIN), (3, "Kimi K3",        LIN),
        (3, "Qwen3.5",        LIN), (3, "GLM-5.3F",       LIN),
        (3, "Llama 4 Scout",  SWA),
        (5, "Ling-3.0-flash", LIN), (5, "MiMo-V2-Flash",  SWA),
        (5, "Gemma 3/4",      SWA),
        (6, "MiMo-V2.5-Pro",  SWA),
        (7, "Ling 2.6",       LIN), (7, "MiniMax-01",     LIN),
        (7, "Jamba",          LIN),
    ]
    # ⛔⛔ 2026-09-15 R10：线性族原来用 GR ——&#160;可 GR 在这张图的**顶部图例里
    #   已经被「普通员工（便宜层）」占了**。于是同一张图里绿色有两个意思：
    #   格① 绿＝便宜层，格② 绿＝线性混合那一族，而图例只声明了前一个。
    #   ⭐ 改成 PU，理由不是「随便换个没用过的色」，是**回到全课的调色板**：
    #     PU ＝ 旋钮③（换回一个固定大小的状态）＝ 线性这一支；
    #     OR ＝ 旋钮② （每步只读一部分）＝ 滑窗／局部这一支 —— 橙本来就是对的。
    #   ⛔ 判据：一张图里一个颜色只能有一个意思；要分配新颜色，
    #     先去全课调色板里找它本来该是什么，别就近挑一个空的。
    FCOL = {LIN: PU, SWA: OR}
    # ⭐ 这两组区间是**从上面这张表算出来的**，不是手写的 ——
    #   手写的区间会跟表悄悄走散（本课在 §8.2 正文上栽过一次）。
    SPAN = {fam: (min(k for k, _, g in MODELS if g == fam),
                  max(k for k, _, g in MODELS if g == fam))
            for fam in (LIN, SWA)}
    assert SPAN[LIN] == (3, 7) and SPAN[SWA] == (1, 6), SPAN
    OVL = (max(SPAN[LIN][0], SPAN[SWA][0]), min(SPAN[LIN][1], SPAN[SWA][1]))
    assert OVL == (3, 6), OVL          # 落点带里写的就是这个区间
    assert len(MODELS) == 14

    # ⛔⛔ 2026-09-14 R48 第二刀：**落点带那句话原来是假的，而图刚把它戳穿。**
    #   原文写「两端各 1/8 的区间里，一个模型都没有」。可这条轴是 1:1 → 8:1：
    #   左端 1:1 上明明站着两个点，右端最近的 7:1 上站着三个 ——
    #   **一句关于分布的话，被同一格里的分布图当场证伪。**
    #   它多半是从更早那版（轴的量程不同）沿用下来的，没人回头核。
    #   ⭐ 教训跟 §8.4 那次同型：**图改了口径，跟着图走的句子必须重新算。**
    #     所以下面这几个数现在全部从 MODELS 推，并各自配一条 assert ——
    #     表一动、句子对不上了，build 当场炸，而不是继续印一句假话。
    CNT = {k: sum(1 for kk, _, _ in MODELS if kk == k)
           for k in {k for k, _, _ in MODELS}}
    TOPK = max(CNT, key=lambda k: CNT[k])
    assert (TOPK, CNT[TOPK]) == (3, 5), CNT          # 最密的一摞
    assert max(CNT) == 7, CNT                        # 右边确实到 7:1 为止
    LOW = min(CNT)
    assert LOW == 1, CNT
    # ⭐ 真正新看见的一条：最左那一摞**清一色橙**（滑窗 / 局部），
    #   而线性族最省也要 3:1 起步 ——&#160;这是 SPAN[LIN][0] == 3 的另一种说法，
    #   两条互为交叉验证。
    assert {g for k, _, g in MODELS if k == LOW} == {SWA}, MODELS
    assert SPAN[LIN][0] > LOW

    # ⭐⭐ 消融建议的区间（论文给的）**和两族实际重叠的区间（这张表算出来的）
    #   是同一段**。课程原来两处各说各的，从没把它们放在一起 ——
    #   合成一条竖带画一次，比画两个几乎重合的标记清楚，也才看得出这件事。
    #   ⛔ 但只说「一样」，不说「所以是因果」：一个是消融扫出来的建议，
    #     一个是各家各自选的结果，重合值得注意，不等于谁导致谁。
    ADV = (3, 6)                             # arXiv 2507.06457 的建议区间
    assert OVL == ADV, (OVL, ADV)            # 不一样了就别再说「正好也是这一段」

    # ── 竖带：建议区间罩住整片点阵 ────────────────────────────────
    # ⭐ 左右各外扩一个点的半径 ——&#160;不外扩的话，端点上那个点会被边线
    #   从正中切开，看着像「一半在区间里一半在外面」。
    # ⭐⭐ R48 第三刀：这块底色原来只罩到轴线为止，于是
    #   「两条区间条正好停在建议区间的左右两个边上」这件事 ——&#160;
    #   本格最值得看的一件事 ——&#160;**只写在落点带的文字里，图上看不出来**。
    #   现在把它一路铺到两条区间条下面，变成一根**贯穿的竖列**：
    #   紫条的左端、橙条的右端，就压在这根列的两条边上，不用讲，眼睛自己会对上。
    PAD = RD_ + 6
    BOT = by + 92 + 30 + 12               # 铺到第二条区间条再往下一点
    f.box(at(ADV[0]) - PAD, py2 + 26,
          at(ADV[1]) - at(ADV[0]) + 2 * PAD, BOT - py2 - 26,
          "#e6f4ea", "none", 6)
    f.t((at(ADV[0]) + at(ADV[1])) / 2.0, py2 + 20,
        "消融建议区间 %d:1 ～ %d:1" % ADV, GR, True, 17, "middle")

    # 轴线压在底色之上（顺序原因见上面那段注）
    f.line(ax0, by, ax1, by, GY2, 1.6, arrow=False)
    f.t(ax1, by + 22, "8 : 1", GY2, size=15, anchor="end")

    # ── 点阵：一个模型一个点，按配比往上堆 ────────────────────────
    stack = {}
    for k, name, fam in MODELS:
        i = stack.get(k, 0)
        stack[k] = i + 1
        f.box(at(k) - RD_, by - 22 - i * DY, RD_ * 2, RD_ * 2,
              FCOL[fam], FCOL[fam], RD_)
    assert max(stack.values()) == 5 and stack[3] == 5, stack   # 最高那摞是 3:1
    assert sum(stack.values()) == len(MODELS)

    for k in sorted(stack):
        f.t(at(k), by + 44, "%d : 1" % k, INK, True, 19, "middle")
        f.t(at(k), by + 64, "%d 个" % stack[k], GY2, size=14, anchor="middle")

    # ── 两族各自的跨度：重叠段是它俩自己长出来的 ─────────────────
    # ⛔⛔ 族标签原来画在条的**左端再往左 14px**、anchor="end"。
    #   「滑窗 / 局部混合」这一条从 at(1)=120 起，标签就跑到了 **x 为负**——
    #   **往左跑出画布，截图上只是「少了半截字」，几何探针也看不见**
    #   （memory: feedback_left-overflow-is-invisible-to-probes）。
    # ⭐ 改成固定左栏 x=16 起排，两行对齐，顺便条的起点也就不受标签长短牵制。
    # ⭐ 底色那块为了不切开端点上的点，左右各外扩了 PAD ——&#160;于是它的边
    #   跟 at(3) / at(6) **差了 15px**，「条正好停在边上」就变成了「差不多」。
    #   在区间条这一带补两条**真边线**（不含外扩），紫条左端、橙条右端压在上面。
    #   ⛔ 只画在这一带：再往上就会从「3 : 1」「6 : 1」两个刻度标的正中穿过去。
    for kk in ADV:
        f.line(at(kk), by + 78, at(kk), BOT, GR, 1.2, dash="3 4", arrow=False)

    LBX, LBW = 16, 150
    for r, fam in enumerate((LIN, SWA)):
        a, b = SPAN[fam]
        sy_ = by + 92 + r * 30
        lab = "%s混合" % fam
        f.line(at(a), sy_, at(b), sy_, FCOL[fam], 5.0, arrow=False)
        for xx in (at(a), at(b)):
            f.line(xx, sy_ - 7, xx, sy_ + 7, FCOL[fam], 2.0, arrow=False)
        # ⚠️ 标签只能挂在**右端**：滑窗那条从 at(1)=120 起，
        #   左边根本放不下 119px 的「滑窗 / 局部混合」——&#160;这就是它
        #   原来会跑到画布外面去的原因，放宽间距救不了，得换边。
        assert at(b) + 14 + wpx(lab, 16) < W - 16, (lab, at(b))
        f.t(at(b) + 14, sy_ + 6, lab, FCOL[fam], True, 16)
    _ovl = "⭐ 两族实际重叠的，正好也是这一段 ——　而它不是从建议区间推出来的，是各家自己选出来的"
    assert LBX + wpx(_ovl, 16) < W - 16, wpx(_ovl, 16)
    f.t(LBX, by + 152, _ovl, BL, True, 16)

    # ── 名单：按族分两行，颜色跟点一致 ───────────────────────────
    ly = by + 182
    NX = LBX + LBW
    for fam in (LIN, SWA):
        who = " · ".join(n for _, n, g in MODELS if g == fam)
        lab = "%s混合" % fam
        assert wpx(lab, 16) < LBW - 8, wpx(lab, 16)
        assert NX + wpx(who, 16) < W - 16, wpx(who, 16)
        f.t(LBX, ly, lab, FCOL[fam], True, 16)
        f.t(NX, ly, who, GY, size=16)
        ly += 26

    # ══════════ ③ 资深不用配很多 ════════════════════════════════
    y2 = y1 + PH2 + 18
    PH3 = 268
    py3 = f.panel(0, y2, W, PH3, "③ 为什么资深不用配很多", BL,
                  sub="他查到的东西会往下传")

    ey = py3 + 24
    for i in range(8):
        x = 96 + i * 158
        pro = (i == 2)
        f.box(x, ey + 40, 110, 70, "#e8f0fe" if pro else "#e6f4ea",
              BL if pro else GR, 8)
        f.t(x + 55, ey + 74, "资深" if pro else "普通", BL if pro else GR,
            True, 19, "middle")
        f.t(x + 55, ey + 100, "第 %d 层" % (i + 1), GY2, size=13,
            anchor="middle")
        if i < 7:
            f.line(x + 112, ey + 75, x + 152, ey + 75, GY2, 1.4)
    f.line(206, ey + 34, 1310, ey + 34, BL, 2.0)
    f.t(700, ey + 22, "他查到的结果，顺着残差流传给后面每一层", BL, True, 17,
        "middle")

    f.box(96, ey + 136, 600, 104, "#e8f0fe", BL, 10)
    f.t(120, ey + 174, "⭐ 只要有几层能「查全部档案」", BL, True, 21)
    f.t(120, ey + 210, "后面的人直接用他的结论就行 ——　不用每层自己查一遍", GY,
        size=17)

