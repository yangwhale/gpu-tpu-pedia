"""图 P-16 —— 两条调优路径，和一个不能比的起点。

P-15 摆了两个终点值，并且承认它拆不动那 1.19 倍。
**这一张才是「差距在软件」的唯一直接实验证据** ——
因为它展示的是同一块硅片上，什么都没换、只改软件，涨了多少。

  甲　两条爬升曲线画在同一根纵轴上（0 起，不截断）
  乙　起点不是同一种东西 —— ③ 档真正贵的地方

⭐ **这一格的重量在甲格那条 v7 曲线上，而不在两条线的高低对比上。**
457 → 662.3 是**同一批机器、同一个规模、同一个模型**，硬件一颗没换，
纯靠编译器 tile、batch、频率档、参数注入方式，涨了 **44.9%**。
按第 6 节的口径把频率档那一步剥掉（它是硬件工作点不是调优），仍有 **+33.4%**。
**这个数是一个真实验，不是一个恒等式的余项。**

**为什么纵轴从 0 起。** 把轴截到 400–900 能让两条线的起伏好看得多，
但这一节整节在讲「怎么让一个数字经得起回查」，
**在这里偷一次视觉放大，后面所有话都白说了。**

⛔ **这张图返工过一次，改的是它最醒目的那个元素。**

第一版在绘图区正中放了一个红框：「**v7 六步爬完 662.3，仍比 GB300 一行没调时低 6.3%**」，
并为它画了全图唯一一条红色参考线。审到第二轮才看清问题：
**这张图用自己最重的视觉元素，做了自己另一半格子判定为无效的那个比较。**
乙格明说「两条线的起点性质不同，这个比较从第一步就不成立」——
可红色永远先被看到，同屏不抵消，**先看到的赢**。

现在红框换成 v7 那条纯软件涨幅（本节唯一的直接证据），
707.2 那条线降成灰色细线、只作刻度用，解读全部交给乙格。

⚠️ **v7 那条阶梯换过一次数据源，原因值得记。**
第一版用的是调优记录 §3.8 的六点（445.1 / 453 / 532 / 580 / 630 / 662.3），有三处毛病：
**① 453 和 532 都测于 256 芯片**（不只是 532）；**② 453 那一步是重复计数** ——
445.1 本身就是「调度器组 × pdbs 8」，调度器 flag 已经在起点里了；
**③ 445.1 与后面几点跨了机器批次**，原始记录自己标了「绝对值不可直接比」。

换成快速上手文档 §0 那张表之后，五个点**全部 64 芯片、一条线走到底、每行只加一件事**，
三个毛病一次消掉，也不再需要任何跨规模免责声明。

⚠️ **和第 6 节的两处对不上，都是真的，都要说明。**
· 第 6 节算的是 **666.6 起点 457 → +45.9%**，这里是 **662.3 → +44.9%**，差在 `pdbs` 一档
  （13 对 12）；本图取 662.3 是为了跟 P-15 摆的那个数一致。
· 第 6 节说「我们 GPU 侧的调优记录只到一次 7 组 sweep（492 → 527）」——
  **那是 A4X（GB200）上另一个模型的记录**，跟本图 GB300 上这个模型的四步是
  **两台机器、两份记录**。隔一节出现会被听成前后矛盾，所以图上写清。

⚠️ **「两边都撞墙了」这句话在 GB300 一侧不成立，已按实情改写。**
v7 侧确实撞墙（tile、XLA flag、SparseCore 卸载、推 batch 四个方向 8 格无一正收益）。
GB300 侧 27 组扫点里撞墙的只有**并行度形状那一组**（PP / VPP 三种切法全落 852–856）；
**同一张表里 EP 32 → 16 是 +3.3%（882.3），且被那张表自己认定为 BF16 最优**，
只是没跟进复测。所以 GB300 这一侧是「没跟进」，不是「到顶」。

数据出处：
  · v7 五点 —— 快速上手文档 §0「全部在 64 芯片上实测」那张表 + 18 参数配方行
  · GB300 四点 —— A4X Max 上 Hy3 实战日志的里程碑 M6 / M7 版本表
  · 频率档 +8.6% 与「属于硬件工作点不是调优」的口径 —— 第 6 节 P-14 底带
  · GB300 未跟进的 882.3 —— 同一份 27 组扫点表 B4 行
"""
from common import Fig, para, BL, RD, GN, YL, PU, INK, SUB, LINE, GREY, FILL

W = 1400
TOP = 84

R1_Y = TOP + 40
R1_H = 502

AX, AW = 20, 900
BX, BW = 932, 448

PX, PW = AX + 66, 546          # 绘图区
PY, PH = R1_Y + 96, 262        # 纵轴 0 → YMAX
YMAX = 900.0

BAND_Y = R1_Y + R1_H + 28
H = BAND_Y + 132

# v7：全部 64 芯片，一条线走到底，每行只加一件事（快速上手文档 §0）
V7 = [(457.0, "起点：<code>megablox</code> + pdbs 8"),
      (543.0, "tokamax tile(512,2048,1536) ← 全场最大单项 +18.8%"),
      (580.0, "pdbs 8 → 12（+6.8%）"),
      (630.0, "锁最高频率档 dvfs_p_state=7（+8.6%）<r>← 这一步不算软件</r>"),
      (662.3, "tile 改走 18 个配置参数，不再需要 tokamax 开关（+5.1%）")]

GB = [(707.2, "V1：照抄厂商官方 BF16 recipe"),
      (744.0, "关掉 recompute（换 33 GB 显存，+5.2%）"),
      (827.0, "cutedsl + a2a_overlap ← 最大单项 +11.2%"),
      (854.4, "full_iteration graph + paged stash（+3.3%）")]

NSTEP = max(len(V7), len(GB)) - 1


def _sx(i):
    return PX + 34 + i * ((PW - 68) / float(NSTEP))


def _sy(v):
    return PY + PH - PH * v / YMAX


def build():
    f = Fig(W, H, "TPU v7 与 GB300 两条调优爬升曲线：v7 六步从 445 爬到 662，"
                  "仍低于 GB300 未调优时的 707")
    f.title("这两个数是怎么挣来的　—— <tspan font-weight=\"700\" fill=\"#d93025\">"
            "两条爬升曲线，和一个不能比的起点</tspan>")
    f.legend([(BL, "GB300 · 四步 · 一个通宵"), (GN, "TPU v7 · 五步 · 约两周"),
              (GREY, "707.2 —— 只作刻度用，解读见乙格")])

    _chart(f)
    _origin(f)
    _band(f)
    f.t(W - 20, H - 12,
        "两条曲线的横轴是「第几步」，不是时间 · "
        "纵轴 TFLOP/s / 计算单元，BF16，0 起未截断 · 同一个 295B-A21B",
        "xxs", GREY, "end")
    return f.out()


# ══════════════════════════════════════════════════════════════════════
def _chart(f):
    f.rect(AX, R1_Y, AW, R1_H, "#fff", LINE, 1.2, 10)
    f.t(AX + 18, R1_Y + 26, "甲　·　两条爬升曲线，同一根纵轴", "sec")
    para(f, AX + 18, R1_Y + 46, 600,
         "<g>纵轴<b>从 0 起、没有截断</b> —— 这一节整节在讲怎么让数字经得起回查，"
         "在自己的图上截轴就没得讲了。</g>", "xs", 16)

    # 纵轴刻度
    for v in (0, 300, 600, 900):
        y = _sy(v)
        f.line(PX, y, PX + PW, y, LINE, 1.0, None, None if v == 0 else "3 4")
        f.t(PX - 10, y + 4, str(v), "xxs", SUB, "end")
    f.t(PX - 10, PY - 24, "TFLOP/s", "xxs", SUB, "end")

    # GB300 抄来的起点 —— 只作刻度，不作论点（解读在乙格）
    yb = _sy(707.2)
    f.line(PX, yb, PX + PW, yb, GREY, 1.0, None, "6 4")
    f.t(PX + PW - 4, yb - 8, "707.2　GB300 抄来的起点", "xxs", GREY, "end")

    for pts, c, tag in ((GB, BL, "GB300"), (V7, GN, "v7")):
        xs = [_sx(i) for i in range(len(pts))]
        ys = [_sy(v) for v, _ in pts]
        d = "M%.1f,%.1f " % (xs[0], ys[0]) + " ".join(
            "L%.1f,%.1f" % (x, y) for x, y in zip(xs[1:], ys[1:]))
        f.path(d, c, 2.4)
        for i, (v, _) in enumerate(pts):
            f.rect(xs[i] - 11, ys[i] - 11, 22, 22, "#fff", c, 2.0, 11)
            f.t(xs[i], ys[i] + 4, "①②③④⑤⑥"[i], "xxs", c, "middle")
        f.t(xs[0] - 12, ys[0] - 18, "%s　%.1f" % (tag, pts[0][0]),
            "lbl", c, "middle")
        f.t(xs[-1] + 16, ys[-1] + 4, "%.1f" % pts[-1][0], "numb", c)
    f.t(PX + 4, PY + PH + 20,
        "①②③④⑤ ＝ 第几步（不是时间轴）", "xxs", SUB)

    # 绘图区左下那片空白 —— 放这张图真正的落点
    NX, NW = PX + 22, 392
    f.rect(NX, PY + 146, NW, 62, "#fff", GN, 1.8, 8)
    yy = para(f, NX + 14, PY + 166, NW - 28,
              "<b>⭐ v7：硬件一颗没换，457 → 662.3，<r>+44.9%</r>。</b>", "xs", 15)
    para(f, NX + 14, yy + 1, NW - 28,
         "<g>剥掉 ④ 那个频率档仍有 <b>+33.4%</b>。"
         "<b>这是本节「差距在软件」唯一的直接实验证据</b> —— "
         "P-15 乙格那个 1.19 是除剩下的，这个是跑出来的。</g>", "xxs", 13)

    f.rect(NX, PY + 216, NW, 48, FILL[YL], YL, 1.4, 8)
    para(f, NX + 14, PY + 234, NW - 28,
         "<b>⚠️ 别把两条线逐步对齐看。</b>"
         "<g>横轴只是「第几步」，两边一步的含义、耗时、继承的家底都不同 —— "
         "为什么不能这么看，全在乙格。</g>", "xxs", 13)

    # 右侧步骤清单
    LX = AX + 636
    LW = AW - 636 - 30
    y = R1_Y + 92
    for pts, c, head in ((GB, BL, "GB300 · 一个通宵，四步 · +20.8%"),
                         (V7, GN, "TPU v7 · 约两周，五步 · +44.9%")):
        f.rect(LX - 10, y - 16, LW + 22, 22, FILL[c], c, 1.2, 5)
        f.t(LX, y, head, "lbl", c)
        y += 22
        for i, (v, name) in enumerate(pts):
            f.t(LX, y + 11, "①②③④⑤⑥"[i], "xxs", c)
            f.t(LX + 16, y + 11, "%.1f" % v, "num", INK)
            y = para(f, LX + 62, y + 11, LW - 62, name, "xxs", 13)
            y += 6
        y += 30


