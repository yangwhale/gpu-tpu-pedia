DMAX = 68.0

C = (38, 288, 624, 716, 872, 996)   # 名字 / 条 / 天数 / 改成了 / 偏向 / 怎么发现
LW = 316


def build():
    f = Fig(W, H, "八笔撤回的台账：只有一笔真的经历过「上游撤了它还挂着」，"
                  "而偏向是六比二不是八比零")
    f.title("八笔撤回，按活了多久排　—— <tspan font-weight=\"700\" fill=\"#d93025\">"
            "第一版只记了五笔，漏掉的三笔恰好方向相反</tspan>", "上一张的台账", RD)
    f.legend([("#c8ccd0", "条上灰段＝上游还立着（或它自己就是源头），没人去看它"),
              (RD, "条上红段＝上游已撤、它还挂着，真正的「漏改」"),
              (GN, "右侧绿牌＝撤回前利于 TPU（六笔）"),
              ("#f6c7c4", "右侧红牌＝撤回前利于 GB300（两笔）· 与 P-18 同一套配色")])

    _ledger(f)
    _band(f)
    f.t(W - 20, H - 12,
        "「改成了」那一列的每个值都能在仓库里查到 —— 一份台账不给正确值，读者就没法回查",
        "xxs", GREY, "end")
    return f.out()


# ══════════════════════════════════════════════════════════════════════
def _ledger(f):
    f.rect(20, R1_Y, 1360, R1_H, "#fff", LINE, 1.2, 10)

    hy = R1_Y + 26
    for x, s in zip(C, ("这一课撤回过的", "活了多久（灰=没人看它 · 红=上游撤了它还挂着）",
                        "总寿命", "改成了", "撤回前偏向", "怎么被发现的")):
        f.t(x, hy, s, "xxs", GREY)
    f.line(38, hy + 8, 1362, hy + 8, LINE, 1.0)

    y = hy + 16
    for i, (name, what, kind, c, span, days, orph, fixed, pro_tpu, how) in enumerate(LED):
        rh = 56
        if i % 2 == 0:
            f.rect(38, y, 1324, rh, "#fcfcfd", None, 0, 4)
        f.rect(38, y, 4, rh, c, None, 0, 2)

        f.t(C[0] + 14, y + 21, name, "lbl", INK)
        f.rect(C[0] + 186, y + 9, 44, 16, FILL[c], c, 1.2, 7)
        f.t(C[0] + 208, y + 21, kind, "xxs", c, "middle")
        f.t(C[0] + 14, y + 38, what, "xxs", SUB)

        # ── 两段条 ──
        by, bh = y + 12, 18
        f.rect(C[1], by, LW, bh, "#fff", LINE, 1.0, 3, "4 3")
        grey_w = max(4, LW * (days - orph) / DMAX)
        f.rect(C[1], by, grey_w, bh, "#e8eaed", "#c8ccd0", 1.4, 3)
        if orph > 0:
            ow = max(4, LW * orph / DMAX)
            f.rect(C[1] + grey_w, by, ow, bh, FILL[RD], RD, 1.6, 3)
            f.t(C[1] + grey_w + ow + 8, by + 13,
                "← 漏改 %d 天" % orph if orph >= 1 else "← 同日补齐", "xxs", RD)
        f.t(C[1], by + 32, span, "xxs", GREY)

        # 天数一律中性色 —— 它量的是「多久没人发现」，不是错误的严重度
        f.t(C[2], y + 30, "%d 天" % days if days >= 1 else "不到 1 天", "num", INK)

        f.rect(C[3], y + 14, 146, 22, FILL[GN], GN, 1.2, 5)
        para(f, C[3] + 8, y + 29, 132, "<g>→ </g><b>" + fixed + "</b>", "xxs", 12)

        dc = GN if pro_tpu else RD
        f.rect(C[4], y + 14, 106, 22, FILL[dc], dc, 1.2, 5)
        f.t(C[4] + 53, y + 29, "利于 TPU" if pro_tpu else "利于 GB300",
            "xxs", dc, "middle")

        para(f, C[5], y + 20, 1352 - C[5], how, "xxs", 13)
        y += rh

    f.line(38, y + 2, 1362, y + 2, LINE, 1.0)
    yy = para(f, C[0] + 14, y + 24, 1310,
              "<r><b>⭐ 同一个正确值，错了两次，方向相反。</b></r>"
              "<g><code>2,500 / 5,000</code> 既是 2,700 改过来的，也是 2,250 改过来的 —— "
              "写这一课（主角是 v7）时<b>猜高</b>，写 GPU 那页（主角是 A4X）时"
              "<b>套错机型</b>（官方同代不同封装差 11.1%）。</g>", "xs", 17)
    yy = para(f, C[0] + 14, yy + 3, 1310,
              "<r><b>⭐ 只有一根条有红段。</b></r>"
              "<g>「上游撤了、下游没跟着撤」八笔里只发生过一次 —— "
              "<b>不是常见故障，但那一次就是 15 天。</b></g>", "xs", 17)
    para(f, C[0] + 14, yy + 3, 1310,
         "<r><b>⚠️ 没有任何一个动作能抓到全部八笔。</b></r>"
         "<g>2,700 没有上游，靠回查规格表；7,308 有上游，靠反推换算；"
         "「归类」那笔靠的是审计。<b>这就是下一张要按来源分级的原因。</b></g>", "xs", 17)


