def _fill(f):
    f.t(20, BOT_Y - 26, "喂满率：三种 K，同一个阵列", "sec")
    cases = [
        (GN, "K ＝ 256", 16, 16, "刚好铺满收缩边。理想情况。", "100%"),
        (RD, "K ＝ 128", 8, 16, "只有一半行在动，另一半空转。<b>head_dim=128 就是这一格</b>。", "50%"),
        (GN, "K ＝ 512", 16, 16, "分两趟走，累加器不落地。<b>和第一格一样满</b>。", "100%"),
    ]
    x = 20
    for c, name, rows, cols, note, pct in cases:
        f.rect(x, BOT_Y, 436, 212, "#fff", c, 1.6, 10)
        f.t(x + 16, BOT_Y + 26, name, "box", c)
        f.t(x + 420, BOT_Y + 26, pct, "numb", c, "end")
        cs = 8.6
        for r in range(16):
            for cc in range(16):
                on = r < rows
                f.rect(x + 16 + cc * (cs + 1.4), BOT_Y + 40 + r * (cs + 1.4), cs, cs,
                       FILL[c] if on else "#f1f3f4", c if on else "#e8eaed", 0.5, 1)
        para(f, x + 190, BOT_Y + 58, 232, note, "xs", 16)
        if name == "K ＝ 512":
            f.rect(x + 16, BOT_Y + 40, 16 * (cs + 1.4) - 1.4, 8 * (cs + 1.4),
                   "none", INK, 1.6, 2, "4,3")
            f.t(x + 20, BOT_Y + 54, "第 1 趟", "xxs", INK)
            f.t(x + 20, BOT_Y + 134, "第 2 趟", "xxs", INK)
            para(f, x + 190, BOT_Y + 128, 232,
                 "<b>这就是「粒度不是上限」的意思</b>：大于 256 的维度只是多走几趟，"
                 "不产生浪费。", "xxs", 14)
        if name == "K ＝ 128":
            para(f, x + 190, BOT_Y + 128, 232,
                 "灰色那一半<r>不能拿去干别的</r> —— 没有第二个任务可以填进来。", "xxs", 14)
        x += 452


