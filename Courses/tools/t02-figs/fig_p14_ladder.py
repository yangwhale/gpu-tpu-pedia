# -*- coding: utf-8 -*-
"""图 P-14 —— 四种比法：一种比一种贵，也一种比一种说得上话。

P-12 和 P-13 都在说「怎么比是错的」。这一张给出正面答案，
而且刻意把**代价**和**能证明什么**并排放 ——
因为这两栏是绑在一起的，光看结论那一栏会以为第四档最好、直接跳过去。

  ① 比峰值　　　　　　　零成本　　　　几乎什么都证明不了
  ② 比 MFU　　　　　　　两边各一次　　这套栈用掉了这块硬件的多少
  ③ 同模型两边各调到最好　数周 ＋ 卡　最接近真话 —— ⭐ 我们做的是这一档
  ④ 每美元 / 每瓦　　　　③ ＋ 口径　　采购真正要的那个答案

**代价那一栏画成了条，而且是对数的。** 只写「零成本 / 一次 / 数周」，
四档读起来像等距的四级台阶；实际上 ① 到 ④ 差了好几个数量级。
对数条至少能让「跳一档要付多少」这件事在图上有个形状。
条长是**示意**，不是测量值 —— 图里也这么标了。

右边单独立一格讲第 ② 档最常见的误用：**MFU 高 ≠ 跑得快**。
这不是经验之谈，是恒等式「吞吐 ＝ MFU × 峰值」推出来的，
所以这一格用一个**算例**把它画出来：两条槽是峰值，填充是实际吞吐 ——
**卡 B 的填充比例明显更小，可填出来的那一段反而更长。**

⚠️ **落点那一条改过两次，两次都是因为它偏向一边。**

**第一版**写「同一个模型、同一个规模、**同一批卡**，v7 上 445.1 → 666.6，+50%」。
问题有三个：
  · **「同一批卡」查不到依据** —— 两个数隔了约两周，删掉；
  · **那 +50% 里有 8.6% 是把频率档从默认锁到最高换来的**，属于硬件工作点，
    不是软件调优。剥掉之后约 **+38%**，仍然很大，但必须说清楚；
  · **起点有两个**：调优记录写 445，快速上手那张步骤表写 457。
    用 457 算是 **+45.9%**。落点里点出这件事本身就是这一节的示范。

**第二版**只补了上面三条，但整条落点仍然**只有 TPU 一侧的数字** ——
一份讲「两边都要调」的图，证据全来自一边。现在补上了 GPU 侧的实际家底：
我们那边的调优记录只到一次 7 组配置的 sweep（492 → 527，+7.1%），
**所以下一节那组数，我们自己也只把它挂在 ③ 档的下沿。**

数据出处：
  · 445 / 630 / dvfs +8.6% —— 本仓库 v7 调优记录的收益分解表
  · 457 —— 同项目快速上手文档的步骤表
  · 666.6 —— v7 FP8 最佳配置
  · 492 → 527 —— A4X Megatron sweep 表 A 的 A1 / A2 两行
"""
from common import Fig, para, BL, RD, GN, YL, PU, INK, SUB, LINE, GREY, FILL

W = 1400
TOP = 84

R1_Y = TOP + 40
R1_H = 480

AX, AW = 20, 900
BX, BW = 932, 448

BAND_Y = R1_Y + R1_H + 28
H = BAND_Y + 128

# (序号, 名称, 成本, 成本色, 成本条长度比例（对数示意）, 能证明什么, 陷阱)
STEPS = [
    ("①", "比峰值", "零成本", GREY, 0.04,
     "<r>几乎什么都证明不了。</r>",
     "峰值只是分母，而且<b>口径地雷全埋在这一层</b>："
     "dense/sparse、哪个 SKU、per chip / per device。"),
    ("②", "比 MFU", "两边各跑一次", YL, 0.16,
     "<b>这套软件栈把这块硬件用掉了多少。</b>",
     "分子分母都是选择（前两张图）。"
     "<r>而且 MFU 高不等于跑得快 —— 见右格。</r>"),
    ("③", "同模型同规模，两边各自调到最好", "数周 ＋ 两边的卡", RD, 0.62,
     "<b>最接近真话的一档。</b><g>⭐ 我们做的是这一档。</g>",
     "贵在<b>两边都得有人会调</b>。"
     "<r>只调一边，比出来的是调参投入的差距。</r>"),
    ("④", "每美元 / 每瓦", "③ ＋ 两个新口径", RD, 0.95,
     "<b>采购真正要的那个答案。</b>",
     "价格是<b>谈出来的</b>，不是牌价；功耗要问清"
     "<b>是芯片、是整机、还是含冷却</b>。"),
]

# 右格算例：(卡名, 峰值, MFU, 吞吐)　—— 槽长 = 峰值，填充 = 吞吐
CASE = [("卡 A", 1000, "40%", 400, BL),
        ("卡 B", 2000, "25%", 500, GN)]
CMAX = 2000.0


def build():
    f = Fig(W, H, "跨平台对比的四个档次：比峰值、比 MFU、同模型两边各自调到最好、"
                  "每美元每瓦，各自的代价与能证明的结论")
    f.title("该怎么比　—— <tspan font-weight=\"700\" fill=\"#1e8e3e\">"
            "一种比一种贵，也一种比一种说得上话</tspan>")
    f.legend([(GREY, "不花钱"), (YL, "一次实验"), (RD, "数周量级")])

    _ladder(f)
    _warn(f)
    _band(f)
    f.t(W - 20, H - 12,
        "第 ③ 档的实测在下一节 · 代价条为对数示意，非测量值 · "
        "v7 与 GPU 侧调优幅度均取自本仓库的调优记录",
        "xxs", GREY, "end")
    return f.out()


# ══════════════════════════════════════════════════════════════════════
def _ladder(f):
    f.rect(AX, R1_Y, AW, R1_H, "#fff", LINE, 1.2, 10)
    f.t(AX + 18, R1_Y + 26, "四档比法　·　代价与结论必须一起读", "sec")
    para(f, AX + 18, R1_Y + 46, AW - 36,
         "<g>只看右边那一栏会以为该直接跳到第 ④ 档。"
         "<b>但每往下一档，代价是跳着涨的 —— 大多数场合停在 ② 就够，"
         "只是必须承认它证明的是什么。</b></g>", "xs", 16)

    # 表头
    hy = R1_Y + 90
    f.t(AX + 40, hy, "比法", "lbl", SUB)
    f.t(AX + 388, hy, "代价（对数示意）", "lbl", SUB)
    f.t(AX + 566, hy, "能证明什么 ／ 别忘了什么", "lbl", SUB)
    f.line(AX + 18, hy + 10, AX + AW - 18, hy + 10, LINE, 1.0)

    CBX, CBW = AX + 388, 156        # 成本条的起点与满程
    y = hy + 22
    for no, name, cost, cc, w, proves, trap in STEPS:
        h = 78
        # 左边缘对齐 —— 阶梯感靠底色、序号颜色与成本条长度递进，不靠缩进。
        # 试过逐级右移 8px，出来像没对齐，不像阶梯。
        f.rect(AX + 18, y, AW - 36, h,
               FILL[cc] if cc != GREY else "#fff", cc, 1.2, 8)
        f.t(AX + 38, y + 34, no, "numb", cc if cc != GREY else INK)
        para(f, AX + 72, y + 28, 300, "<b>%s</b>" % name, "xs", 15, INK)

        f.rect(CBX, y + 20, CBW, 18, "#fff", LINE, 1.0, 3, "4 3")
        f.rect(CBX, y + 20, max(CBW * w, 6), 18,
               FILL[cc] if cc != GREY else "#eceff1", cc, 1.2, 3)
        f.t(CBX, y + 54, cost, "xs", cc if cc != GREY else INK, None, "600")

        yy = para(f, AX + 566, y + 28, AW - 602, proves, "xs", 15)
        para(f, AX + 566, yy + 1, AW - 602, "<g>%s</g>" % trap, "xxs", 13)
        y += h + 8


# ══════════════════════════════════════════════════════════════════════
def _warn(f):
    f.rect(BX, R1_Y, BW, R1_H, FILL[RD], RD, 1.4, 10)
    f.t(BX + 18, R1_Y + 26, "⚠️　MFU 高 ≠ 跑得快", "sec")
    para(f, BX + 18, R1_Y + 46, BW - 36,
         "<g>第 ② 档最常见的误用。不是经验之谈 —— "
         "一条恒等式直接推出来的。</g>", "xs", 16)

    f.rect(BX + 18, R1_Y + 82, BW - 36, 42, "#fff", INK, 1.4, 8)
    f.t(BX + BW / 2, R1_Y + 109, "吞吐  =  MFU  ×  峰值", "box", INK, "middle")

    # 算例：槽长 = 峰值，填充 = 实际吞吐
    f.t(BX + 18, R1_Y + 148, "一个算例　·　槽长＝峰值，填充＝实际吞吐",
        "lbl", SUB)
    LX, LW = BX + 84, 268
    y = R1_Y + 160
    for name, peak, mfu, thr, cc in CASE:
        f.t(BX + 20, y + 20, name, "box", INK)
        f.rect(LX, y + 4, LW * peak / CMAX, 24, "#fff", LINE, 1.0, 4, "4 3")
        f.rect(LX, y + 4, LW * thr / CMAX, 24, FILL[cc], cc, 1.4, 4)
        f.t(LX + 8, y + 21, str(thr), "num", cc)
        f.t(BX + 20, y + 38, "峰值 %s · MFU %s" % (format(peak, ","), mfu),
            "xxs", SUB)
        y += 54

    f.rect(BX + 18, R1_Y + 272, BW - 36, 40, "#fff", RD, 1.2, 8)
    para(f, BX + 32, R1_Y + 290, BW - 64,
         "<r><b>卡 B 的 MFU 低了 15 个点，却快 25%。</b></r>", "xs", 16)

    y = R1_Y + 332
    for ln in ["<g>MFU 回答的是「<b>这套栈把手上这块硬件用满了没有</b>」——"
               "它是<b>效率</b>指标，不是<b>速度</b>指标。"
               "<r>所以它适合<b>纵向</b>比：同一块硬件，我这周比上周调好了多少。</r></g>",
               "<b>横向比谁更快，只能看吞吐本身</b>"
               "<g>—— 优先用 tokens/s 或「跑完一步几秒」，"
               "它们比 TFLOP/s 少一层公式（见上一张图的甲格）。</g>"]:
        y = para(f, BX + 18, y, BW - 36, ln, "xs", 17) + 8

    f.rect(BX + 18, R1_Y + 416, BW - 36, 52, "#fff", BL, 1.2, 8)
    para(f, BX + 32, R1_Y + 436, BW - 64,
         "<b>两个都报最省事</b>：<g>吞吐说明谁快，MFU 说明还剩多少没榨出来。</g>",
         "xs", 16)


# ══════════════════════════════════════════════════════════════════════
def _band(f):
    f.rect(20, BAND_Y, 1360, 100, FILL[BL], BL, 1.4, 10)
    f.t(38, BAND_Y + 28, "⭐ 第 ③ 档为什么贵：只调一边，比出来的是调参投入的差距", "sec")
    y = BAND_Y + 54
    para(f, 38, y, 1324,
         "<b>同一个模型、同一个规模，v7 上从 445 调到 666.6 TFLOP/s/chip —— +50%。</b>"
         "<g>（这里面有 <b>8.6% 是把频率档从默认锁到最高</b>换来的，属于硬件工作点不是调优，"
         "剥掉约 <b>+38%</b>；起点另有一份文档记的是 457，那样算 <b>+45.9%</b>。"
         "<b>三个数都列出来，正是这一节在讲的事。</b>）</g>"
         "<r>这个幅度比很多「硬件对比」结论本身都大 —— 只调了一边的对比，"
         "读者看到的是「哪一边的人更熟」。</r>"
         "<b>⚠️ 而我们 GPU 侧的调优记录只到一次 7 组配置的 sweep（492 → 527，+7.1%）—— "
         "所以下一节那组数，我们自己也只把它挂在 ③ 档的下沿。</b>", "xs", 19)


if __name__ == "__main__":
    import sys
    open(sys.argv[1] if len(sys.argv) > 1 else "out/fig_p14_ladder.svg",
         "w", encoding="utf-8").write(build())
