SVG_L200 = {}
_svg_cache = {}


def _l200_svg(key):
    if key not in _svg_cache:
        script, fn = SVG_L200[key]
        d = tempfile.mkdtemp(prefix="l200fig-")
        r = subprocess.run([sys.executable, os.path.join(HERE, script)],
                           cwd=d, capture_output=True, text=True)
        assert r.returncode == 0, "%s 跑挂了：\n%s" % (script, r.stderr)
        path = os.path.join(d, fn)
        assert os.path.isfile(path), "%s 没有吐出 %s" % (script, fn)
        _svg_cache[key] = io.open(path, encoding="utf-8").read().strip()
    return _svg_cache[key]


_FIG_SEEN = []


def fig(key, wide=None):
    """把 L300 里 id=key 的整个 <figure> 搬过来。

    wide=True/False 可以覆盖它的宽度类：L300 里 §0–§2 那批手写图是窄版
    （.fbox），§3 之后的显微镜图是宽版（.fbox.fwide）。L200 里两批混排，
    个别地方需要统一。不传就保持原样。
    """
    assert key not in _FIG_SEEN, "图 %s 被放了两次 —— L200 的全部意义就是不重复" % key
    _FIG_SEEN.append(key)

    i = _src.index('id="%s"' % key)
    beg = _src.rindex("<figure", 0, i)
    end = _src.index("</figure>", i) + len("</figure>")
    block = _src[beg:end]

    if key in CAP_OVERRIDE:
        # 保留 figcaption 尾巴上那个「—— 出自《显微镜》」的出处 span：
        # 它是引用，覆盖图注时丢掉就成了假原创。
        old = re.search(r"<figcaption>(.*?)</figcaption>", block, re.S).group(1)
        src_tail = re.search(r'<span class="msfrom">.*?</span>', old, re.S)
        new = CAP_OVERRIDE[key] + ("　" + src_tail.group(0) if src_tail else "")
        block = re.sub(r"<figcaption>.*?</figcaption>",
                       lambda _: "<figcaption>%s</figcaption>" % new, block, flags=re.S)

    if key in SVG_L200:
        i0 = block.index("<svg")
        i1 = block.index("</svg>") + len("</svg>")
        block = block[:i0] + _l200_svg(key) + block[i1:]

    if wide is True and "fwide" not in block[:120]:
        block = block.replace('class="fbox"', 'class="fbox fwide"', 1)
    elif wide is False:
        block = block.replace('class="fbox fwide"', 'class="fbox"', 1)
    return block


def lift(marker_start, marker_end):
    """从 L300 原样搬一段 HTML（用在那种「已经写好、没必要重写」的块上，
    目前只有 §1 那张十行手册表 ＋ 它的四条脚注）。"""
    i = _src.index(marker_start)
    j = _src.index(marker_end, i) + len(marker_end)
    return _src[i:j]


