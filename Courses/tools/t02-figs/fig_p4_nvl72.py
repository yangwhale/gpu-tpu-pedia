# -*- coding: utf-8 -*-
"""图 P-4 —— NVL72 把「一台机器」这个词废掉了，顺便埋了两个口径陷阱。

T-8 那张图讲的是「能连多远」，这张讲的是「连起来之后那个边界在哪」。
大多数人脑子里那张图还停在上一代：机内 NVLink 8 卡、出机器掉到网络。
**NVL72 不是这样** —— 新的边界是 18 个节点 72 张卡，中间全走 NVSwitch。

但这一节真正的教学价值不在拓扑，在**两个口径陷阱**，而且两个都很典型：

1. **72 是物理规模，能进训练任务的是 64**（16 节点上阵、2 节点热备）。
   问「一个域有多少显存」，答案取决于你问的是物理量还是可用量 ——
   跟附录 A 里 192 GiB / 96 GiB / 94.74 GiB 那三层是一模一样的病。
2. **节点合计 2,000 Gbps 里混了 400 Gbps 的管理网**，
   真正能拿去算 all-to-all 的只有 1,600。

所以这张图刻意把「陷阱」画成和拓扑图同等份量的两张卡 ——
**听众记住 72 这个数没有用，记住「先问是物理量还是可用量」才有用。**
"""
from common import Fig, para, BL, RD, GN, YL, PU, INK, SUB, GREY, FILL

W = 1400
TOP = 84

TP_Y = TOP + 40
TP_H = 276

TR_Y = TP_Y + TP_H + 46
TR_H = 268
TR_W = 670

BAND_Y = TR_Y + TR_H + 30
H = BAND_Y + 158

# 四层嵌套：从一张卡到跨域。宽度逐层收窄，最外层是「旧常识失效」的地方
LAYERS = [
    (GREY, "跨域　·　RoCE / RDMA",
     "出了这个域才掉到网络。实测 all-reduce <b>约 840 → 约 325 GB/s</b>"
     "（<b>2.6 倍</b>，本仓库 gpu/a4x/04-nccl-test），<b>而且通信库要换一条实现路径</b>。"),
    (BL, "NVL72 域　·　18 节点 ＝ 72 GPU，NVSwitch 5 全互联",
     "<r>新的边界在这里。</r>域内任意两张卡之间都是 NVLink，<b>不是网络</b>。"),
    (GN, "节点　·　2 × Grace ARM64 ＋ 4 × Blackwell GPU",
     "<g>「一台机器」原来的边界 —— 现在这条线基本不重要了。</g>"),
    (YL, "一张 B200", ""),
]


def build():
    f = Fig(W, H, "NVL72 域层级示意，以及两个容易读错的口径：72 张是物理规模而可训练是 64 张，"
                  "节点合计 2000 Gbps 含 400 Gbps 管理网")
    f.title("NVL72 把「一台机器」这个词废掉了"
            "　—— 顺便埋了<tspan font-weight=\"700\" fill=\"#d93025\">两个口径陷阱</tspan>")
    f.legend([(BL, "新的边界：NVL72 域"), (GN, "旧的边界：一个节点"),
              (RD, "读错了就会一路错下去的地方")])

    _topo(f)
    _traps(f)
    _band(f)
    return f.out()


# ══════════════════════════════════════════════════════════════════════
def _topo(f):
    f.rect(20, TP_Y, 1360, TP_H, "#fff", "#dadce0", 1.2, 10)
    f.t(38, TP_Y + 27, "先把边界摆对　—— 上一代的常识（机内 8 卡、出机器掉网络）在这一代已经不成立", "sec")

    # 四层的**上下都要逐层内缩**。第一版只缩了上边、四层共用同一条底边，
    # 于是最里那层只剩一条 28px 的缝，标签正好压在边框线上 ——
    # 而且底边重合会让人看不出这是嵌套关系。
    DTOP, DBOT, DX = 42, 14, 26
    inner = TP_H - 44 - 16                       # 最外层可用高度
    for i, (c, head, body) in enumerate(LAYERS):
        x = 38 + i * DX
        y = TP_Y + 44 + i * DTOP
        w = 1324 - 2 * i * DX
        h = inner - i * (DTOP + DBOT)
        f.rect(x, y, w, h, FILL[c], c, 1.3, 8)
        f.t(x + 14, y + 25, head, "lbl", INK)
        if body:
            para(f, x + 360 - i * DX, y + 25, w - 380 + i * DX, body, "xs", 17)


# ══════════════════════════════════════════════════════════════════════
TRAP1 = [
    ("问题", "「一个 NVL72 域有多少显存？」"),
    ("按 72 卡（物理规模）", "<b>13.4 TB</b>　—— 这个数<r>不能拿去规划任务</r>"),
    ("按 64 卡（我们的编排口径）", "<b>11.9 TB</b>　—— 16 节点上阵，<b>2 节点 8 卡做热备</b>"),
    ("为什么让出 8 卡", "这批集群 <b>auto-repair 是关的</b>，坏一台要靠换标签顶上"),
    ("⚠️ 所以 64 不是平台限制", "是<b>我们自愿让出 11% 容量</b>换稳定 —— <r>换个人运维就是别的数</r>"),
]

TRAP2 = [
    ("问题", "「一个节点的网络带宽是多少？」"),
    ("RDMA（GPU 跨域通信）", "CX-7 × 4 × 400 Gbps ＝ <b>1,600 Gbps</b>　←　<b>算 all-to-all 用这个</b>"),
    ("管理网", "GVNIC　<b>400 Gbps</b>　—— 跟 GPU 通信没关系"),
    ("常见的报法", "<r>「节点合计 2,000 Gbps」</r>　—— 它把管理网算进来了"),
]


def _traps(f):
    for x, title, sub, rows in [
            (20, "陷阱一　·　物理规模 ≠ 可用规模", "跟附录 A 里 192 / 96 / 94.74 那三层是同一种病", TRAP1),
            (710, "陷阱二　·　合计里混进了不该算的东西", "跟第 0 节里 GiB 和 GB 混用是同一类错", TRAP2)]:
        f.rect(x, TR_Y, TR_W, TR_H, FILL[RD], RD, 1.4, 10)
        f.t(x + 18, TR_Y + 26, title, "sec")
        para(f, x + 18, TR_Y + 46, TR_W - 36, "<g>%s</g>" % sub, "xs")

        y = TR_Y + 60
        for i, (k, v) in enumerate(rows):
            f.rect(x + 18, y, TR_W - 36, 38, "#fff" if i else "#f1f3f4", None, 0, 6)
            f.t(x + 32, y + 24, k, "lbl", INK)
            para(f, x + 216, y + 24, TR_W - 250, v, "xs")
            y += 40


# ══════════════════════════════════════════════════════════════════════
def _band(f):
    f.rect(20, BAND_Y, 1360, 142, FILL[BL], BL, 1.4, 10)
    f.t(38, BAND_Y + 28, "拿这个数回头看专题一 —— 「域」才是新的「一台机器」", "sec")
    y = BAND_Y + 54
    for seg in [
            "专题一算过：那个模型常驻权重 <b>1.23 TiB ＝ 约 1.35 TB</b>"
            "（<g>这一步换算别省 —— 这张图刚说完 GiB / GB 不能混，自己更不能踩</g>）。"
            "一个域按 64 卡算有 <b>11.9 TB</b>，权重只占约 <b>11%</b> —— "
            "<b>余量足够再放下相当规模的 KV cache</b>（具体多少取决于并发与序列长度，本节不展开）。",
            "也就是说，对这一档模型，<r>「跨域断崖」这件事在推理时根本不必发生</r>。"
            "<b>但这个结论踩在两个前提上，两个都得说出来</b>："
            "一是<b>按 64 不是 72</b>；二是 <r>11.9 TB 本身也还是物理量</r> —— "
            "实际可用还要扣激活、优化器状态与框架开销。<b>左边那格批评的病，这句话同样要防。</b>"]:
        y = para(f, 38, y, 1324, seg, "xs", 19) + 4


if __name__ == "__main__":
    import sys
    open(sys.argv[1] if len(sys.argv) > 1 else "out/fig_p4_nvl72.svg",
         "w", encoding="utf-8").write(build())
