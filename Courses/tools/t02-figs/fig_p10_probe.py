# -*- coding: utf-8 -*-
"""图 P-10 —— 体检工具变成搜索器：29 组探针，一张卡都没占。

P-9 证明了「编译器算的那本账跟真机对得上」。这一张是那句话的**推论**：
既然它一分钱卡都不用、两分钟出一次结果，那就可以**在 CPU 上把配置空间扫一遍**，
只问一个问题 —— **装不装得下**。真机额度留给活下来的那少数几个。

三格是三类不同性质的发现，凑在一起才说明「值得扫」：

  甲　天花板在哪　　—— 而且它不在你以为的地方（13 比 12 还省）
  乙　旋钮灵不灵　　—— 有两个旋钮**改了完全没反应**
  丙　哪些是承重墙　—— 一组 XLA flag 是「能跑」和「跑不了」的分界

**这三条里最值钱的是乙。** 甲和丙是数字，明年换个模型就变；
乙是一句可以带走的话：**改了没反应 ≠ 改对了。**
在没有 AOT 之前，这种「旋钮根本没被读到」只能靠真机跑一轮才看得出来 ——
而真机那一轮的结论会是「没变化」，跟「调对了但不明显」长得一模一样。

⚠️ **单位：全表 GiB。** 源记录里成功那几档是按字节 ÷ 1e9 记的（写作 80.48），
失败那几档是编译器报错里抄的、本来就是 GiB。**同一张表两种单位，差 7.4%。**
这里统一换算成 GiB（80.48 GB → 74.95 GiB），跟 94.74 那条上限同口径。
连带两个派生数跟源记录不一样，是源记录混了单位算的：
**余量 14 → 19.8 GiB**，**flag 压低 15.3% → 21%**（(95.01−74.95)/95.01）。

⚠️ 乙那一格的横轴是**倍数**（需要的 temp ÷ 94.74 GiB）。
理由**不是**「绝对值会挤成一条线」—— 倍数只是常数缩放，条长一模一样，
那个理由是假的。真理由是：**1.0× 那条线本身就是判据**，一眼看出过没过。
每根条右边仍标原始 GiB —— **换算过的图必须让人能换回去。**
"""
from common import Fig, para, BL, RD, GN, YL, PU, INK, SUB, LINE, GREY, FILL

W = 1400
TOP = 84

R1_Y = TOP + 40
R1_H = 512
CW = 446
XS = [20, 20 + CW + 11, 20 + 2 * (CW + 11)]

BAND_Y = R1_Y + R1_H + 28
H = BAND_Y + 158

LIMIT = 94.74          # GiB／device，可分配上限（第 0 节推过这三步）

# ── 甲：batch 天花板 ────────────────────────────────────────────
BATCH = [(12, 1536, 74.95, True, "原来的生产配置"),
         (13, 1664, 73.11, True, "<r>比 12 还省 1.8 GiB</r>"),
         (14, 1792, 96.53, False, "只差 1.79 GiB"),
         (16, 2048, 102.59, False, "15 也试过，同样装不下")]

# ── 乙：remat 一松就崩 ──────────────────────────────────────────
REMAT = [("生产配置：custom ＋ 一处 offload", 74.95, True, ""),
         ("out_proj 放回 device", 118.05, False, ""),
         ("decoder_layer_input 放回 device", 115.08, False, ""),
         ("remat_policy=full", 115.08, False, "<r>跟上一行一字不差</r>"),
         ("mlpwo 放回 device", 323.45, False, ""),
         ("remat_policy=minimal", 562.58, False, ""),
         ("qkv_proj 放回 device", 74.95, True, "<r>改了没反应</r>"),
         ("mlpwi 放回 device", 74.95, True, "<r>改了没反应</r>")]
RMAX = 6.4             # 实测最大 5.94，截断从不触发；留余量是为了万一有条被截能看出来

# ── 丙：XLA flag 是承重墙 ───────────────────────────────────────
# 第五行没有 temp 数字 —— 它换了一种崩法（VMEM 不是 HBM），
# 而这张图的轴只量 HBM。**留着这一行，就是把轴的边界画出来。**
FLAGS = [("生产那 16 个都带上", 74.95, True, "还剩约 19.8 GiB 余量"),
         ("一个都不带", 95.01, False, "<r>只超 0.3%</r>"),
         ("只带 vmem 上限那一个", 94.81, False, "几乎没省"),
         ("只带 SparseCore 卸载那 9 个", 95.01, False, "<r>跟一个都不带一模一样</r>"),
         ("只带调度器组", None, False, "<r>换了一种崩法：VMEM 爆，不是 HBM</r>"),
         ("vmem 上限 ＋ 调度器组", 74.95, True, "<b>这两组才是承重的</b>")]


def build():
    f = Fig(W, H, "用 AOT 在 CPU 上扫配置空间的三类发现：batch 天花板、"
                  "remat 策略对显存的影响、以及一组 XLA flag 是能否跑通的分界")
    f.title("体检工具变成搜索器　—— <tspan font-weight=\"700\" fill=\"#1a73e8\">"
            "29 组探针，一张卡都没占</tspan>")
    f.legend([(GN, "装得下"), (RD, "装不下")])
    # 判据是一条虚线，不是一个色块 —— 图例里给虚线本身，别给灰方块
    f.line(232, 54, 262, 54, INK, 1.6, dash="5 4")
    f.t(268, 58, "判据：需要的 temp vs 94.74 GiB／device", "sm")

    _batch(f)
    _remat(f)
    _flags(f)
    _band(f)
    f.t(W - 20, H - 12,
        "实测：与 P-9 同一批 · 29 组配置探针 / 一台机器 3 并发 · "
        "丙格那五档消融在另一台机器上独立复跑过，数字逐位相同",
        "xxs", GREY, "end")
    return f.out()


def _hdr(f, i, title, sub):
    x = XS[i]
    f.rect(x, R1_Y, CW, R1_H, "#fff", LINE, 1.2, 10)
    f.t(x + 16, R1_Y + 26, title, "sec")
    return para(f, x + 16, R1_Y + 46, CW - 32, sub, "xs", 16)


# ══════════════════════════════════════════════════════════════════════
def _batch(f):
    x = XS[0]
    _hdr(f, 0, "甲　·　天花板在哪",
         "<g>从想要的 batch 往上加，装不下就退回来。</g>")

    y = R1_Y + 78
    for pdbs, gb, temp, ok, note in BATCH:
        c = GN if ok else RD
        f.rect(x + 16, y, CW - 32, 54, FILL[c], c, 1.2, 8)
        f.t(x + 30, y + 23, "pdbs = %d" % pdbs, "box", c)
        f.t(x + 30, y + 42, "global batch %s" % format(gb, ","), "xxs", SUB)
        f.t(x + CW - 30, y + 25, "%.2f GiB" % temp, "num", c, "end")
        f.t(x + CW - 30, y + 43, "✅ 装得下" if ok else "❌ 装不下", "xxs", c, "end")
        if note:
            para(f, x + 168, y + 43, 180, note, "xxs", 12)
        y += 62

    f.rect(x + 16, R1_Y + 380, CW - 32, 116, "#fff", BL, 1.2, 8)
    yy = para(f, x + 30, R1_Y + 402, CW - 60,
              "<r>13 比 12 更省，这是反直觉的。</r>复现过两次、"
              "<b>字节级一致</b>。机制没查明 —— <b>记在这里是因为它可执行，"
              "不是因为它被解释清楚了。</b>", "xs", 16)
    yy = para(f, x + 30, yy + 3, CW - 60,
              "<g>14 只差 1.79 GiB，试了三种省法都补不上。</g>", "xs", 16)
    para(f, x + 30, yy + 3, CW - 60,
         "<b>⚠️ 但别把它当神谕。</b>专题一提醒过：<b>贴着上限那一带它判不准，"
         "我们判错过</b>。<b>14 这种「只差 1.79」的，仍然要真机确认。</b>", "xs", 16)


# ══════════════════════════════════════════════════════════════════════
def _remat(f):
    x = XS[1]
    _hdr(f, 1, "乙　·　旋钮灵不灵",
         "<g>横轴是<b>倍数</b>（需要的 temp ÷ 94.74 GiB）—— "
         "这样 <b>1.0× 那条线本身就是判据</b>，一眼看出过没过。"
         "每根条右边仍标原始 GiB。</g>")

    bx = x + 16
    bw = CW - 32 - 100
    ll = bx + bw / RMAX
    f.t(ll + 5, R1_Y + 112, "上限 1.0×", "xxs", INK)

    y = R1_Y + 126
    for name, v, ok, note in REMAT:
        c = GN if ok else RD
        r = v / LIMIT
        lbl = "<b>%s</b>" % name + ("　%s" % note if note else "")
        para(f, bx, y, CW - 32, lbl, "xxs", 12, c)
        f.rect(bx, y + 8, max(bw * min(r, RMAX) / RMAX, 2), 11, c, None, 0, 3)
        # 线画在条之后 —— 超限的条要能看见自己「越过」了这条线
        f.line(ll, y + 5, ll, y + 22, INK, 1.5, dash="4 3")
        f.t(bx + bw + 6, y + 18, "%.2f×" % r, "num", c)
        f.t(x + CW - 16, y + 18, "%.2f GiB" % v, "xxs", SUB, "end")
        y += 34

    f.rect(x + 16, R1_Y + 424, CW - 32, 72, "#fff", BL, 1.2, 8)
    para(f, x + 30, R1_Y + 446, CW - 60,
         "<r>最后两行改了完全没反应</r> —— 这两个旋钮在本模型的 custom remat 路径上"
         "<b>根本没被读到</b>。<b>改了没反应 ≠ 改对了。</b>", "xs", 16)


# ══════════════════════════════════════════════════════════════════════
def _flags(f):
    x = XS[2]
    _hdr(f, 2, "丙　·　哪些是承重墙",
         "<g>同一份配置，只改带哪些 XLA flag。</g>")

    y = R1_Y + 78
    for name, v, ok, note in FLAGS:
        c = GN if ok else RD
        f.rect(x + 16, y, CW - 32, 50, FILL[c], c, 1.2, 8)
        para(f, x + 30, y + 20, CW - 140, "<b>%s</b>" % name, "xs", 14, c)
        # v 为 None 那行没有 temp 数字，正因为它压根不是 HBM 爆的
        f.t(x + CW - 30, y + 22, "%.2f" % v if v else "—", "num", c, "end")
        f.t(x + CW - 30, y + 40, "✅" if ok else "❌", "xxs", c, "end")
        para(f, x + 30, y + 40, CW - 140, note, "xxs", 12)
        y += 56

    f.rect(x + 16, R1_Y + 424, CW - 32, 72, "#fff", BL, 1.2, 8)
    yy = para(f, x + 30, R1_Y + 446, CW - 60,
              "<b>这组 flag 把峰值临时空间从 95.01 压到 74.95 GiB，低 21%</b> —— "
              "<r>正好跨过 94.74 那条线。</r>", "xs", 16)
    para(f, x + 30, yy + 2, CW - 60,
         "<g>而且必须成对：单开哪一个都崩，只是崩法不同。</g>", "xs", 16)


# ══════════════════════════════════════════════════════════════════════
def _band(f):
    f.rect(20, BAND_Y, 1360, 130, FILL[BL], BL, 1.4, 10)
    f.t(38, BAND_Y + 28, "三条发现里，只有一条明年还成立", "sec")
    y = BAND_Y + 54
    for seg in [
            "<b>甲和丙是数字，换个模型、换代硬件就都变了。</b>"
            "<r>乙是一句能带走的话：改了没反应 ≠ 改对了。</r>"
            "<b>在能免费重扫之前，「这个旋钮根本没被读到」和「调对了但不明显」"
            "长得一模一样</b> —— 而真机上想分开这两者，要花一轮抢卡。",
            "<r>⚠️ 但它也有看不见的东西：</r>"
            "<b>AOT 体检的是「配置文件描述的那个程序」。</b>"
            "在容器里现场打的补丁，它看不见。"
            "<g>我们就撞过一次：一个调 tile 的补丁照常打印「已生效」，"
            "加了计数器才发现<b>它一次都没被调用</b> —— "
            "补丁没写错，是打在了另一条 kernel 路径上，而生产走的不是那条。</g>"]:
        y = para(f, 38, y, 1324, seg, "xs", 19) + 4


if __name__ == "__main__":
    import sys
    open(sys.argv[1] if len(sys.argv) > 1 else "out/fig_p10_probe.svg",
         "w", encoding="utf-8").write(build())
