# -*- coding: utf-8 -*-
r"""外传 图 X-1 · **同一把尺子量四颗芯片 —— 只有 v6e 落在别处**。

════════════════════════════════════════════════════════════════════
⭐⭐ 这一讲的钩子，全部重量压在这一张上
════════════════════════════════════════════════════════════════════

专题二 §1 立了一条线：**算力 ÷ HBM 带宽**，得到「每搬一个字节，这台机器
本来能算多少次」。那一讲算出 B200 和 TPU v7 **几乎一模一样，都是 312**，
并把这件事当成结论：**按参数表，这是同一类芯片。**

⭐ 这一讲开门就把同一把尺子多量两颗，其中一颗立刻破了那个「都一样」：

    H100  989.5 ÷ 3.35  = 295
    B200  2500  ÷ 8.0   = 312
    v7    2307  ÷ 7.38  = 313
    v6e   918   ÷ 1.638 = 560   ← 唯一的异类

⭐⭐ **「算力强、显存弱」这句话，精确版本就是这个 560。**
   它不是形容词，是一个能当场除出来的数：
   **v6e 要求你每搬一个字节，比 H100 多算一倍的次数。**

⛔ 三条口径，错一条整讲作废（跟 topic02x-verified-specs.md 同源）：
   ① H100 用**稠密** 989.5，不用数据表印的 1,979 ——&nbsp;那个带稀疏，差整一倍
   ② v6e **1 TensorCore / chip**，per-chip 就是 per-device，不用除 2
   ③ 四颗全取 bf16，不拿 v6e 的 Int8 去凑

════════════════════════════════════════════════════════════════════
⛔ 画法上的两条边界
════════════════════════════════════════════════════════════════════
① **不画整条 roofline 折线。** L100 二十分钟，屋顶线那套坐标要花五分钟铺垫，
   而这里只需要「一根轴上四个点」。⭐ 只画屋脊点本身，不画屋顶。
② **不比谁快。** 图上一个 benchmark 数都没有 ——&nbsp;现场已定这一讲只讲
   硬件结构与负载匹配。屋脊点是**结构量**，不是性能量，这条界要在图上说清。
"""
import io
import re

from topic03_draw import (Fig, wpx, _sz, LINE, LINE2,
                          BL, OR, GR, RD, GY, GY2, PU, INK)

# ── 数据：四颗芯片，全部来自 topic02x-verified-specs.md ────────────
# (名字, 算力 TFLOP/s bf16 稠密, HBM 带宽 TB/s, 颜色, 出处标注)
CHIPS = (
    ("NVIDIA H100 SXM", 989.5, 3.35, GY, "数据表（稠密 ＝ 1,979 ÷ 2）"),
    ("NVIDIA B200", 2500.0, 8.00, GY, "专题二 §1 已算过"),
    ("TPU v7（Ironwood）", 2307.0, 7.38, GY, "专题二 §1 已算过"),
    ("TPU v6e（Trillium）", 918.0, 1.638, RD, "官方 v6e 规格表"),
)
# ⭐ 前三颗刻意都用中性灰：**它们是背景，不是主角**。
#   只有 v6e 上色 ——&nbsp;一眼看出「三个挤在一起，一个跑出去」。


def main():
    W = 1400
    f = Fig(W, "四颗芯片的算力除以显存带宽：H100 是 295，B200 是 312，"
               "TPU v7 是 313，三者几乎一样；而 TPU v6e 是 560，"
               "接近前三者的两倍")
    f.marks = set()
    y = f.header(
        '同一把尺子，量四颗芯片 ——&#160;'
        '<tspan font-weight="700">只有 v6e 落在别处</tspan>',
        '⭐ 尺子还是专题二那一把：<tspan font-weight="700">算力 ÷ 显存带宽</tspan>'
        ' ＝ 每搬一个字节，这台机器本来能算多少次。'
        '<tspan font-weight="700">数越大，越挑「算得多、搬得少」的活。</tspan>',
        [(GY, "三颗旗舰：几乎重合"), (RD, "v6e：跑出去将近一倍")])

    # ── 轴 ──────────────────────────────────────────────────────
    AX0, AX1 = 620, W - 120          # 轴的左右端
    VMAX = 620.0                     # 轴的量程
    def xf(v):
        return AX0 + (AX1 - AX0) * (v / VMAX)

    ROW = 66
    top = y + 8

    # ⛔⛔ 参考线**必须先画**。第一版把这段放在四行之后，于是它盖住了
    #   H100 那个 295（只露出一个「5」）和三个灰圆点 ——&nbsp;
    #   渲染出来才看见，几何探针查不出（重叠的是图形不是文字）。
    #   ⭐ SVG 按文档顺序绘制，**后写的在上面**。凡是「背景／参考」性质的
    #     东西，位置就该在最前面 ——&nbsp;这跟图 1-7 那条「会动的要单独一层」
    #     是同一条：**先想清楚这一笔属于哪一层，再想画在哪个坐标。**
    # ⭐ 顺带把虚线框换成两条竖参考线：框太重，而且它围出来的大半是空白。
    for v in (295, 313):
        f.line(xf(v), top - 10, xf(v), top + 3 * ROW + 18, LINE, 1,
               dash="3 4", arrow=False)
    f.t((xf(295) + xf(313)) / 2.0, top - 18,
        "295 ～ 313：三颗挤在这一线", GY2, size=_sz(11), anchor="middle")

    for i, (name, tf, bw, col, src) in enumerate(CHIPS):
        yy = top + i * ROW
        ridge = tf * 1e12 / (bw * 1e12)
        # 左：芯片名 ＋ 算式
        f.t(0, yy + 4, name, col if col != GY else INK, bold=True, size=13)
        f.t(0, yy + 24, "%s ÷ %s TB/s" % (
            ("%.1f" % tf).rstrip("0").rstrip("."), bw), GY2, size=_sz(11),
            mono=True)
        f.t(220, yy + 24, src, GY2, size=_sz(11))
        # 中：细基线 ＋ 棒棒糖
        f.line(AX0, yy + 8, AX1, yy + 8, LINE2, 1, arrow=False)
        f.line(AX0, yy + 8, xf(ridge), yy + 8,
               col, 3.0 if col != GY else 2.0, arrow=False)
        f.box(xf(ridge) - 7, yy + 1, 14, 14, col, col, 7)
        # ⭐ 数值一律画在圆点右侧 14px；前三颗的点都落在参考线附近，
        #   所以这几个数会紧贴虚线右边 ——&nbsp;这是有意的，读者顺着线往右扫。
        f.t(xf(ridge) + 15, yy + 13, "%d" % round(ridge),
            col, bold=True, size=15)
    ay = top + len(CHIPS) * ROW - 26

    # 刻度
    f.line(AX0, ay, AX1, ay, GY2, 1.2, arrow=False)
    for v in range(0, 601, 100):
        f.line(xf(v), ay, xf(v), ay + 5, GY2, 1, arrow=False)
        f.t(xf(v), ay + 20, str(v), GY2, size=_sz(11), anchor="middle")
    f.t((AX0 + AX1) / 2.0, ay + 40,
        "屋脊点（FLOP / byte）——&#160;每搬一个字节，本来能算多少次",
        GY, size=_sz(11), anchor="middle")

    # ⭐ 把那个比值明写出来。不画这一笔，读者得自己拿 560 去除 295。
    ry = top + 3 * ROW + 26
    f.line(xf(295), ry, xf(560), ry, RD, 1.4, arrow=True)
    f.line(xf(560), ry, xf(295), ry, RD, 1.4, arrow=True)
    f.t((xf(295) + xf(560)) / 2.0, ry - 8,
        "v6e 的胃口是 H100 的 1.9 倍", RD, bold=True, size=_sz(12),
        anchor="middle")

    y = ay + 58

    # ── 落点 ────────────────────────────────────────────────────
    y = f.band(y, "warn",
               "「算力强、显存弱」不是形容词 ——&#160;它就是这个 560",
               ['把 v6e 跟 H100 逐项摆开：'
                '<tspan font-weight="700">算力 918 对 989.5，是它的 93%，基本打平</tspan>；'
                '而 <tspan font-weight="700">带宽 1,638 对 3,350，只有 49%</tspan>，'
                '<tspan font-weight="700">容量 32 GB 对 80 GB，只有 40%</tspan>。',
                '⭐ 分子几乎没变、分母砍掉一半 ——&#160;'
                '<tspan font-weight="700">屋脊点就翻了一倍</tspan>。'
                '这就是那句「算力强、显存弱」唯一精确的说法。',
                '⭐⭐ 于是这颗芯片对负载的要求变了：'
                '<tspan font-weight="700">每搬一个字节，你得给它凑够 560 次运算，它才不闲着。</tspan>'
                '——&#160;凑不够的活，它比谁都亏；凑得够的活，它比谁都划算。'])

    y = f.band(y + 14, "info",
               "所以这一讲只回答一个问题：什么样的活凑得够 560",
               ['⛔ <tspan font-weight="700">屋脊点是结构量，不是性能量。</tspan>'
                '它只说「这台机器的胃口有多大」，'
                '<tspan font-weight="700">一个字都没说谁跑得快</tspan> ——&#160;'
                '本讲从头到尾不比 benchmark。',
                '接下来两张图<tspan font-weight="700">把两颗芯片拆开</tspan>，'
                '看这个 560 是从什么样的硅片布局里长出来的；'
                '然后再看<tspan font-weight="700">扩散模型的计算长什么样</tspan>，'
                '为什么它恰好是那种「凑得够」的活。'])

    y = f.src(y + 18,
              'v6e：918 TFLOPs bf16 / 1,638 GBps / 32 GB ——&#160;官方 v6e 规格表；'
              'H100 SXM：稠密 989.5 TFLOPs（数据表 1,979 带稀疏 ÷ 2）/ 3.35 TB/s / 80 GB ——&#160;官方数据表',
              '⚠️ 口径三连：H100 取稠密不取稀疏（差整一倍）；v6e 每 chip 只有 1 个 TensorCore，'
              'per-chip 即 per-device；四颗一律 bf16。B200 与 v7 两行沿用专题二 §1 已核过的数。')
    f.save("figx-1.svg", y + 6)


main()
