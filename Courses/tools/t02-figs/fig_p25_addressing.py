# -*- coding: utf-8 -*-
"""图 P-25 —— 跨卡写一个字节，发送方到底交出去什么。

**为什么补这张图。** 4.3 原来是全文唯一一个没有图的小节，而且偏偏是 TPU 侧 ——
GPU 侧（4.2）有两张红卡，TPU 侧一张没有。版面上这读起来像「这半边讲得不认真」，
而实际上 4.3 讲的东西一点都不次要：它是 4.2 末尾埋的 RDMA 语义的另一半。

**这张图要立的是「同一条约束，两种长相」，不是「谁更安全」。**
所以两栏必须回答**同一个问题** ——「发送方手里那张单子上写着什么」——
而不是各写各的机制。各写各的会变成两份特性清单，读的人只能比长短；
同一个问题两种答案，才看得见底下那条共同的约束。

**⚠️ 两栏的证据等级不一样，必须画出来。** RDMA 那半是公开语义；
ICI 寻址这半我没有找到可以公开引用的出处。本课的规矩是查不到就明写查不到 ——
所以 TPU 那栏挂一个「未标注来源」的角标，底带再说一次。
把两栏画得一样权威，就是在用版式撒谎。
"""
from common import Fig, para, BL, GN, RD, YL, INK, SUB, GREY, FILL

W = 1400
TOP = 84

COL_Y = TOP + 46
COL_H = 248
CW = 672
LX, RX = 20, 708

SLIP_H = 114                      # 「发送方手里那张单子」

SAME_Y = COL_Y + COL_H + 30
SAME_H = 82
BAND_Y = SAME_Y + SAME_H + 26
H = BAND_Y + 120

SIDES = [
    (LX, BL, "GPU 侧　·　RDMA", "跨域写远端内存",
     "公开语义",
     [("单子上写的是", "对方的<b>内存地址</b>"),
      ("但这个地址不是随便挑的",
       "那块内存必须<b>先被对方注册过</b>（memory registration）—— "
       "没注册过的地址写不进去。")],
     "发送方<b>不能</b>凭空写进对方的任意地址。"),
    (RX, GN, "TPU 侧　·　ICI", "机内机间同一套，2D / 3D 环面",
     "未标注来源",
     [("单子上写的是", "<b>哪颗芯片　＋　哪个段　＋　偏移</b>"),
      ("「段」是什么",
       "接收方<b>事先划出来、并且把编号告诉了发送方</b>的一块存储。"
       "发送方<b>只知道编号</b>，不知道它落在对方 HBM 的哪个物理位置 —— "
       "<b>段的物理基址握在接收方手里</b>。")],
     "发送方<b>不能</b>凭空写进对方的任意地址。"),
]


def build():
    f = Fig(W, H, "GPU 的 RDMA 与 TPU 的 ICI 在跨卡寻址上的对照："
                  "两边给使用者的约束是同一条，发送方都不能凭空写进对方的任意地址")
    f.title("跨卡写一个字节，<tspan font-weight=\"700\">发送方交出去的是什么</tspan>"
            "　—— 两种长相，同一条约束")
    f.legend([(BL, "GPU · RDMA（公开语义）"), (GN, "TPU · ICI（未标注来源）"),
              (YL, "两边落到同一句话的那一格")])
    for args in SIDES:
        _side(f, *args)
    _same(f)
    _band(f)
    return f.out()


# ══════════════════════════════════════════════════════════════════════
def _side(f, x, c, ttl, sub, grade, rows, floor):
    f.rect(x, COL_Y, CW, COL_H, FILL[c], c, 1.4, 10)
    f.t(x + 18, COL_Y + 27, ttl, "sec", c)
    f.t(x + 18, COL_Y + 46, sub, "xs", SUB)

    # 证据等级角标 —— 两栏的可引用性不一样，这件事要看得见，不能只写在底带
    gc = SUB if grade == "公开语义" else RD
    f.rect(x + CW - 132, COL_Y + 14, 114, 22, "#fff", gc, 1.1, 11)
    f.t(x + CW - 75, COL_Y + 29, grade, "xxs", gc, "middle")

    # 「单子」：一张白纸，两栏形状完全一样 —— 差别只在纸上写了什么
    f.rect(x + 18, COL_Y + 60, CW - 36, SLIP_H, "#fff", c, 1.1, 7)
    y = COL_Y + 84
    for k, (lbl, val) in enumerate(rows):
        f.t(x + 32, y, lbl, "xxs", GREY)
        y = para(f, x + 32, y + 18, CW - 64, val, "xs", 17) + (10 if k == 0 else 0)

    # 落到的那一句：两栏**逐字相同**，这是整张图的机关。
    # ⛔ 别在这下面再补一句「所以两边约束一样」—— 那正是底下黄带说的话，
    #    写两遍等于告诉读者「这张图的重点你自己找」。
    f.rect(x + 18, COL_Y + 60 + SLIP_H + 14, CW - 36, 44, "#fff", c, 1.4, 7)
    para(f, x + 32, COL_Y + 60 + SLIP_H + 40, CW - 64, floor, "sm", 18, fill=INK)


# ══════════════════════════════════════════════════════════════════════
def _same(f):
    f.rect(20, SAME_Y, 1360, SAME_H, FILL[YL], YL, 1.6, 10)
    f.t(38, SAME_Y + 28,
        "⭐ 两栏底下那句话是逐字相同的 —— 这张图要的就是这个", "sec")
    para(f, 38, SAME_Y + 54, 1324,
         "一边给地址、一边给段号，看着是两套东西；但<b>它们对使用者施加的约束是同一条</b>。"
         "至于两边是不是出于同一个设计动机（安全？地址虚拟化？多租户隔离？）—— "
         "<b>这是推断，没有哪份文档这么写。</b>", "xs", 19)


# ══════════════════════════════════════════════════════════════════════
def _band(f):
    f.rect(20, BAND_Y, 1360, 104, FILL[RD], RD, 1.4, 10)
    f.t(38, BAND_Y + 28, "⚠️ 这张图左右两半的证据等级不一样，别一起往外传", "sec")
    y = BAND_Y + 54
    for seg in [
            "<b>RDMA 那一半是公开语义</b>，没有问题。"
            "<b>ICI 寻址这一半我没有找到可以公开引用的出处</b> —— "
            "本课的规矩是查不到就明写查不到，所以它按<b>「未标注来源」</b>对待："
            "可以讲，但不要当成可引证的事实往外传。",
            "另有一处差别顺带记下：<b>TPU 这边没有面向用户的独立通信库</b> —— "
            "你不会 import 一个通信库，也不会调它的 API，"
            "<b>通信是编译器生成的</b>。这一条第 5 节会重新捡起来。"]:
        y = para(f, 38, y, 1324, seg, "xs", 19) + 4


if __name__ == "__main__":
    import io
    io.open("out/fig_p25_addressing.svg", "w", encoding="utf-8").write(build())
    print("ok fig_p25_addressing")
