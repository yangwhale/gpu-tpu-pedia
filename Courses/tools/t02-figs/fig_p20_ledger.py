"""图 P-20 —— 八笔撤回的台账，以及「它们朝哪边偏」这个问题的真实答案。

⛔ **这张图前后错了三次。第三次最值得讲，因为它错在台账本身。**

**错一：条长量的不是同一件事。**
第一版按「总寿命」排序、按「错误类型」着色，于是 `31.60%`（26 天）
和 `7,308`（16 天）看起来是同一类故障。**不是。**
`31.60%` 从出生（08-05）起分母就已经是那个虚构的 2,700，
而 2,700 直到 08-31 才被撤 —— 也就是说
**「上游撤了它还挂着」这个状态只存在了同一天之内**，另外 25.9 天里根本没有上游可跟。
真正经历过孤儿期的只有 `7,308`（08-16 → 08-31，**15 天**）。
所以现在每根条**分两段**：灰 = 上游还立着（或它自己就是源头）、红 = 上游已撤它还挂着。
**画出来之后，只有一根条有红段** —— 这削弱了「这是个常见故障」的说法，
但它换来一个更准的说法：**这个故障不常见，但一次就是 15 天。**

**错二：落点被它自己最长的那根条证伪。**
第一版的落点是「要复查的不是哪个数看起来可疑，是**哪个数最近有东西在它上游动过**」。
听着很利落 —— 但 `2,700`（50 天）**根本没有上游**，图上自己写着「它从来没有出处」。
这条规则只覆盖八笔里的两笔。抓到 2,700 靠的是「回查官方规格表」，
那是下一张甲格 ① 的动作。现在的落点改成诚实的版本：
**没有任何一个动作能抓到全部八笔 —— 这正是下一张要按来源分级的原因。**

⛔ **错三（真正严重的一个）：台账只记了五笔，而漏掉的三笔恰好方向相反。**

第一版的整张底带建立在一个观察上：**「五笔撤回全部利于 TPU」**，
并为此写了一套三步辩护（承认动机痕迹 / 但偏置方向与结论相反 / 真正该担心的是反面）。
**审计去数了一遍，`5/5` 这个数据本身是选出来的。**

`§6` 的正文自己写着：「下面三张图里的反面例子，**全部来自本仓库自己的文档** ——
一份 MFU 表整页偏高 11%、一次 run 同时挂着两个百分比、
一条调优收益里混着一项不属于调优的东西……**这几处是回查时自己发现并改掉的**」。
**三笔已公开承认的撤回，一笔都没进台账。** 理由是「它们在 §6，不在 §8」——
也就是**按图的边界记账，而不是按事实记账**。补上之后：

    八笔 · 利于 TPU 六笔 · 利于 GB300 两笔

而且那两笔不是勉强算的：`R-6a` 把 GB200 一整页的 MFU 抬高 11%，
`R-6b` 让一个 FP8 run 的头条 MFU 用 BF16 分母 ——
**恰好是 TPU 侧同类数字的反口径**（v7 的 FP8 一律按分母 4,614 报）。

⭐ **修正之后，这一节反而拿到了一个比原来那套辩护强得多的答案。**

**同一个正确值，错了两次，方向相反：**

  · `2,700 / 5,400` —— 写这一课（主角是 v7）时**猜高**了 GB300 的峰值 → 利于 TPU
  · `2,250 / 4,500` —— 写 GPU 那页（主角是 A4X）时**套错了机型**
    （那是 HGX B200 的峰值，官方同代不同封装差 11.1%）→ 利于 GB300
  · 两者的正确值**是同一个数**：`2,500 / 5,000`（GB300 与 GB200 的 BF16/FP8 峰值相同，
    Blackwell Ultra 提升的是 dense FP4 与 attention，不是这两项）

**所以偏向跟的不是「我想要的结论」，是「这份文档的主角是谁」。**
乐观总是朝着当前在写的那一侧偏 —— 这比「立场」更机械，也更好防：
**换个主角重读一遍自己的数**，比「保持客观」可执行。

⭐ **第 ③ 步那个担忧也被自己的记录证伪了两次。**
原来写的是「利于 GB300 的错没人有动机去找，已知唯一一处是 P-18 的 882.3」。
**已知的不是一处，是三处** —— 882.3 未跟进，加上 `R-6a`、`R-6b`
这两处**确实是自己找出来并改掉的**。所以现在能说的是更弱、但为真的一句：
这类错**更容易被放着**（882.3 至今没复测），而不是**没人会发现**。

⚠️ **两个必须写进图里的限定：**
  · `R-6b` 是**部分撤回** —— 表体那个 20.1% 至今仍按 BF16 峰值报，
    改掉的只是「没说这是哪个口径」。10.1% 现在并列写在表注里。
  · `R-6c` 只在**课件侧**撤回 —— 上游 `TUNING-v7.md:1398` 和
    `QUICKSTART-v7.md:46-51` 至今仍把 `dvfs_p_state=7 +8.6%` 直接摆进
    累计 +37.9% / +47.5%，没有「这一步不算软件」的标注。

数据出处（全部为本仓库 git 历史 / 文档，均已逐条核对）：
  · R-6a 生 `c79a635` 06-29，死 `732d47b` 08-31；A2 23.4% → 21.1%
  · R-6b 生 `4b09a45` 06-30，死 `732d47b` 08-31（部分）；v7 侧 FP8 分母见 `README.md:29`
  · R-6c 生 `181a8de` 08-11，死 `732d47b` 08-31（仅课件侧）
  · 2,700→2,500 / 5,000、2,250 的 SKU 归属：`Courses/tools/topic02-verified-specs.md:31-49`
  · 31.60%→34.16%：854.0 ÷ 2,500 ｜ 7,308→4,830 ｜ 1,014.8→637.0
"""
