            (RD, "① <tspan font-weight=\"700\">时刻毫无规律</tspan>　"
                 "——　挤在一起的有，隔很久才来一个的也有"),
            (RD, "② <tspan font-weight=\"700\">很晚了还会来</tspan>　"
                 "——　不是「开头不稳，稳了就没事」"),
