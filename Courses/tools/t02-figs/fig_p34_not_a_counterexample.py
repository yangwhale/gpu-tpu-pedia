def _cards(f):
    for i, (c, ttl, tag, a, b, cc) in enumerate(CARDS):
        x, w = 20 + i * 456, 438
        f.rect(x, CD_Y, w, CD_H, FILL[c], c, 1.6, 9)
        f.t(x + 16, CD_Y + 26, ttl, "box", c)
        f.t(x + w - 16, CD_Y + 26, tag, "xxs", SUB, anchor="end")
        y = para(f, x + 16, CD_Y + 52, w - 32, a, "xs", 18)
        y = para(f, x + 16, y + 10, w - 32, b, "xs", 18)
        f.line(x + 16, y + 8, x + w - 16, y + 8, c, 0.8, dash="3 3")
        para(f, x + 16, y + 28, w - 32, cc, "xs", 18)


