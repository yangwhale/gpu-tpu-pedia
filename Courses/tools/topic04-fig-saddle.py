# -*- coding: utf-8 -*-
r"""专题四 · §3.3「导数为零 ≠ 走不动了」——&#160;为什么梯度下降在高维里更好走

⭐⭐⭐ 2026-09-17 新画。现场原话：「梯度下降法这个是一切的本源，
  你一定要想办法把这个本源给讲清楚 ……让大家理解**为什么**梯度下降法可以」。
  ⛔ 上一格 `fig-descent` 老实交代了一件坏事：**落在哪个谷取决于起点，
    不保证是最低的那个。** 一维图上这件事看起来很吓人 ——&#160;
    一眼就能看见好几个坑，随便掉哪个都出不来。
  ⭐⭐ 这一格就是来接这句话的：**那个画面是一维骗你的。**

⭐⭐ 取法来自**李宏毅**（台大）《类神经网络训练不起来怎么办（一）：
  局部最小值与鞍点》。三条都从原投影片核过：
    · 导数为零的点统称 **critical point**，它分两类 ——&#160;
      local minima（走不了）和 **saddle point（还能走）**
    · 判据是 Hessian 的特征值：**全正才是局部最小**，有正有负就是鞍点；
      而且**沿着负特征值那个方向就能继续下降**
      （⚠️ 他原话补了一句 "this method is seldom used in practice" ——&#160;
      真实训练里没人去算 Hessian，靠的是动量和噪声）
    · 实验：训练到收敛于临界点，看 **minimum ratio ＝ 正特征值 ÷ 全部特征值**，
      原片结论是 **never reach a real "local minima"**

⛔⛔ 三条**没写进图**的克制，都是「绝不编」这条在管：
  ① **不画他那张实测散点图。** 我手上只有定性结论，照着记忆摆点就是伪造数据。
     Ⓒ 只画那根 minimum ratio 轴和「观测到的都停在 1 之前」这一个事实。
  ② **不给「高维里局部最小值有多罕见」配概率。** 「每个方向朝上朝下各半，
     d 维全朝上就是 2^-d」听起来很顺 ——&#160;但**特征值的符号并不独立**，
     这个数是假的。Ⓑ 只讲定义层面必然成立的那句：
     **要当谷底得所有方向都朝上，而只要有一个朝下就还能走。**
  ③ 李宏毅课上引了《三体Ⅲ·死神永生》里那个能在高维取物的魔法师作比。
     这个典故**只在出处里转述他的原话**，不在图上展开情节 ——&#160;
     小说细节我没核，而图上的主比喻用我们自己的：**垭口**。

⭐ 主比喻「垭口」是本讲自己的：**翻山的那个豁口，沿着路它是最高点，
  横着爬山脊它是最低点。** 中文管这个地形就叫「鞍部」——&#160;
  比喻和术语本来就是同一个东西，不用再架一层。

⭐⭐⭐ 落点接下一格：卡不住，不代表走得快。鞍点附近**坡极平、梯度极小**，
  朴素梯度下降会在那儿磨很久 ——&#160;而这正是后面 Adam 分母那一坨的用武之地
  （小梯度被除以一个同样小的数，反而放大）。李宏毅原片收尾也是这句：
  **smaller batch size and momentum help escape critical points。**
"""
from topic03_draw import (Fig, BL, OR, GR, RD, PU, GY, INK, GY2, LINE)

W = 1400


def main():
    f = Fig(W, "导数为零的点不止一种。要成为真正的谷底，必须所有方向都朝上；"
               "只要有一个方向朝下，它就是鞍点，顺着那个方向还能继续下降。"
               "一维图上只有两个方向可选，所以看起来到处是坑；"
               "而几千亿个参数就是几千亿个方向，"
               "要求它们全都朝上是个极其苛刻的条件。"
               "李宏毅课上的实测也支持这一点：训练收敛到的那些梯度为零的点，"
               "没有一个是真正的局部最小值。"
               "所以真正的麻烦不是卡住，是鞍点附近坡太平、走得太慢")

    y0 = f.header(
        "导数为零 ≠ 走不动了　——　<tspan font-weight=\"700\">"
        "上一格那个「掉进坑里出不来」，是一维骗你的</tspan>",
        "⭐ 这一格回答：<tspan font-weight=\"700\">"
        "为什么参数越多，梯度下降反而越走得通</tspan>",
        [(RD, "真谷底：走不了"), (GR, "鞍点：还能走"), (PU, "实测：没遇到过真谷底")])

    # ══════════ Ⓐ 导数为零的点，分三种 ═════════════════════════════
    PH = 420
    py = f.panel(0, y0, W, PH,
                 "Ⓐ 坡度为零的地方<tspan font-weight=\"700\">不止一种</tspan>"
                 "　——　看<tspan font-weight=\"700\">两个方向</tspan>就能分开", INK,
                 sub="⭐ 每一格画的是<tspan font-weight=\"700\">同一个点</tspan>，"
                     "只是沿两个不同方向切一刀看剖面")

    KINDS = (
        (RD, "真谷底（局部最小）", (+1, +1), "两个方向都往上",
         "⛔ 往哪走都变差 ——　真的卡住了"),
        (OR, "山顶（局部最大）", (-1, -1), "两个方向都往下",
         "⭐ 一推就走 ——　训练里基本遇不到"),
        (GR, "鞍点（垭口）", (+1, -1), "一个往上，一个往下",
         "✅ 顺着往下那个方向，接着走"),
    )

    CW, CGAP, X0 = 420, 40, 40
    for i, (col, name, signs, what, verdict) in enumerate(KINDS):
        x = X0 + i * (CW + CGAP)
        f.box(x, py + 40, CW, 300, "#fff", col, 8, sw=1.6)
        f.box(x, py + 40, CW, 4, col, col, 2)
        f.t(x + CW / 2, py + 76, name, col, True, 18, "middle")

        # 两个方向各切一刀 ——&#160;∪ 是「往这边走 loss 变大」，∩ 是变小
        for k, s in enumerate(signs):
            cx = x + 26 + k * 200
            base = py + 178
            # ⚠️⚠️ SVG 的 y **向下**长 ——&#160;这一晚已经在这上面栽过两次
            #   （`fig-spike` 的 loss 曲线画反、`fig-muon` 的圆弧画凹）。
            #   所以把换算写成一句话记在这儿：
            #     s=+1「往上」= 离开这点 loss 变大 = 中点在屏幕上**更低**
            #                = 中点 y **更大** → 控制点 **加** y。
            #   二次贝塞尔中点 =（P0 + 2·P1 + P2）÷ 4，所以控制点给 2 倍垂距。
            dy = 90 * s
            assert (s > 0) == (dy > 0), "往上/往下和 y 的方向对不上"
            f.path("M %.1f %.1f Q %.1f %.1f %.1f %.1f"
                   % (cx, base - 34, cx + 84, base - 34 + dy, cx + 168, base - 34),
                   col, 2.4, arrow=False)
            f.box(cx + 84 - 6, base - 34 + dy / 2.0 - 6, 12, 12, col, col, 6)
            f.t(cx + 84, base + 34, "方向 %d" % (k + 1), GY2, size=12.5,
                anchor="middle")
            f.t(cx + 84, base + 56, "往上 ↑" if s > 0 else "往下 ↓",
                col, True, 13, "middle")

        f.t(x + CW / 2, py + 286, what, INK, True, 15.5, "middle")
        f.t(x + CW / 2, py + 316, verdict, GY, size=13.5, anchor="middle")

    f.t(700, py + 372,
        "⭐⭐ 「垭口」就是鞍点：<tspan font-weight=\"700\">"
        "沿着翻山的那条路，它是整条路的最高点；横过来沿山脊走，它又是最低点。"
        "</tspan>　中文管这种地形叫<tspan font-weight=\"700\">鞍部</tspan>。",
        INK, size=14.5, anchor="middle")
    f._pan = None

    # ══════════ Ⓑ 方向一多，「真谷底」的门槛就高得离谱 ═══════════════
    PH2 = 366
    py2 = f.panel(0, py + PH + 20, W, PH2,
                  "Ⓑ ⭐⭐⭐ 要当<tspan font-weight=\"700\">真谷底</tspan>，"
                  "得<tspan font-weight=\"700\">所有</tspan>方向都朝上"
                  "　——　而只要有<tspan font-weight=\"700\">一个</tspan>朝下，就还能走", GR,
                  sub="⛔ 一维图上<tspan font-weight=\"700\">只有两个方向可选</tspan>")

    # ⭐⭐⭐ 2026-09-18 R21 重画。旧版是三个等高的框，每框四段文字 ——&#160;
    #   把字删掉只剩三个一样的框。
    #   ⭐⭐ 而这一格要讲的是一个**合取条件**：
    #     「方向数从 2 涨到几千亿，而要求是**全都**朝上」。
    #   ⭐⭐⭐ 合取条件的形状，就是**一排箭头**：
    #     箭头越多，「全都朝上」越难；而**只要有一个朝下，就有路**。
    #   ⛔ 三行用**同样的箭头大小和同样的间距** ——&#160;
    #     这样行的**长度**就等于方向的**个数**，比例是诚实的。
    #     （若各行用不同间距，读者会把「密度」误当成「数量」。）
    #   ⚠️ 但真实的数远画不下，所以每行都标出「图上画了几个」，
    #     最后一行直接画到边缘再加省略号 ——&#160;**画不下这件事本身就是论点**。
    AGAP, AH, AX = 9.0, 20.0, 132         # 箭头间距／高度／起点
    # ⛔ 左边那两行标签是 anchor="end"，AX 太小它们会顶出画布左缘。
    #   ⭐ 这是 fig4-saddle 那轮记的「右侧文字先算起点＋字数×字号」的**镜像版**
    #     ——&#160;左对齐的反面是右对齐，两头都要算。（第一版 AX＝96 就切掉了两个字。）
    assert AX - 14 - 7 * 15.5 > 8, "左边标签会顶出画布"
    ROOM = int((1290 - AX) / AGAP)        # 一行最多塞几个
    ROWS = (
        (RD, "一维图上", "2 个方向", 2, None,
         "⛔ 两个都朝上很容易凑齐 ——　所以那种图上坑一个接一个"),
        (OR, "一个小模型", "几万个方向", 40, None,
         "⚠️ 四十个全朝上已经很苛刻了　——　何况几万个"),
        (GR, "我们在谈的规模", "几千亿个方向", ROOM, 73,
         "✅ 只要漏掉一个，它就只是个垭口 ——　接着走"),
    )
    assert ROWS[2][3] > 100, "最后一行要真的画满，不然「画不下」这句就没画面"

    for i, (col, who, dirs, n, down_at, verdict) in enumerate(ROWS):
        ry = py2 + 52 + i * 96
        f.t(AX - 14, ry + 6, who, GY, size=13, anchor="end")
        f.t(AX - 14, ry + 26, dirs, col, True, 15.5, "end")
        for k in range(n):
            x = AX + k * AGAP
            if down_at is not None and k == down_at:
                # ⭐ 那唯一一个朝下的 ——&#160;这一格的落点全在它身上
                f.line(x, ry - 4, x, ry + AH + 6, RD, 2.4)
            else:
                f.line(x, ry + AH, x, ry, col, 1.3)
        xe = AX + n * AGAP
        if i == 2:
            f.t(xe + 6, ry + AH, "…", col, True, 18)
            f.t(AX, ry + AH + 30,
                "⛔ <tspan font-weight=\"700\">画到这儿就到头了</tspan>"
                "　——　真实的数再乘十亿倍，这一行根本画不下", GY2, size=12.5)
            f.line(AX + down_at * AGAP, ry - 22, AX + down_at * AGAP - 44, ry - 34,
                   RD, 1.4)
            f.t(AX + down_at * AGAP - 50, ry - 30,
                "<tspan font-weight=\"700\">只要有这一个</tspan>", RD, True, 13.5, "end")
        else:
            f.t(xe + 14, ry + AH - 2, "（图上画了 %d 个）" % n, GY2, size=12)
        if i == 2:
            # 跟「画到这儿就到头了」并排放右边 ——&#160;
            # 底下 py2+316 那句「这是定义层面的话」是原来就有的，不能压
            f.t(660, ry + AH + 30, verdict, col, size=13.5)
        else:
            f.t(AX, ry + AH + 28, verdict, GY, size=13.5)

    f.t(700, py2 + 316,
        "⚠️ 这是<tspan font-weight=\"700\">定义层面的话，不是概率论证</tspan>"
        "　——　各个方向的弯曲方向<tspan font-weight=\"700\">并不彼此独立</tspan>，"
        "所以这里不给「罕见到什么程度」配任何数字。",
        GY, size=13, anchor="middle")
    f._pan = None

    # ══════════ Ⓒ 实测：从没真正到过谷底 ═══════════════════════════
    PH3 = 282
    py3 = f.panel(0, py2 + PH2 + 20, W, PH3,
                  "Ⓒ ⭐⭐ 而这不只是推理　——　"
                  "<tspan font-weight=\"700\">量过</tspan>", PU,
                  sub="⭐ 把训练跑到梯度为零，再看这个点"
                      "<tspan font-weight=\"700\">有多少方向是朝上的</tspan>")

    AX0, AX1, AY = 200, 1180, py3 + 138
    f.line(AX0, AY, AX1 + 40, AY, GY2, 1.4)
    f.t(AX0 - 16, AY + 6, "0", GY2, size=13, anchor="end")
    f.t(AX1, AY + 34, "1", GY2, True, 14, "middle")
    # ⛔ 轴名原来挂在右端 AX1+46＝1226，16 个字直接顶出 1400 的画布右边。
    #   ⭐ 判据：**图里任何右侧的文字，落笔前先算一遍「起点 ＋ 字数 × 字号」。**
    #     这类越界渲染器不报错、SVG 也合法，只有版面 lint 抓得到。
    f.t(AX0, AY - 60, "横轴：朝上的方向占比（minimum ratio）", GY2, size=12.5)

    # 观测落在左中段；右端那一小截是「真谷底」，实测从没到过
    OBS0, OBS1 = AX0 + 90, AX0 + 640
    f.box(OBS0, AY - 40, OBS1 - OBS0, 40, "#f3e8fd", PU, 6)
    f.t((OBS0 + OBS1) / 2, AY - 14, "实际训练收敛到的点，都落在这一段",
        PU, True, 14.5, "middle")

    f.line(AX1, AY - 60, AX1, AY + 10, RD, 1.6, dash="4 3", arrow=False)
    f.t(AX1 + 14, AY - 66, "＝ 1　所有方向都朝上", RD, True, 14.5)
    f.t(AX1 + 14, AY - 40, "＝ 真正的局部最小值", RD, size=13)
    f.t(AX1 + 14, AY - 14, "⛔ 实测<tspan font-weight=\"700\">一次都没到过</tspan>",
        RD, True, 14.5)

    f.t((OBS0 + OBS1) / 2.0, AY + 34,
        "⭐ 换句话说：<tspan font-weight=\"700\">训练停下来的那些地方，"
        "总还剩一批方向是朝下的</tspan>", INK, size=14.5, anchor="middle")
    f.t((OBS0 + OBS1) / 2.0, AY + 60,
        "——　没走，不是因为没路，是因为坡太平了", GY, size=13, anchor="middle")

    f.t(700, py3 + 232,
        "⛔ <tspan font-weight=\"700\">这根轴是示意，不是实测散点</tspan>"
        "　——　只画「观测都停在 1 之前」这一个事实，原图见李宏毅投影片。",
        GY, size=13, anchor="middle")
    f._pan = None

    yb = f.band(py3 + PH3 + 20, "ok",
                "所以「梯度下降为什么可以」，最深的那半个答案是：参数越多，它越不容易真卡住",
                ("✅ <tspan font-weight=\"700\">好消息</tspan>："
                 "上一格那个「掉进浅坑出不来」的画面，"
                 "是<tspan font-weight=\"700\">一维特有的</tspan>。"
                 "维度一多，坡度为零的地方绝大多数只是垭口 ——&#160;"
                 "<tspan font-weight=\"700\">总还剩一个朝下的方向。</tspan>",
                 "⛔ <tspan font-weight=\"700\">坏消息</tspan>：卡不住，"
                 "<tspan font-weight=\"700\">不等于走得快</tspan>。垭口附近坡极平、"
                 "梯度极小，朴素梯度下降（步长 ∝ 斜率）会在那儿"
                 "<tspan font-weight=\"700\">磨很久</tspan>　——　"
                 "后面几格讲的那些优化器，一多半是在治这个。",
                 "⭐⭐⭐ 顺带回答一个常见困惑："
                 "「参数多不是更难训吗？」——&#160;显存和算力上是更难，"
                 "但**在「会不会卡死」这一项上恰恰相反**。"
                 "两件事各论各的，别混成一句「模型越大越难训」。"))

    yb = f.src(yb + 16,
               "📌 「critical point 分 local minima 与 saddle point」"
               "「判据是 Hessian 特征值全正与否」"
               "「沿负特征值方向可继续下降，但实践中很少这么做」"
               "「实测 never reach a real local minima」四条，取自"
               "<tspan font-weight=\"700\">李宏毅</tspan>2021《类神经网络训练不起来怎么办"
               "（一）：局部最小值与鞍点》投影片　——　"
               "<tspan font-weight=\"700\">已逐条核过原文，图是我们自己重画的。</tspan>",
               "⭐ 他课上还引了《三体Ⅲ·死神永生》里那个能在高维取物的魔法师作比，"
               "投影片原话是「从三维空间看它是封死的，在更高维度里并不是」。"
               "⛔ 小说情节我们没核，所以只转述这一句，不展开 ——&#160;"
               "图上的主比喻用我们自己的<tspan font-weight=\"700\">垭口</tspan>。",
               "⚠️ Ⓑ <tspan font-weight=\"700\">刻意不给概率</tspan>："
               "「每个方向朝上朝下各半，所以 d 维全朝上的概率是 2 的 −d 次方」"
               "这句话听起来很顺，但<tspan font-weight=\"700\">特征值的符号并不独立</tspan>，"
               "那个数是编的。只讲定义层面必然成立的部分。",
               "⭐ 原片收尾那句也在本讲别处出现："
               "<tspan font-weight=\"700\">更小的 batch 和动量都有助于逃离临界点</tspan>"
               "　——　噪声和惯性，正好是 `fig-batch` 与 Adam 那两格在讲的东西。")

    f.save("fig4-saddle.svg", yb + 14)


if __name__ == "__main__":
    main()
