"""图 P-15 —— 两边的实测：同一个模型、同一个规模、两边各自调到最好。

第 6 节立了规矩，这一张是把规矩用在真数上的第一步。
整张图只回答一个问题：**这 1.29 倍的差距，是硬件的还是软件的？**

  甲　两条共轴的条 —— 槽 = 各自的 BF16 峰值，填充 = 实测
  乙　把 1.29 拆成两段 —— 峰值 1.084 × 峰值以外 1.190

⛔ **这一格返工过第二次，而这次改的是结论本身，必须记下来。**

第一版乙格把第二段叫「**软件效率之比**」，落点写「差的不是硅片，是软件」。
审到第二轮才发现这是**用命名冒充证明**：

    MFU ≡ 实测 ÷ 峰值

所以 `854.0 ÷ 662.3 = (2500/2307) × (MFU 之比)` 对**任意两个数**都恒成立。
式子里唯一的经验内容是「峰值比只有 1.084」，剩下那 1.190 是**余项**，不是测量值。
而峰值 dense FLOPs 只是硬件的**一根轴** —— HBM 带宽、片上 SRAM、MXU 收缩维形状、
互联拓扑，**全部落在那个余项里**。

最硬的一击来自这门课自己：**§3.4 花了一整小节论证 `head_dim = 128`
在 v7 的 256 收缩维上只喂满一半、在 GPU 上一点不浪费**。
那是**纯硅片效应**，而它的表现形式恰恰是 MFU 偏低 ——
按第一版的叫法，它被算进了「软件」。

而且 §4.5 立过规矩：「一个走错路的对照项**比没有对照项更危险**，
它会让你以为自己排除了什么。」峰值 FLOPs 就是这样一个对照项。

改法：第二段改叫「**峰值以外**」，落点只说「这 1.19 不来自峰值差」。
「其中相当一部分是软件」这句话仍然能说，但它的证据是 **P-16 那条纯软件
爬升曲线**（v7 不换硬件涨了 44.9%），不是这个恒等式。
**这一改让 P-16 从配角变成全节最有分量的一格。**

**甲那两条是这张图的全部说服力来源，值得说清为什么这么画。**
如果只写「854 对 662」，读者拿到的是一个差值；
画成「峰值槽 + 实测填充」之后，同一屏里同时看得见三件事：

  · 两个槽的长度 —— 峰值；
  · 两段填充的长度 —— 吞吐；
  · **填充占槽的比例** —— 这就是 MFU，不用再单独解释一遍。

这是 P-14 右格那条「吞吐 = MFU × 峰值」在真数上的第二次出场 ——
同一个视觉语言，故意重复使用。

⚠️ **这张图返工过一次，而返工的原因本身成了图里最好的一格。**

第一版的落点写的是：「**两个槽几乎一样长（差 8.4%），两段填充差得多（差 29%）**，
图上这一眼就是这一节的结论。」渲染出来才发现**图上根本不是这样**：

    峰值之差   2,500 − 2,307 = 193.0 TFLOP/s
    实测之差   854.0 − 662.3 = 191.7 TFLOP/s

**在一根绝对刻度的轴上，这两段几乎一样长（36 px 对 36 px）。**
那句落点讲的是**比值**（8.4% 与 29%），画出来的却是**差值** ——
图与话在说两件事，而只要读者信图，他记住的就是「两边差不多」。

改法不是把图改成配合那句话，是**把这件事本身变成这一格的论点**：
两段一样长，可一段是 2,307 的 8.4%、另一段是 662 的 29%。
**差距要相除不能相减 —— 这张图正好给出一个看得见的理由**，
而且它顺势把乙格那个「1.084 × 1.190」为什么是乘法解释掉了。

⚠️ **乙格那两段为什么按对数切。** 1.084 和 1.190 是**相乘**的关系，
按 0.084 : 0.190 的比例切段等于把它们当成相加。
`ln(1.084) : ln(1.190) = 0.317 : 0.683`，这才是「一个乘积里各占多少」
的正确切法。图里标了这一句，因为这一节讲的就是这种一步换算别省。

⚠️ **底带那条「换个单位倍数就变」是本节最该带走的一条。**
按 TFLOP/s 算差 1.29 倍，按 tok/s 算差 1.31 倍。差的这 1.5% 不是测量误差 ——
是两边框架的分析式 FLOP 公式对同一个模型给出的答案不一样。

  v7 侧　662.3e12 ÷ 4,770 = **138.9 GFLOP/token**（本图两个数相除得来）
  GB300 侧　854.0e12 ÷ 6,242 = **136.8 GFLOP/token**

⚠️ 但**这两个数不能当成两边框架的「官方口径」**：实验日志 §3.9 修完 FLOP
统计 bug 之后直接记过一次 v7 侧是 **137.2**，与 GB300 的 136.8 只差 0.3%。
138.9 是从本图这两个数反推的，与 137.2 有 1.2% 出入，**未定位**。
所以图上只说「两边报数确实不完全一致」，不去断言差多少。
**token 是能数出来的，TFLOP/s 里还夹着一条公式** —— 这一条不受影响。

⚠️ **「两边都调到各自的墙上」这句话对 GB300 不成立，图上必须写出来。**
v7 侧确实撞墙（四个方向 8 格实验无一正收益）。但 GB300 侧自己的 27 组扫点表里，
**B4（EP 32 → 16）= 882.3 TFLOP/s / 6,450 tok/s，比 A1 高 3.3%，是那张表认定的
BF16 最优**，只是没有跟进复测，所以全仓库的对标基线一直用 A1 的 854.0。
**结论：本图这个 1.29 / 1.31 倍是下限，不是终值。** 换成 882.3 就是 1.33 / 1.35。

数据出处（全部来自本仓库，两边都是自己跑的）：
  · GB300 854.0 / 34.2% / 6,242 —— A4X Max 上 Hy3 27 组扫点表的 A1 行
    （首测 854.4，复现区间 854.2–856.6，±0.14%）
  · GB300 882.3 / 6,450 —— 同表 B4 行（EP16，其余与 A1 完全一致）
  · v7 662.3 / 28.71% / 4,770 —— v7 快速上手文档 §0 的最优配方行
    （2026-08-15，18 个 tile 配置参数 + pdbs 12 + dvfs 7，64 芯片实测）
  · 峰值 2,500 / 2,307 —— 见 P-12，两边都取官方 dense、per GPU / per chip
"""
import math
from common import Fig, para, BL, RD, GN, YL, PU, INK, SUB, LINE, GREY, FILL

W = 1400
TOP = 84

R1_Y = TOP + 40
R1_H = 452

AX, AW = 20, 836
BX, BW = 868, 512

BARX, BARW = 240, 470        # 甲：共轴条的起点与满程（对应 GMAX）
GMAX = 2500.0

BAND_Y = R1_Y + R1_H + 28
H = BAND_Y + 152

# (名字, 副标题, 峰值, 实测, MFU, tok/s, 其余口径, 颜色, 补注)
RUN = [("GB300 NVL72　64 GPU", "机型 a4x-max · 单 NVLink 域 16 节点",
        2500, 854.0, "34.2%", "6,242",
        "step 21.0 s　·　GBS 2048　·　TP1 PP2 VPP8 EP32 · MBS 1", BL,
        "<r><b>⚠️ 这一侧没到顶</b></r><g>：同一张扫点表里 EP 32→16 是 "
        "<b>882.3 / 6,450（+3.3%）</b>，未跟进复测。"
        "<r><b>所以下面所有倍数都是下限。</b></r></g>"),
       ("TPU v7　64 chips（4x4x4）", "128 device · 3D torus 一个切片",
        2307, 662.3, "28.71%", "4,770",
        "step 20.61 s　·　等效 GBS 1536　·　DP1×FSDP128 · pdbs 12 · dvfs 7", GN,
        "<g><b>这一侧撞墙了</b>：tile、XLA flag、SparseCore 卸载、推 batch "
        "四个方向共 8 格实验，<b>无一正收益</b>。</g>")]

# 乙：把 1.29 拆成两段（长度按对数切 —— 两项是相乘的）
# ⛔ 第二段叫「峰值以外」不叫「软件」—— 它是余项，非峰值的硬件差异也在里面。
G_HW = 2500 / 2307.0
G_SW = (854.0 / 2500) / (662.3 / 2307)
G_ALL = G_HW * G_SW
SEG = [("① 峰值之比　—— 能算清的那段", "2,500 ÷ 2,307", G_HW, RD,
        "<g>官方 dense BF16，两边都按 P-12 的口径取。<b>这一段不用调，买回来就是它。</b></g>"),
       ("② 峰值以外　—— 余项，不等于「软件」", "34.160% ÷ 28.708%", G_SW, BL,
        "<r><b>这不是量出来的，是除剩下的。</b></r>"
        "<g>软件在里面，<b>非峰值的硬件也在里面</b>：HBM 带宽、片上 SRAM、"
        "MXU 收缩维形状、互联拓扑。</g>")]


def build():
    f = Fig(W, H, "同一个模型在 GB300 与 TPU v7 上的实测：854.0 对 662.3 TFLOP/s；"
                  "1.29 倍的差距里峰值只占 1.084 倍，剩下的 1.19 是余项、不等于软件")
    f.title("两边的实测　—— <tspan font-weight=\"700\" fill=\"#1e8e3e\">"
            "同一个模型、同一个规模，两边各自调到目前的水位</tspan>")
    f.legend([(BL, "GB300 NVL72 · 64 GPU"), (GN, "TPU v7 · 64 chips"),
              (GREY, "浅槽＝该平台的 BF16 dense 峰值，深段＝实测"),
              (RD, "两段差值，长度几乎相同")])

    _runs(f)
    _split(f)
    _band(f)
    f.t(W - 20, H - 12,
        "同一个 Hunyuan3-295B-A21B（80 层 · 192 专家）· seq 4096 · 合成数据 · "
        "两边都不落盘 checkpoint（但重算策略不同，见 P-18 第 ③ 条）· "
        "两边都是我们自己跑的",
        "xxs", GREY, "end")
    return f.out()


# ══════════════════════════════════════════════════════════════════════
def _runs(f):
    f.rect(AX, R1_Y, AW, R1_H, "#fff", LINE, 1.2, 10)
    f.t(AX + 18, R1_Y + 26, "甲　·　两条共轴的条：槽是峰值，填充是实测", "sec")
    para(f, AX + 18, R1_Y + 46, 560,
         "<g>同一根绝对刻度的横轴。<b>下面那两段红色标注是这一格的重点</b>，"
         "别急着看数字。</g>", "xs", 16)
    f.t(AX + AW - 18, R1_Y + 50, "横轴：TFLOP/s（BF16 dense）　满程 = 2,500",
        "xxs", SUB, "end")

    BARTOP = R1_Y + 100                 # 第一条的上沿
    STEP = 92
    for i, (name, sub, peak, meas, mfu, toks, cfg, c, warn) in enumerate(RUN):
        by = BARTOP + i * STEP
        f.t(AX + 24, by + 12, name, "box", INK)
        f.t(AX + 24, by + 30, sub, "xxs", SUB)

        tw = BARW * peak / GMAX
        fw = BARW * meas / GMAX
        f.rect(AX + BARX, by, tw, 30, FILL[SUB], GREY, 1.0, 4)
        f.rect(AX + BARX, by, fw, 30, FILL[c], c, 1.8, 4)
        f.t(AX + BARX + fw + 10, by + 20, "%.1f" % meas, "numb", c)
        f.t(AX + BARX + tw + 10, by + 20, "峰值 %s" % format(peak, ","),
            "xxs", SUB)

        para(f, AX + 24, by + 52, AW - 60,
             "<b>MFU %s</b>　·　<b>%s tok/s / 计算单元</b>　·　%s"
             % (mfu, toks, cfg), "xs", 15)
        para(f, AX + 24, by + 70, AW - 60, warn, "xxs", 13)

    # ── 两段差：峰值之差 193.0，实测之差 191.7 —— 画在同一条基线上比长度 ──
    SY = R1_Y + 284                     # 差值带
    f.rect(AX + 18, SY, AW - 36, 66, FILL[SUB], LINE, 1.0, 8)

    def _gap(xa, xb, top, val, rel):
        f.line(xa, top, xa, SY + 22, RD, 0.9, None, "2 4")
        f.line(xb, top, xb, SY + 22, RD, 0.9, None, "2 4")
        f.rect(xa, SY + 22, xb - xa, 18, FILL[RD], RD, 1.6, 3)
        f.t((xa + xb) / 2, SY + 16, val, "num", RD, "middle")
        f.t((xa + xb) / 2, SY + 56, rel, "xxs", SUB, "middle")

    px = AX + BARX + BARW                       # 2,500
    pa = AX + BARX + BARW * 2307 / GMAX         # 2,307
    ma = AX + BARX + BARW * 662.3 / GMAX
    mb = AX + BARX + BARW * 854.0 / GMAX
    _gap(ma, mb, BARTOP, "实测差 191.7", "＝ 662.3 的 29%")
    _gap(pa, px, BARTOP, "峰值差 193.0", "＝ 2,307 的 8.4%")
    f.t(AX + 30, SY + 36, "同一条基线上比长度 →", "xxs", SUB)

    f.rect(AX + 18, R1_Y + 362, AW - 36, 72, "#fff", RD, 1.4, 8)
    yy = para(f, AX + 32, R1_Y + 384, AW - 64,
              "<b>⭐ 这两段在图上几乎一样长 —— 193.0 对 191.7 TFLOP/s。</b>"
              "<g>但一段是 2,307 的 <b>8.4%</b>，另一段是 662.3 的 <b>29%</b>。</g>",
              "xs", 17)
    para(f, AX + 32, yy + 4, AW - 64,
         "<r><b>差距要相除，不能相减。</b></r>"
         "<g>相减出来的两个数一样大，相除出来的差 3.4 倍 —— "
         "而下一格那个 <b>1.084 × 1.190</b> 之所以是乘法，理由就在这里。</g>",
         "xs", 17)


# ══════════════════════════════════════════════════════════════════════
def _split(f):
    f.rect(BX, R1_Y, BW, R1_H, "#fff", BL, 1.4, 10)
    f.t(BX + 18, R1_Y + 26, "乙　·　把这 1.29 倍拆开 —— 只拆得动一半", "sec")

    f.rect(BX + 18, R1_Y + 44, BW - 36, 44, FILL[BL], INK, 1.4, 8)
    f.t(BX + BW / 2, R1_Y + 72,
        "854.0 ÷ 662.3  =  1.29  =  1.084 × 1.190", "box", INK, "middle")

    # 分段条：长度按对数切，因为两项是相乘的
    LX, LW = BX + 24, BW - 48
    ly = R1_Y + 110
    tot = math.log(G_ALL)
    x = LX
    for name, expr, val, c, note in SEG:
        w = LW * math.log(val) / tot
        f.rect(x, ly, w, 34, FILL[c], c, 1.6, 4)
        f.t(x + w / 2, ly + 22, "%.3f" % val, "numb", c, "middle")
        x += w
    f.t(LX, ly + 52, "↑ 段长按对数切 —— 两项是相乘的，按 0.084 : 0.190 切就是"
                     "把乘法当成了加法", "xxs", SUB)

    y = R1_Y + 186
    for name, expr, val, c, note in SEG:
        f.rect(BX + 18, y, BW - 36, 68, "#fff", c, 1.4, 8)
        f.t(BX + 32, y + 22, name, "lbl", c)
        f.t(BX + BW - 32, y + 22, expr, "num", INK, "end")
        para(f, BX + 32, y + 40, BW - 64, note, "xxs", 13)
        y += 76

    f.rect(BX + 18, R1_Y + 344, BW - 36, 96, "#fff", RD, 1.4, 8)
    yy = para(f, BX + 32, R1_Y + 366, BW - 64,
              "<r><b>⚠️ 这个式子恒成立，所以它不是一个发现。</b></r>"
              "<g>因为 MFU ≡ 实测 ÷ 峰值，任意两个数都能这么拆。</g>", "xs", 17)
    para(f, BX + 32, yy + 2, BW - 64,
         "<g>它证明的只有一件事：<b>这 1.19 倍不来自峰值差</b>。"
         "至于它有多少来自软件 —— <r><b>这张图答不了，下一张才答。</b></r></g>",
         "xs", 17)


# ══════════════════════════════════════════════════════════════════════
def _band(f):
    f.rect(20, BAND_Y, 1360, 124, FILL[YL], YL, 1.4, 10)
    f.t(38, BAND_Y + 28,
        "⚠️ 换一个单位，倍数就变 —— 而变掉的那 1.5% 正好是第 6 节讲的那件事", "sec")
    y = BAND_Y + 54
    for seg in [
            "<b>按 TFLOP/s 算，GB300 是 v7 的 1.29 倍；按 tok/s 算，是 1.31 倍</b>"
            "<g>（6,242 ÷ 4,770）。两个数都对，差在<b>分子那条公式</b> ——"
            "同一个模型、同一条 token，两边的分析式 FLOP 公式给出的答案"
            "<b>差 1.5%</b>。</g>"
            "<r><b>差多少不重要，差本身才重要。</b></r>",
            "<r><b>token 是能数出来的，TFLOP/s 里还夹着一条公式。</b></r>"
            "<g>所以两个都报的时候，把 tok/s 放在前面。"
            "<b>这不是吹毛求疵：1.5% 在这里无关紧要，但它证明了那条公式确实是两边各写各的</b> ——"
            "下一次遇到的不一定还是 1.5%，而 P-13 甲格里那个漏白名单的例子是 5 倍。</g>"]:
        y = para(f, 38, y, 1324, seg, "xs", 19) + 4


if __name__ == "__main__":
    import sys
    open(sys.argv[1] if len(sys.argv) > 1 else "out/fig_p15_headtohead.svg",
         "w", encoding="utf-8").write(build())
