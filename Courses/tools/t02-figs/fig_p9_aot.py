# -*- coding: utf-8 -*-
"""图 P-9 —— 静态换回来的那一样：不占一张卡，先把账算清楚。

5.5 整节在算静态的**代价**。这一张是账单的另一半。

论点的支点只有一句：**形状是编译期常量** —— 5.5 说的就是这个，
只不过那一节讲的是它的反面（换形状＝换程序，所以要收费）。
这一张讲正面：**既然编译期什么都知道，编译期就能回答问题。**

三格分别回答三个问题，缺一格论点就塌：

  甲　凭什么不用卡        —— 只造张量的形状，从不真的把张量造出来
  乙　算出来的是什么      —— 每个 device 的一本显存账，判 OOM 只看其中一项
  丙　凭什么信它          —— 跟真机打印的数逐位吻合

⚠️ **最容易讲错的地方，是把它讲成「省编译时间」。** 那是错的，
而且错得很自然 —— 「提前编译」这四个字就在引导人往那儿想。
真机上编译只要 46 秒，占启动的 1/5。**它省的是「排队 → 抢到卡 →
发现装不下 → 重排队」这个小时级的循环。** 所以落点带专门用来打掉它。

⚠️ **单位口径 —— 这张图返工过一次，教训记在这里。**
第一版把 94.74 写成十进制 GB，错的。**94.74 是 GiB**：v7 每芯片 192 GiB
÷ 2 device = 95.93，扣掉约 1.2 GiB runtime 自留 = 94.74 —— 第 0 节推过这三步，
第 4 节也是这么写的。

坑在于**源记录里那本显存账是用十进制 GB 记的**（字节 ÷ 1e9），
而编译不过时编译器报的那个数是 GiB。**同一张表里两种单位，差 7.4%。**
照着源记录直接比，余量会算多、flag 的收益会算少。
**所以这张图整表换算成 GiB**（80.48 GB → 74.95 GiB），跟上限同口径。
"""
from common import Fig, para, BL, RD, GN, YL, PU, INK, SUB, LINE, GREY, FILL

W = 1400
TOP = 84

R1_Y = TOP + 40
R1_H = 460
AX, AW = 20, 636
BX, BW = 676, 704

R2_Y = R1_Y + R1_H + 28
R2_H = 190

BAND_Y = R2_Y + R2_H + 28
H = BAND_Y + 136

# ── 甲：凭什么不用卡 ────────────────────────────────────────────
# 画成一条链，是因为要说的就是「哪一环被替换掉了」——
# 只有第二环是假的，其余全是真的走了一遍。
CHAIN = [
    (GN, "配置文件", "模型、并行策略、batch、remat、XLA flag ——\n跟真会跑的那份<b>一字不差</b>"),
    (RD, "一副假的设备网格", "唯一被替换掉的一环。\n<b>告诉编译器「有 64 芯片、拓扑长这样」</b>"),
    (GN, "只造形状，不造张量", "<b>编译这一步本来就只看形状和 dtype</b>，值不参与 ——\n所以这一环<b>跟真机一模一样</b>，省掉的只是把数填进去"),
    (GN, "XLA 完整走一遍", "图优化、降到机器码、分配显存 ——\n<b>这一步没有任何东西是假的</b>"),
]

# ── 乙：一本显存账 ──────────────────────────────────────────────
# 单位统一走 GiB —— 编译器报 OOM 那条 94.74 就是 GiB，同口径才能比。
# 源记录里这几项是按字节 ÷ 1e9 记的（temp 写作 80.48），差 7.4%，别抄错。
MEM = [
    ("argument_size", 21.75, SUB, "输入：权重 ＋ 优化器状态的本地分片"),
    ("output_size", 21.75, SUB, "输出"),
    ("temp_size", 74.95, RD, "临时／scratch —— <b>判 OOM 只看这一项</b>"),
    ("generated_code", 0.27, SUB, "代码本身"),
    ("host_temp_size", 29.62, SUB,
     "host 侧临时（offload 用）—— <b>不占 device HBM，不受上面那条线管</b>"),
]
LIMIT = 94.74
MSCALE = 100.0

# ── 丙：凭什么信它 ──────────────────────────────────────────────
MATCH = [("temp（pdbs=12）", "74.95", "75.0"),
         ("temp（pdbs=13）", "73.11", "73.1"),
         ("argument", "21.75", "21.7"),
         ("host temp", "29.62", "29.6")]


def build():
    f = Fig(W, H, "AOT 提前编译：在普通 CPU 上为手上没有的 TPU 拓扑编译训练步，"
                  "得到每个 device 的显存分解，并与真机打印的数字逐位吻合")
    f.title("静态换回来的那一样　—— <tspan font-weight=\"700\" fill=\"#1e8e3e\">"
            "不占一张卡，先把账算清楚</tspan>")
    f.legend([(GN, "真的走了一遍"), (RD, "被替换掉的那一环／要盯的那个数")])

    _chain(f)
    _mem(f)
    _match(f)
    _band(f)
    f.t(W - 20, H - 12,
        "实测：Hunyuan3-295B-A21B（80 层）· 目标 64 芯片 · 一台普通 CPU 机器 · "
        "单个探针约 2 分钟；含存产物上传的全流程约 5 分钟",
        "xxs", GREY, "end")
    return f.out()


# ══════════════════════════════════════════════════════════════════════
def _chain(f):
    f.rect(AX, R1_Y, AW, R1_H, "#fff", LINE, 1.2, 10)
    f.t(AX + 18, R1_Y + 26, "甲　·　凭什么不用卡", "sec")
    para(f, AX + 18, R1_Y + 46, AW - 36,
         "<g>四环里<b>只有一环是假的</b>，其余三环跟真机上一模一样。</g>", "xs")

    y = R1_Y + 62
    for i, (c, name, body) in enumerate(CHAIN):
        f.rect(AX + 18, y, AW - 36, 50, FILL[c], c, 1.2, 8)
        f.t(AX + 32, y + 21, name, "box", c)
        yy = y + 21
        for seg in body.split("\n"):
            yy = para(f, AX + 210, yy, AW - 246, seg, "xs", 15)
        if i < len(CHAIN) - 1:
            f.line(AX + AW / 2, y + 50, AX + AW / 2, y + 70, SUB, 1.4, "aK")
        y += 70

    f.rect(AX + 18, R1_Y + 346, AW - 36, 86, "#fff", GN, 1.2, 8)
    para(f, AX + 32, R1_Y + 372, AW - 64,
         "<b>这就是 5.5 那句话的正面。</b>那一节说「形状是编译期常量，所以换形状要收费」；"
         "<b>反过来，编译期既然什么都知道，编译期就能回答问题。</b>"
         "<r>代价和红利是同一件事的两面。</r>", "xs", 16)


# ══════════════════════════════════════════════════════════════════════
def _mem(f):
    f.rect(BX, R1_Y, BW, R1_H, FILL[RD], RD, 1.4, 10)
    f.t(BX + 18, R1_Y + 26,
        "乙　·　算出来的是<tspan font-weight=\"700\" fill=\"#d93025\">每个 device 的一本账</tspan>", "sec")
    para(f, BX + 18, R1_Y + 46, BW - 36,
         "<g>单位 <b>GiB</b> —— <b>跟编译器报 OOM 那条 94.74 同一个口径，可以直接比</b>。</g>", "xs")

    lx, lw = BX + 148, BW - 148 - 210

    # 上限线先画，后面的条压在它上面就能一眼看出谁顶到了
    ll = lx + lw * LIMIT / MSCALE
    f.line(ll, R1_Y + 64, ll, R1_Y + 248, INK, 1.6, dash="5 4")
    f.t(ll + 6, R1_Y + 76, "94.74", "num", INK)
    f.t(ll + 6, R1_Y + 90, "GiB／device", "xxs", INK)

    y = R1_Y + 72
    for name, v, c, desc in MEM:
        # host 那项走主机内存，不归上面那条 device 上限管。画在同一根轴上、
        # 压在同一条线下，等于坐标轴本身在误导 —— 隔一道线，条画成空心。
        host = name.startswith("host")
        if host:
            f.line(BX + 18, y - 6, BX + BW - 18, y - 6, LINE, 1)
        f.t(BX + 18, y + 13, name, "lbl", c if c == RD else INK)
        f.rect(lx, y + 3, max(lw * v / MSCALE, 2), 15,
               "#fff" if host else c, SUB if host else None, 1 if host else 0, 3)
        f.t(lx + lw * v / MSCALE + 8, y + 15, "%.2f" % v, "num", c)
        para(f, BX + 18, y + 29, BW - 36, "<g>%s</g>" % desc, "xxs", 13)
        y += 44

    f.rect(BX + 18, R1_Y + 296, BW - 36, 104, "#fff", RD, 1.2, 8)
    yy = para(f, BX + 32, R1_Y + 320, BW - 64,
              "<r>判 OOM 只看 temp_size，别把 argument 加进去。</r>"
              "早期那个「argument ＋ temp ＋ 代码」的公式<b>偏保守，"
              "会把跑得动的配置误判成 OOM</b>。<b>原因是 argument 里有 21.75 GiB "
              "跟输出是同一块内存（别名）</b>，两笔不能相加。", "xs", 16)
    para(f, BX + 32, yy + 4, BW - 64,
         "<b>temp 是 argument 的 3.4 倍</b> —— 这个配置的显存大头"
         "<b>不是权重，是激活和 scratch</b>。"
         "<g>想省显存该动 remat 和 batch，不是去切权重。</g>", "xs", 16)

    # 边界要跟能力放在同一格里 —— 分开放，听众只会记住能力那一半。
    f.rect(BX + 18, R1_Y + 410, BW - 36, 38, "#fff", GREY, 1.2, 8)
    para(f, BX + 32, R1_Y + 432, BW - 64,
         "<b>⚠️ 这本账里没有「跑多快」。</b>"
         "<g>AOT 只回答装不装得下、编不编得过，一个吞吐数字都给不了。</g>", "xs")


# ══════════════════════════════════════════════════════════════════════
def _match(f):
    f.rect(20, R2_Y, 1360, R2_H, FILL[GN], GN, 1.4, 10)
    f.t(38, R2_Y + 26,
        "丙　·　凭什么信它　—— <tspan font-weight=\"700\" fill=\"#1e8e3e\">"
        "在真机打印的精度内完全吻合</tspan>", "sec")
    para(f, 38, R2_Y + 46, 1324,
         "<g>同一份配置：左边是 CPU 上算出来的，右边是 64 芯片真跑起来之后自己打印的。"
         "<b>左边这几个数就是乙格那本账</b>，同一个口径（GiB）—— "
         "所以丙格证的不是「又量了一遍」，是<b>「AOT 算的 ＝ 真机得到的」</b>。</g>", "xs", 16)

    cw = 316
    for i, (name, aot, real) in enumerate(MATCH):
        x = 38 + i * (cw + 12)
        f.rect(x, R2_Y + 84, cw, 62, "#fff", GN, 1.2, 8)
        f.t(x + 14, R2_Y + 104, name, "lbl", INK)
        f.t(x + 14, R2_Y + 132, "AOT 算的", "xxs", SUB)
        f.t(x + 96, R2_Y + 134, aot, "numb", INK)
        f.t(x + 168, R2_Y + 132, "真机打的", "xxs", SUB)
        f.t(x + 250, R2_Y + 134, real, "numb", GN)

    para(f, 38, R2_Y + 170, 1324,
         "<b>它给的不是估算，就是编译器在真机上会得到的同一份账</b>"
         "<g>（因为算这份账的本来就是同一个编译器）。"
         "⚠️ 但能说的只到这儿 —— <b>真机那栏只打三位有效数字</b>，推不出「一个字节都不差」。"
         "真正的字节级证据是另一组：同一份配置在两台机器上编，产物 md5 一模一样。</g>", "xs")


# ══════════════════════════════════════════════════════════════════════
def _band(f):
    f.rect(20, BAND_Y, 1360, 108, FILL[YL], YL, 1.4, 10)
    f.t(38, BAND_Y + 28, "⚠️ 关于 AOT 最容易说错的一句：它不是用来省编译时间的", "sec")
    y = BAND_Y + 54
    for seg in [
            "「提前编译」这四个字会把人往那儿引，但账不是那么算的："
            "<b>64 芯片上真机编译只要 46 秒</b>，而启动到第一步一共 227 秒 —— "
            "<r>编译只占 1/5</r>。<b>带上预编译产物：227 秒 → 175.6 秒，省 51 秒</b>"
            "<g>（编译本体 46 秒换成加载 400 MB 产物的 2.15 秒；余下约 8 秒源记录没拆，这里也不硬凑）</g>。",
            "<b>它真正省掉的是这个循环：排队 → 抢到 64 张卡 → 跑起来发现装不下 → 退出 → 重排队。</b>"
            "<r>那是小时级的，而且占着别人的容量。</r>"
            "<b>一次探针约两分钟、一台普通 CPU 机器 —— 每换一次配置就跑一遍，没有理由省。</b>"]:
        y = para(f, 38, y, 1324, seg, "xs", 19) + 4


if __name__ == "__main__":
    import sys
    open(sys.argv[1] if len(sys.argv) > 1 else "out/fig_p9_aot.svg",
         "w", encoding="utf-8").write(build())
