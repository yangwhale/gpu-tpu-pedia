from topic03_draw import (Fig, BL, OR, GR, RD, PU, GY, INK, GY2, LINE)

W = 1400

# ⭐ 示意曲线：**尖峰的位置是手挑的，挑的原则只有一条 ——「看不出规律」**。
#   论文说 spike 出现在极不规则的时刻，所以这里刻意不等距、不递增、不成组。
#   ⛔ 别用随机数生成：同一份源码每次构建要画出同一张图。
SPIKES = (0.07, 0.11, 0.19, 0.205, 0.31, 0.36, 0.48, 0.505, 0.52,
          0.61, 0.66, 0.74, 0.78, 0.795, 0.83, 0.87, 0.905, 0.93, 0.955, 0.98)
assert len(SPIKES) == 20, "论文说的是「大约 20 次」，图上就画 20 个"
# 相邻间距的最大值要比最小值大一个量级以上，否则「不规则」这件事画不出来
_gaps = [b - a for a, b in zip(SPIKES, SPIKES[1:])]
assert max(_gaps) / min(_gaps) > 8, "间距太均匀了，看着像有规律 —— 重挑"


def _loss_y(t, top, bot):
    """loss 主干：t∈[0,1] → 像素 y。

    ⛔ 2026-09-17 第一版画反了 ——&#160;两条曲线都在往上爬。
      根因：**SVG 的 y 轴朝下，而 loss 朝下是「变好」。** 两个「朝下」
      指的是相反的方向，脑子里一顺手就写反了。
      ⭐ 判据：**凡是把一个「越小越好」的量画成图，都先问一句
        「屏幕上往下是变好还是变差」** ——&#160;这类错不会报错，
        图照样画得出来，而且看上去像一条正经曲线。
    """
    loss = 0.12 + 0.88 * (1.0 - t) ** 1.7        # 1.0 → 0.12，单调下降
    return top + (bot - top) * (1.0 - loss)      # loss 大 → y 小（屏幕上高）


# 自检：开头必须比结尾**高**（屏幕上 y 更小）
assert _loss_y(0.0, 100.0, 300.0) < _loss_y(1.0, 100.0, 300.0), "曲线画反了"


