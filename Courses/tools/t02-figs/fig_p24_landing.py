def _fork(f):
    f.rect(AX, R1_Y, AW, R1_H, "#fff", LINE, 1.2, 10)

    # ── 一个提问 ──
    f.rect(AX + 178, QY, 644, 50, FILL[BL], BL, 1.8, 10)
    f.t(AX + 500, QY + 21, "整门课只有一个决定要问", "xxs", BL, "middle")
    f.t(AX + 500, QY + 40,
        "运行时才知道的那些事（形状、访问落在哪、谁忙谁闲），交给谁处理？",
        "box", INK, "middle")

    # ── 两条分支：竖下来 → 横过去 → 再竖下去带箭头扎进分支框 ──
    for sx, tx, c, mk in ((AX + 400, LCX + CWD // 2, RD, "aR"),
                          (AX + 600, RCX + CWD // 2, GN, "aG")):
        f.path("M%d %d L%d %d L%d %d L%d %d"
               % (sx, QY + 50, sx, BRY - 22, tx, BRY - 22, tx, BRY - 3),
               c, 1.8, "none", mk)

    for cx, c, big, sub in (
            (LCX, RD, "交给硬件，在运行时处理", "—— 也就是交给了人"),
            (RCX, GN, "交给编译器，在编译期算准", "—— 也就是接受它的脾气")):
        f.rect(cx, BRY, CWD, 54, FILL[c], c, 1.8, 9)
        f.t(cx + CWD // 2, BRY + 23, big, "box", c, "middle")
        f.t(cx + CWD // 2, BRY + 42, sub, "xxs", SUB, "middle")

    # ── 三条后果 ──
    # 两条通到底的浅色带：把分支框的红／绿一路拖下来。
    # 上一版这里是「隔行浅灰」—— 行分开了，但**列的身份在分支框下面就断了**，
    # 读者要靠左右位置去记哪边是谁。颜色连续下来就不用记。
    # 题面保持中性（它是问两边的），只有**答案格**染色；
    # 左边那条色轨通到底，负责把三格串成一列。
    TOTAL = RH * len(CONS)
    for cx, c in ((LCX, RD), (RCX, GN)):
        f.rect(cx - 10, ROWY - 4, 4, TOTAL - 4, c, None, 0, 2)

    y = ROWY
    for i, (q, l, r, ref) in enumerate(CONS):
        for cx, c in ((LCX, RD), (RCX, GN)):
            f.rect(cx - 10, y + 34, CWD + 20, RH - 44, FILL[c], None, 0, 6)
        f.t(AX + 26, y + 20, q, "lbl", INK)
        f.t(AX + AW - 26, y + 20, ref, "xxs", GREY, "end")
        f.line(AX + 26, y + 28, AX + AW - 26, y + 28, LINE, 1.0)
        para(f, LCX + 10, y + 48, CWD - 30, l, "xs", 17)
        para(f, RCX + 10, y + 48, CWD - 30, r, "xs", 17)
        # 行与行之间在中缝上串一支箭头：② ③ 的题面已经写了「所以，」，
        # 这支箭头是它的图形版 —— 三行是一条推理链，不是三个并列条目。
        if i < len(CONS) - 1:
            f.line(AX + 500, y + RH - 20, AX + 500, y + RH + 22, GREY, 1.5, "aK")
        y += RH


