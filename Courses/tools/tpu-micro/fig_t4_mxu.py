"""图 T-4 —— MXU：256×256 到底意味着什么，以及数在阵列里怎么流。

两件事要讲清楚：

1. **脉动是什么意思。** 不是「一次性把 256×256 个乘法做完」，而是数据像波一样
   斜着穿过阵列 —— 同一条反对角线上的 cell 在同一拍工作。这解释了为什么
   一次矩阵乘的**延迟**远大于 1 拍，而**吞吐**又能做到每拍一整列。

2. **256 是粒度不是上限。** K 比 256 大就多走几趟，一点不浪费；K 比 256 小
   才是真浪费 —— 而这正是 `head_dim=128` 打 TPU 却不打 GPU 的原因。

峰值那条链是官方给的，不是推的：262,144 FLOP/周期/MXU × 2.2 GHz × 4 MXU。
但「每 cell 2 次乘加」在硅上怎么实现，公开资料答不了 —— 图上如实标出来。
"""
from common import Fig, para, BL, RD, YL, GN, PU, TL, INK, SUB, GREY, FILL
import gate

W = 1400
TOP = 84

N = 16                       # 画 16×16 代表 256×256（每格 = 16×16 个 cell）
CELL = 19.0
AX, AY = 130, 196            # 阵列左上角
ASIDE = N * CELL

RX = 640                     # 右栏
# 下半部分必须让到阵列那三段说明文字之后。最后一段是三行 × 16px，
# 起点 +194 → 结束 ~+242，而节标题画在 BOT_Y − 26，所以 BOT_Y 至少要 +300。
BOT_Y = AY + ASIDE + 300
H = BOT_Y + 232


def build():
    f = Fig(W, H, "TPU v7 MXU 脉动阵列：权重驻留、激活横向流入、部分和纵向下移；"
                  "同一条反对角线上的单元在同一拍工作")
    f.title("MXU　—— 256×256 的阵列里，数是斜着穿过去的", "第 4 / 8 张")
    f.legend([(GN, "乘加单元（权重驻留其中）"), (BL, "激活：从左边进，每拍前进一列"),
              (RD, "部分和：向下累加，最后落进累加器"),
              (GREY, "灰色 ＝ 这一拍还没轮到")])

    _array(f)
    _cards(f)
    _fill(f)
    return f.out()


# ══════════════════════════════════════════════════════════════════════
def _array(f):
    f.t(20, TOP + 26, "一次矩阵乘在阵列里的样子　—— 第 16 拍的快照", "sec")
    para(f, 20, TOP + 46, 600,
         "颜色深浅表示这个单元<b>什么时候开始干活</b>：左上角最早，右下角最晚。"
         "同一条<r>反对角线</r>上的单元在同一拍工作 —— 这就是「脉动」两个字的意思。", "xs", 15)

    WAVE = 15                                     # 当前快照的波前（r + c）
    for r in range(N):
        for c in range(N):
            d = r + c
            if d > WAVE:
                fill, st = "#fff", "#e8eaed"
            else:
                # 越早启动的越深，形成从左上到右下的渐变
                op = 0.16 + 0.62 * (1 - d / max(WAVE, 1))
                fill, st = f"rgba(30,142,62,{op:.2f})", GN
            f.rect(AX + c * CELL, AY + r * CELL, CELL - 1.6, CELL - 1.6,
                   fill, st, 0.6, 1.5)
    # 波前那条线
    f.path(f"M{AX + (WAVE + 1) * CELL} {AY} L{AX} {AY + (WAVE + 1) * CELL}",
           RD, 2.2, dash="5,3")
    f.t(AX + ASIDE - 4, AY + ASIDE + 4, "← 第 16 拍的波前", "lbl", RD, "end")

    f.rect(AX - 6, AY - 6, ASIDE + 12, ASIDE + 12, "none", GN, 2, 4)
    f.t(AX - 6, AY - 16, "一个 MXU　256 × 256", "box", GN)
    f.t(AX + ASIDE + 6, AY - 16, "图上 1 格 ＝ 16 × 16 个真实单元", "xxs", None, "end")

    # 左侧：激活流入。左边只留 110px，塞不下说明文字 ——
    # 上一版硬塞进去，文字直接压在箭头上。说明挪到下方正文里。
    for r in range(0, N, 2):
        y = AY + r * CELL + CELL / 2
        f.line(AX - 52, y, AX - 10, y, BL, 1.4, marker="aB")
    f.t(AX - 56, AY + ASIDE / 2 - 8, "激活", "box", BL, "end")
    f.t(AX - 56, AY + ASIDE / 2 + 8, "逐行进入", "xxs", BL, "end")

    # 顶部：权重驻留
    f.t(AX, AY - 34, "权重：预先载入，整趟计算期间<b>驻留不动</b>"
        .replace("<b>", "").replace("</b>", ""), "xs", GN)

    # 底部：部分和落进累加器
    for c in range(0, N, 2):
        x = AX + c * CELL + CELL / 2
        f.line(x, AY + ASIDE + 10, x, AY + ASIDE + 40, RD, 1.4, marker="aR")
    f.rect(AX, AY + ASIDE + 44, ASIDE, 34, FILL[RD], RD, 1.4, 6)
    f.t(AX + 10, AY + ASIDE + 65, "累加器　128 个 · 形状 (8, 256) · 32 bit", "lbl", RD)

    para(f, 20, AY + ASIDE + 96, 600,
         "激活<b>一行一行从左边进来，每拍往右挪一列</b>；第 r 行比第 0 行晚 r 拍到齐。"
         "部分和则沿着列往下累加，走到底就落进累加器。", "xs", 16)
    para(f, 20, AY + ASIDE + 140, 600,
         "<b>延迟和吞吐是两回事。</b>一个数从进阵列到出结果要走满 2N−1 拍 —— "
         "对 256×256 就是 <b>511 拍</b>。但阵列一旦灌满，<r>每一拍都有一整列结果落地</r>。"
         "所以矩阵越大越划算：填满流水线的那 511 拍被摊薄了。", "xs", 16)
    para(f, 20, AY + ASIDE + 194, 600,
         "反过来说，<r>小矩阵在 TPU 上格外亏</r>：算一个 256×256×256 的乘法，"
         "光是灌满和排空流水线就占掉一半时间。这是 §7 那条「编译器必须提前排班」"
         "的物理根源之一。", "xs", 16)


