# -*- coding: utf-8 -*-
r"""专题六 · 第十四节「第一天的八问」：接手一个推理服务，第一天按顺序问的八件事。

⭐ 回答的问题：一个陌生模型、一批陌生的卡、一份 SLO 摆在面前，先问什么、后问什么？
   八张卡片按问的顺序排，每张写：问题、拿什么回答、回哪一节。
   颜色对主线三类：灰 ＝ 校准尺子；蓝 ＝ 让一趟分给更多 token；绿 ＝ 少搬；橙 ＝ 把活拆开放对地方。
⛔ 数字：这张图没有承重数字。顺序是本课归纳（先定口径和负载，再定放不放得下，最后才调招数）。
⛔ 刻意没画：每一问的具体阈值（各节里有，挪到这里会和各节打架）。
"""
from topic03_draw import Fig, BL, OR, GR, GY, INK

W = 1400
Q = [
    (GY, "负载长什么样？", "输入／输出长度分布、并发|SLO：TTFT、单用户 tok/s", "第二节"),
    (GY, "用哪把尺子？", "每卡还是总量|output 还是 total|在哪个交互档位比", "第二节"),
    (GR, "一步至少搬多少字节？", "（激活权重 ＋ 全部 KV）÷ 带宽|＝ 每步时间的下限", "第一、五节"),
    (BL, "放得下几条序列？", "（HBM − 权重）÷ 每条序列的 KV|＝ batch 上限", "第三、十节"),
    (BL, "attention 怎么切？", "KV 头少，TP 会复制 KV：用 DEP|上下文很长，再加 DCP", "第六、七节"),
    (OR, "拆不拆 PD，配几台？", "看输入输出比和 TTFT 目标|多一台 prefill，先买到的是 TTFT", "第八、九节"),
    (GR, "投机和量化开不开？", "并发小时投机最赚|权重字节就是步时下限，量化直接减", "第十一、十二节"),
    (GY, "上线前跑通了吗？", "形状分桶、编译缓存|冷启动、路由健康检查", "第十三节"),
]
assert len(Q) == 8


def fig_eight():
    f = Fig(W, "第一天的八问：按顺序问负载、口径、字节下限、batch 上限、attention 切法、"
               "PD 拆分与配比、投机与量化、上线准备，每一问标出用什么回答和回哪一节")
    y0 = f.header("第一天的八问　——　<tspan font-weight=\"700\">先定尺子和账，再挑招数</tspan>",
                  "按问的顺序从左到右、从上到下。颜色 ＝ 这一问属于主线的哪一类",
                  [(GY, "校准尺子 ／ 上线"), (BL, "分给更多 token"), (GR, "少搬"), (OR, "拆开放对地方")])
    CW, CH, GX, GY_ = 320, 124, 24, 20
    X0 = (W - 4 * CW - 3 * GX) / 2
    for i, (col, q, how, sec) in enumerate(Q):
        r, c = divmod(i, 4)
        x, y = X0 + c * (CW + GX), y0 + 10 + r * (CH + GY_)
        f.box(x, y, CW, CH, "#fff", col, 8, 2)
        f.badge(x + 16, y + 15, i + 1, col)
        f.t(x + 50, y + 34, q, INK, True, 16)
        f.lines(x + 18, y + 64, CW - 36, how.split("|"), size=13, lh=20)
        f.t(x + CW - 16, y + CH - 16, "→ " + sec, col, True, 13, "end")
    yb = y0 + 10 + 2 * CH + GY_ + 24
    yb = f.band(yb, "ok", "前四问不碰任何开关", [
        "口径、负载、字节下限、batch 上限，都是纸上能算完的账。",
        "后四问才是招数；账没算清就调参，调出来的数没法和别人比。",
    ])
    yb = f.src(yb + 10, "⚠️ 本课归纳：顺序按「先校准、再算账、后调招数」排，各问的判据见对应节。")
    f.save("fig6-eight.svg", yb + 14)


fig_eight()
