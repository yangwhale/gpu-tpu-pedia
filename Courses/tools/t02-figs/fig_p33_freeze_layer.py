"""图 P-33 —— 冻结发生在哪一层：CUDA Graph 冻的是最上面那层，TPU 编译器冻到底。

**这是 5.7 的核心图，也是整个反驳的答案所在。** P-32 已经说清 CUDA Graph
省的是主机侧的发射开销。那么「GPU 开了 graph 是不是就跟 TPU 一样了」这个问题，
就变成一个位置问题：<b>到底是哪一层被冻住了。</b>

**把数据通路分成三层，答案一眼可见。**
① <b>编排层</b>：下一个 kernel 是什么、什么时候提交；
② <b>落地层</b>：这个 kernel 的块放到哪个 SM；
③ <b>发射层</b>：核在跑的时候，下一拍执行哪条指令。
CUDA Graph 把 ① 冻住了，<b>② 和 ③ 一个都没动</b>；
TPU 的编译器是三层全冻，而且 ③ 冻到<b>具体哪个周期、哪个发射槽</b>。

**所以「一样了」这句话对了一层、错了两层。** 而错的那两层恰好是耗硅片面积的那两层 ——
这就把话交给了 P-34：既然 ② ③ 没变，那些为它们服务的部件就一个都省不掉。

**⚠️ 出处口径。** 三层的划分<b>是我为讲清楚这件事定的，不是谁的术语</b>。
每一层里「谁在决定」的事实有出处（CUDA 编程模型、VLIW 的定义），
但<b>「分成三层」这个切法本身是一个讲法</b>，图上写明了。
「粒度差三到四个数量级」是<b>用 kernel 的微秒量级除以时钟周期的纳秒量级推的</b>。
"""
from common import Fig, para, BL, GN, RD, YL, PU, TL, INK, SUB, GREY, FILL

W = 1400

COL_Y, COL_H = 84, 404                      # ① 三栏 × 三层
ANA_Y, ANA_H = COL_Y + COL_H + 22, 112      # ② 行程单比喻
GRA_Y, GRA_H = ANA_Y + ANA_H + 22, 112      # ③ 粒度差多少
LAND_Y, LAND_H = GRA_Y + GRA_H + 22, 108    # ④ 落点
SRC_Y, SRC_H = LAND_Y + LAND_H + 22, 92     # ⑤ 出处
H = SRC_Y + SRC_H + 20

COL_GAP = 8
COL_W = (1400 - 140 - 20 - 2 * COL_GAP) // 3   # = 408，别手填
LAY_H = 96                                  # 一层一个盒子

# 三层的名字与它们各自在问什么。**顺序就是从软到硬**，不要调。
TIERS = [
    ("① 编排层", "下一个 kernel 是什么、什么时候提交"),
    ("② 落地层", "这个 kernel 的块，放到哪个 SM 上"),
    ("③ 发射层", "核在跑的时候，下一拍执行哪条指令"),
]

# 三栏。每栏三层：(状态色, 徽章, 这一层由谁决定)
FROZEN, LIVE = GN, RD
COLS = [
    (GREY, "GPU · 不开 graph", "三层全是活的", [
        (LIVE, "运行时", "<b>CPU 每次现发一条</b>。发得慢，GPU 就闲着。"),
        (LIVE, "运行时", "<b>硬件分发器启动时挑一个 SM</b>，程序员指定不了。"),
        (LIVE, "每个周期", "<b>warp 调度器每拍挑一个数据到位的发</b>。"),
    ]),
    (BL, "GPU · 开 CUDA Graph", "只冻住了最上面一层", [
        (FROZEN, "capture 时定死", "<b>整张 DAG 在 capture 那一下固定</b>，"
                                   "之后只发一条 replay。<b>这一层确实变成静态的了。</b>"),
        (LIVE, "运行时", "<r>一点没变。</r>graph 里每个节点仍然是一次正常的 kernel 启动，"
                         "块照样由硬件现场分发。"),
        (LIVE, "每个周期", "<r>一点没变。</r>调度器、记分板、warp 槽、常驻上下文 —— "
                           "<b>全都还在，而且全都还在工作。</b>"),
    ]),
    (GN, "TPU · XLA 编译", "三层全冻，而且冻到周期", [
        (FROZEN, "编译期", "<b>整个 step 编成一个程序</b>。"
                           "<g>本来就没有「主机一条条发」这回事 —— 不需要 graph。</g>"),
        (FROZEN, "编译期", "没有「放到哪儿」这个问题：<b>用哪个部件写在指令里。</b>"),
        (FROZEN, "编译期", "<b>VLIW：哪条指令、第几个周期、哪个发射槽，全排死。</b>"
                           "<r>卡住就是真的空转。</r>"),
    ]),
]


def build():
    f = Fig(W, H, "CUDA Graph 冻结的是主机编排层；kernel 的块分发与 warp 发射两层"
                  "完全没有变化。TPU 的编译器则把三层全部冻结，并精确到时钟周期")
    f.title("冻结发生在<tspan font-weight=\"700\">哪一层</tspan>"
            "　—— CUDA Graph 冻的是最上面那层，TPU 编译器<tspan "
            "font-weight=\"700\">冻到底</tspan>")
    f.legend([(FROZEN, "这一层是静态的（跑之前就定死）"),
              (LIVE, "这一层是活的（芯片在运行时决定）")])
    _cols(f)
    _analogy(f)
    _gran(f)
    _land(f)
    _src(f)
    return f.out()


# ══════════════════════════════════════════════════════════════════════
# 三栏并排。**中间那一栏是全图的答案**：只有第一格变绿，下面两格还是红的。
def _cols(f):
    # 左侧的层名条，让三栏能横着对齐读
    for i, (name, ask) in enumerate(TIERS):
        y = COL_Y + 62 + i * (LAY_H + 8)
        f.t(24, y + 22, name, "xxs", INK)
        para(f, 24, y + 40, 108, ask, "xxs", 13, fill=GREY, max_lines=4)

    for j, (c, ttl, tag, tiers) in enumerate(COLS):
        x = 140 + j * (COL_W + COL_GAP)
        f.rect(x, COL_Y, COL_W, COL_H, "#fff", c, 1.8, 10)
        f.t(x + 16, COL_Y + 28, ttl, "sec", c)
        f.t(x + COL_W - 16, COL_Y + 28, tag, "xxs", SUB, anchor="end")
        for i, (sc, badge, body) in enumerate(tiers):
            y = COL_Y + 62 + i * (LAY_H + 8)
            f.rect(x + 12, y, COL_W - 24, LAY_H, FILL[sc], sc, 1.4, 6)
            f.t(x + 24, y + 22, badge, "box", sc)
            # ⚠️ max_lines=4 是硬约束：LAY_H 固定 96，第五行会压出盒子。
            para(f, x + 24, y + 42, COL_W - 48, body, "xs", 16, max_lines=4)


# ══════════════════════════════════════════════════════════════════════
def _analogy(f):
    f.rect(20, ANA_Y, 1360, ANA_H, FILL[YL], YL, 1.6, 10)
    f.t(38, ANA_Y + 26, "🧳 一个能记住的说法：行程单 vs 航班内部", "sec")
    y = para(f, 38, ANA_Y + 50, 1324,
             "<b>CUDA Graph 相当于把整趟旅行的行程单提前打印好</b> —— "
             "先坐哪班飞机、再转哪趟车，一条一条都定死了，不用到了机场再现查。"
             "<b>省下来的就是「每一段都要现查一次」的那些时间。</b>", "xs", 19)
    para(f, 38, y + 2, 1324,
         "<r>但每一班飞机内部一点没变</r>：怎么排队、谁先登机、空乘怎么调度，"
         "还是现场决定。<b>TPU 编译器管的恰恰是这一层</b> —— "
         "它连「第几分钟谁走哪条通道」都提前排好了。", "xs", 19)


# ══════════════════════════════════════════════════════════════════════
