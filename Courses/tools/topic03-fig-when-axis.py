r"""专题三 · §4.2b「事后压 vs 从头按压缩训」

⭐⭐⭐ 2026-09-14 **整张重画**，换成一个装修过房子的人都懂的画面：
   **老房改造 vs 一开始就这么设计。**

   · **事后压 ＝ 房子已经盖好了再改造** ——&nbsp;快、便宜、不用搬家，
     但**承重墙动不了**，有些地方就是别扭。
   · **native ＝ 图纸阶段就按这个户型画** ——&nbsp;要重盖（重训），
     但**哪儿都合适**。

   这条对立在这一讲里**出现四次**，每次在不同的分支上 ——&nbsp;
   ⚠️ 但四次**全落在旋钮①② 上，旋钮③ 一格都没有**（为什么留空见 §4.2b 正文）。

⚠️ 一条必须讲清的口径（否则这张图会教出一个错的心智模型）：
   **「事后 / native」说的是这个方法<b>这一次被怎么用</b>，不是方法本身的属性。**
   GQA 最初是 uptraining 出来的（改造），但今天 Llama 那一系
   **从第一天就是 GQA**（新建）。同一个机制，两种用法。
"""
from topic03_draw import (Fig, BL, OR, GR, RD, GY, PU, INK, GY2, LINE, LINE2,
                          BG2)

W = 1400


def main():
    f = Fig(W, "事后压 vs 从头按压缩训：就像老房改造和一开始就按这个户型设计 —— "
               "改造快、便宜、不用搬家，但承重墙动不了；"
               "新建要重盖，但哪儿都合适。这条对立在四个分支上各出现一次")
    f.marks = set()
    y0 = f.header(
        "事后压，还是从头按压缩训",
        "就像<tspan font-weight=\"700\">老房改造</tspan> 和 "
        "<tspan font-weight=\"700\">图纸阶段就按这个户型画</tspan>",
        [(OR, "改造（事后）"), (GR, "新建（native）"),
         (GY, "同一个机制的两种用法")])

    # ══════════ ① 两种做法 ══════════════════════════════════════
    PH = 262
    py = f.panel(0, y0, W, PH, "① 两种做法 ——　各有各的好，不是谁淘汰谁",
                 INK, sub="装修过的人都懂")

    ay = py + 24
    f.box(56, ay + 24, 636, 188, "#fff", OR, 10)
    f.t(80, ay + 64, "改造 ——　房子已经盖好了", OR, True, 25)
    for i, ln in enumerate([
        "✅ 快、便宜，不用搬家（不用重训）",
        "✅ 想撤随时撤（很多是推理期开关）",
        "⛔ 承重墙动不了 ——　有些地方就是别扭",
    ]):
        f.t(104, ay + 108 + i * 36, ln, GY, size=18)

    f.box(724, ay + 24, 636, 188, "#e6f4ea", GR, 10)
    f.t(748, ay + 64, "新建 ——　图纸阶段就这么画", GR, True, 25)
    for i, ln in enumerate([
        "⛔ 要重盖（重训），贵、慢",
        "⛔ 盖完了就改不回去",
        "✅ 哪儿都合适 ——　省得更狠，掉点更小",
    ]):
        f.t(772, ay + 108 + i * 36, ln, GY, size=18)

    # ══════════ ② 四次出现 ══════════════════════════════════════
    y1 = y0 + PH + 18
    PH2 = 442   # ⭐ 落点带字号抬到 15 之后变高，这里要多让 18px
    py2 = f.panel(0, y1, W, PH2, "② 这条对立，在这一讲里出现四次",
                  GR, sub="四次都在不同的分支上 ——　所以它不是巧合")

    ROWS = [
        ("旋钮① · 低秩分解",
         "Eigen / Palu / LoRC", "拿训好的模型做低秩分解", "省 40% / 50%",
         "MLA", "从第一天就按 512 训", "省 56.9×"),
        ("旋钮① · 砍头",
         "GQA uptraining", "平均已有的头 ＋ 5% 算力续训", "接近 MHA",
         "GQA from scratch", "一开始就分 8 组", "同上，但不用两段"),
        ("旋钮② · 挑着看",
         "H2O", "一个 KV 驱逐策略，不改训练", "随时可开关",
         "DSA", "943.7B token 继续训练", "掉点小得多"),
        ("旋钮② · 挑着看",
         "ClusterKV / HashAttention / Quest", "推理期加的选择器",
         "⛔ 三家三种毛病（见 §6.3b）",
         "NSA", "端到端训练的三条分支", "持平或超过全注意力"),
    ]
    by = py2 + 20
    f.t(80, by + 18, "第几次", GY2, True, 15)
    f.t(200, by + 18, "改造（事后）", OR, True, 19)
    f.t(760, by + 18, "新建（native）", GR, True, 19)
    by += 26
    for i, (where, a1, a2, a3, b1, b2, b3) in enumerate(ROWS):
        f.box(56, by, W - 112, 88, "#fff", LINE, 8)
        f.t(80, by + 36, "第 %d 次" % (i + 1), INK, True, 19)
        f.t(80, by + 64, where, GY2, size=13, w=112)
        f.box(196, by + 12, 524, 64, "#fff7ed", OR, 6)
        f.t(214, by + 38, a1, OR, True, 18, w=486)
        f.t(214, by + 64, a2 + "　·　" + a3, GY, size=15, w=486)
        f.line(726, by + 44, 752, by + 44, GY2, 1.6)
        f.box(758, by + 12, 524, 64, "#e6f4ea", GR, 6)
        f.t(776, by + 38, b1, GR, True, 18, w=486)
        f.t(776, by + 64, b2 + "　·　" + b3, GY, size=15, w=486)
        by += 96

    f.t(80, by + 22, "⚠️ 四次<tspan font-weight=\"700\">全落在旋钮①② 上</tspan>"
        " ——&#160;旋钮③ 一格都没有（为什么留空，见 §4.2b 正文）", RD, True, 19)

    # ══════════ 落点 ════════════════════════════════════════════
    # ⛔ 这里原来写死 y1 + PH2 + 20，而面板②最后那行提示是画在**面板外面**的
    #   （by 已经跑到 PH2 以下）。落点带一长高就压上去了。
    # ⭐ 判据：落点带的起点要跟**真实画到哪儿**走，不能跟声明的面板高走。
    yy = max(y1 + PH2, by + 40) + 20
    yy = f.band(yy, "warn", "⚠️ 一条不讲会教出错误心智模型的口径", [
        "<tspan font-weight=\"700\">「改造 / 新建」说的是这个方法<em>这一次被怎么用</em>，"
        "不是方法本身的属性。</tspan>",
        "最好的例子就是 GQA：它最初是 <tspan font-weight=\"700\">uptraining</tspan> 出来的"
        "（改造），可今天 Llama 那一系<tspan font-weight=\"700\">从第一天就是 GQA</tspan>"
        "（新建）。⭐ <tspan font-weight=\"700\">同一个机制，两栏都待过。</tspan>",
    ])

    yy = f.band(yy + 14, "info", "⭐ 带走的用法：拿到一个新名字，先把它放进某一格", [
        "放得进去的，<tspan font-weight=\"700\">它的优点和代价你已经知道了</tspan> ——&#160;"
        "改造类的就去问「承重墙在哪」（哪里改不动）；"
        "新建类的就去问「重训要多少钱」。",
        "⭐ <tspan font-weight=\"700\">放不进去的，才值得你花时间</tspan> ——&#160;那才是真正的新东西。",
    ])

    yy = f.src(yy + 16,
               "各家的出处见 §五 / §六 对应小节；"
               "GQA 的 mean pooling ＋ α=5% 续训出自 arXiv 2305.13245 §2.2",
               "⚠️ 「老房改造 / 图纸阶段」是<tspan font-weight=\"700\">本课的比喻</tspan>；"
               "⚠️ 「四次」只数到旋钮①②，旋钮③ 那一格本讲没有核过数，故留空")
    f.save("fig3-when-axis.svg", yy + 6)


main()
