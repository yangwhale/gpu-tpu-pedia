TODO = re.compile(
    r'<section[^>]*><div class="wrap">\s*<div class="note info">'
    r'<span class="t">🚧 后面还在写</span>.*?</section>', re.S)


def main():
    svg = _harvest()
    parts = {k: _split(k, v) for k, v in svg.items()}
    defs = parts["g1"][0]
    for k, (d, _) in parts.items():                 # 十六份 defs 必须完全一致，
        assert d == defs, "defs 不一致：" + k        # 否则抽成一份会悄悄改掉某张图
    F = lambda k: figure(k, parts[k][1])

    html = io.open(PAGE, encoding="utf-8").read()

    # 幂等注入 CSS。**曾经写的是 `if CSS not in html`，那是个假幂等** ——
    # 只要改一个字，旧块就通不过 `not in` 测试，于是又追加一份，旧的还留着。
    # 实际累积到了 5 份（`.fwide{margin-left:50%` 在页面里出现 5 次）。
    # 现在改成：先把「第一个标记 → </style>」之间整段铲掉，再插当前这份。
    # 铲的范围天然覆盖历史上所有版本，无论它们各自长什么样。
    i = html.find(CSS_MARK)
    if i >= 0:
        # rstrip 掉标记前的空白：CSS 常量自己是 '\n/* ---- */...' 开头的，
        # 如果只从标记位置开始删，那个前导换行每轮都会剩一个下来 —— 文件
        # 于是「每跑一次多一个空行」，看着像不幂等，其实只差这一下。
        html = html[:i].rstrip() + html[html.index("</style>", i):]
    html = html.replace("</style>", CSS + "</style>", 1)

    block = "\n".join([
        BEG,
        '<svg width="0" height="0" style="position:absolute" aria-hidden="true">',
        defs, "</svg>",
        sections(F),
        END])

    # 幂等：第一次吃掉「🚧 后面还在写」那一段，之后拿生成块自己当锚点。
    # 不能先删再找 —— 上一版就是这么写的，删完锚点就没了，第二次跑必炸。
    old = re.compile(re.escape(BEG) + ".*?" + re.escape(END), re.S)
    if old.search(html):
        html = old.sub(lambda _: block, html, count=1)
    else:
        assert TODO.search(html), "找不到「🚧 后面还在写」那一段，页面结构变了"
        html = TODO.sub(lambda _: block, html, count=1)

    # ⚠️ 两道自检都必须跑在**写盘之前**。
    # 上一版是先写后检 —— 那样内部词一旦漏进来，等 assert 喊出声时，
    # 它已经落在这个**公开仓库**的文件里了，接下来只要有人 commit 就出去了。
    # 「检查失败」和「文件没被污染」得是同一件事，不能分成两步。
    # ⛔ 禁字表**不在这里**，在 tpu-micro/gate.py 的 `_FORBIDDEN`。
    #    这里曾经自己抄了一份，两件坏事一起来：① 两份表会漂，一处补了另一处
    #    没补，还以为有两道防线；② 仓库级闸门扫到这个文件时会命中**这份表自己**，
    #    永远误报，而一个总在误报的闸门等于没有闸门。
    #    目录名带连字符，不能当包 import —— 直接把它加进 sys.path。
    sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                    "tpu-micro"))
    from gate import lint_public
    bad = lint_public(html)
    assert not bad, "公开页面里出现内部词，已中止写盘：%s" % bad

    # 数**页面上真有的**，不是数采集到的。这两个数一度差了 6 ——
    # sections() 里漏掉了六张图，而这行照样报「移植 16 张图」，
    # 于是自检看着全绿、实际漏了三分之一。**报数只能报最终产物。**
    placed = set(re.findall(r'<figure class="fbox fwide" id="ms-(\w+)"', html))
    miss = sorted(set(parts) - placed)
    assert not miss, "这几张采集了却没摆上页面：%s" % miss

    io.open(PAGE, "w", encoding="utf-8").write(html)
    print("ok  topic-02-L300.html  %s 字符  移植 %d 张图  禁字自检通过"
          % (format(len(html), ","), len(placed)))

    # 生成区里有一个 id="s012-fig0-1" 的**空壳 svg**（附录 A 那张瀑布图），
    # 真内容归 topic02-inject-s012.py 管。这里直接把它跑掉，而不是靠人记住 ——
    # 忘一次的后果是页面上凭空多一块空白，而且不报错。
    inj = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                       "topic02-inject-s012.py")
    r = subprocess.run([sys.executable, inj], capture_output=True, text=True)
    assert r.returncode == 0, "注入 s012 图失败：\n%s%s" % (r.stdout, r.stderr)
    print(r.stdout.strip())


if __name__ == "__main__":
    main()
