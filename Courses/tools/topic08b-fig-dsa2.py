def fig_fence():
    S = N.DSA_FENCE_STALE
    f = Fig(W, "小核把一块部分梯度用带加法的间接写，加进共享内存里同一批 key 的行。每笔写分两段：先读源，再把数加进目的地。wait 只等源读完就返回。"
               "上：不加栅栏，下一块对同一行的加法可能先落地，两笔加法先后颠倒，末位不同；最后一块加完紧接着把结果拷回，拷回可能读到还没加上的旧值。"
               "下：每块排空后发一次很小的本地拷贝，并等它写完；这种写等待会把之前发出的所有写一起围住，下一块和拷回都在加法落地之后。"
               "单卡微基准：不加栅栏 75 次里有 3732 个元素读到旧值，加了 0 个。整模型每步多 3 到 6 毫秒。")
