    py = f.panel(0, y0, W, PH,
                 "Ⓐ 同一张纸上放两条曲线，"
                 "<tspan font-weight=\"700\">差别一眼就看出来</tspan>", RD,
                 sub="⭐ 横轴是训练步数，纵轴是 loss ——&#160;"
                     "<tspan font-weight=\"700\">越低越好，所以主干是往下走的</tspan>")

    X0, X1 = 96, W - 250
    TOP, BOT = py + 58, py + 196          # 大模型那条的上下沿
    TOP2, BOT2 = py + 246, py + 330       # 小模型那条

    # 坐标轴（只有方向，没有刻度 —— 见文件头那条纪律）
    f.line(X0, BOT + 14, X1 + 16, BOT + 14, GY2, 1.2)
    f.line(X0, BOT + 14, X0, TOP - 16, GY2, 1.2)
    f.t(X0 - 10, TOP - 24, "loss", GY2, size=12, anchor="end")
    f.t(X1 + 20, BOT + 18, "步数 →", GY2, size=12)

    def curve(top, bot, spikes, col, sw):
        """主干 ＋ 尖峰，一条 path 画完。"""
        pts, N = [], 160
        for i in range(N + 1):
            t = i / float(N)
            pts.append((X0 + (X1 - X0) * t, _loss_y(t, top, bot)))
        d = "M %.1f %.1f" % pts[0]
        for i in range(1, N + 1):
            x, y = pts[i]
            t = i / float(N)
            # 尖峰：走到某个位置时先扎上去，再立刻回到主干
            for k, s in enumerate(spikes):
                if t - 1.0 / N < s <= t:
                    h = 42 + 34 * ((k * 7) % 5) / 4.0      # 高度有变化但固定
                    d += " L %.1f %.1f L %.1f %.1f" % (x, y - h, x + 5, y - h * .25)
            d += " L %.1f %.1f" % (x, y)
        f.path(d, col, sw, arrow=False)

    curve(TOP, BOT, SPIKES, RD, 1.7)
    curve(TOP2, BOT2, (), GR, 1.7)

    f.t(X1 + 26, BOT - 18, "540B", RD, True, 16)
    f.t(X1 + 26, BOT + 4, "约 20 次", RD, size=12.5)
    f.t(X1 + 26, BOT2 - 18, "更小的模型", GR, True, 16)
    f.t(X1 + 26, BOT2 + 4, "一次都没有", GR, size=12.5)
    # ⚠️ 两条不共用纵轴 —— 小模型的 loss 本来就更高，硬放一根轴上会
    #    让人去比高低，而这张图要比的是**形状**。
    f.t(X0 + 6, TOP2 - 22, "⚠️ 下面这条<tspan font-weight=\"700\">另起一根纵轴</tspan>"
        " ——　这里比的是形状，不是谁低", GY2, size=12)

