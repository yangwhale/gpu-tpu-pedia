# 判据用「最长公共子串」而不是整句相等：真实的重复几乎都是**换了个说法但
# 骨架照搬**（「问题就从 X 变成了位置问题：到底哪一层被冻住了」对
# 「X 就变成一个位置问题：到底哪一层被冻住了」），整句比对一条都抓不到。
DUP_MIN = 14          # 连续 14 个字一样，基本不可能是巧合
DUP_WINDOW = 2        # 只跟前后各 2 个 figcaption 比 —— 隔了半页的呼应是好事，不算重复


def _lcs(a, b):
    """最长公共子串的长度和内容。文本都在几百字量级，O(nm) 完全够用。"""
    best, bi = 0, 0
    prev = [0] * (len(b) + 1)
    for i in range(1, len(a) + 1):
        cur = [0] * (len(b) + 1)
        for j in range(1, len(b) + 1):
            if a[i - 1] == b[j - 1]:
                cur[j] = prev[j - 1] + 1
                if cur[j] > best:
                    best, bi = cur[j], i
        prev = cur
    return best, a[bi - best:bi]


# 允许重复的：专有名词和固定术语。**白名单只放「换个说法就是错的」的词** ——
# 用它来放过写重了的句子，等于把这道检查关掉。
DUP_OK = ("FlashAttention", "CUDA Graph", "cp.async", "__syncthreads",
          "SparseCore", "TensorCore", "head_dim", "NVLink", "warp 调度器",
          # R3 加：3.5 正文要给图上这个词一句白话释义（它是全课唯一
          # 「出现即用、从未定义」的术语），而释义必然要把词本身写出来。
          # 这正是白名单该放的东西 —— 换个说法就是错的。
          "duplication factor")


def _dup_check(html):
    # ⚠️ 先把 <svg> 整块删掉再查。SVG 里全是图上的文字，而图注本来就在
    #    描述图上的文字 —— 不删的话每张图都会「自己跟自己重复」，
    #    真正的重复被淹在噪声里。（第一版就是这么误报了两条。）
    html = re.sub(r"<svg.*?</svg>", "", html, flags=re.S)
    plain = lambda x: re.sub(r"[\s　]+", "", re.sub(r"<[^>]+>", "", x))
    # 按出现顺序切成「正文块」和「图注」两串，保留原始次序好算窗口
    items = []
    for m in re.finditer(
            r"<figcaption>(.*?)</figcaption>"
            r"|<p[^>]*>(.*?)</p>"
            r"|<div class=\"note[^\"]*\">(.*?)</div>", html, re.S):
        cap, para, note = m.group(1), m.group(2), m.group(3)
        if cap is not None:
            items.append(("cap", plain(cap)))
        else:
            t = plain(para if para is not None else note)
            if len(t) >= DUP_MIN:
                items.append(("txt", t))

    bad = []
    for i, (k, t) in enumerate(items):
        if k != "txt":
            continue
        for j in range(max(0, i - DUP_WINDOW * 2), min(len(items), i + DUP_WINDOW * 2 + 1)):
            if j == i or items[j][0] != "cap":
                continue
            n, frag = _lcs(t, items[j][1])
            # ⚠️ 判据是「这段重复**基本就是那个术语本身**」，不是「里面含有术语」。
            #    第一版写成 `any(w in frag)`，结果一个 40 字的真重复因为里面
            #    含了 cp.async 被整段放过 —— 白名单一松，检查就等于没有。
            ok = any(f2 == w.replace(" ", "") or len(f2) <= len(w) + 3
                     for w in DUP_OK for f2 in [frag] if w.replace(" ", "") in f2)
            if n >= DUP_MIN and not ok:
                bad.append((n, frag, t[:34]))

    if bad:
        bad.sort(reverse=True)
        msg = "\n".join("  %d 字重复：「%s」\n      正文这边：%s…" % b for b in bad)
        raise AssertionError(
            "正文复述了紧挨着的图注 —— 这正是 L300 栽过的那个毛病：\n%s\n"
            "  改法：正文只负责「把上一张图的结论接到下一张图的问题上」，"
            "图上写了的话一个字都不要再写一遍。" % msg)
    print("    查重通过（正文与相邻图注无 %d 字以上重复）" % DUP_MIN)


