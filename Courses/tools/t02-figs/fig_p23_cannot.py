# -*- coding: utf-8 -*-
"""图 P-23 —— 这门课答不了的二十条，以及每一类要怎样才能补上。

⭐ **这张图的结构不是「列清单」，是「按补法排成一条轴」。**

二十条按「要怎样才补得上」分成四类，从左到右**越来越不由我们决定**：

  ① 缺一组对照实测　→ 去跑一次就有（缺的只是机时）
  ② 缺一个能拆开的实验　→ 多跑一遍没用，得先设计对照组
  ③ 缺可比口径　　　→ 口径没对齐之前，测出来也不能比
  ④ 查不到出处　　　→ 等厂商公开，或找到可引用的来源

分成四堆而不是列二十条，是因为**「答不了」这三个字本身没有信息量** ——
听众真正要判断的是「这条能不能补、多久能补」。排成轴之后，
第 ① 类立刻变成一份可执行的待办（其中最便宜的一条：去测 128 个单元），
第 ④ 类则明确告诉听众别等了。

**四类正好各五条是数出来的，不是凑的。** 二十条逐条对得上出处，
没有为了对称拆条或并条 —— 图右下角那行脚注就是说这件事。

⭐ **底带那条才是这张图存在的理由，而它是画这张图的时候数出来的。**

二十条按「课件上承认过没有」再切一刀，得到的是**三堆，不是两堆**
（这一刀是逐条去 `topic-02.html` 里 grep 出来的，不是估的）：

  · **十六条写在课件的图上** —— 每美元、每瓦、分桶浪费、热启动那 8 分钟、
    pdbs 13 的机制、B300 是不是双 die……
  · **两条只写在作者自己的备忘里**（大纲的「还没想清楚的」，
    原文是「**没查证，先不要讲**」）：v7 切片有没有「物理 ≠ 可训练」、
    SparseCore 在集合通信里的角色。**课件上一个字都没有。**
  · **两条从来没想到**：「哪个更适合推理」和「TCO」。

**三堆的成因完全不同，而台下看到的是同一片空白。**

第三堆的机制：**自曝清单只能列出你撞到过的坑。** 那 16 条全是在做事的过程中
撞出来的 —— 跑不出来、对不上、查不到出处；而两边推理对比和 TCO
**从来没有开过工**，所以从来没有机会暴露自己。
**没做过的方向，不会在做的过程中自己冒出来。**

第二堆的机制不一样，也更隐蔽：那是一个**主动决定**（「先不要讲」），
**但学生看不出它是个决定** —— 一个决定不讲的空白，跟一个没意识到的空白，
在台下眼里长得一模一样。所以要么讲，要么在课件上明写「这一条查过，没结论」。

三张图的三个补法因此各防一样东西，缺一不可：
**P-20「换个主角重读」防偏向；「换个外行提问」防想不到；
「把决定不讲的也写出来」防台下看不见。—— 偏了、漏了、藏了。**

⚠️ **两处措辞不能松：**

  · 「哪个更适合推理」缺的是**两边同模型的吞吐 / TTFT / 并发对比**。
    §5.5 有 TPU 侧的移植账单、GB300 侧有一份 runlog，但**不同模型、不同口径**；
    §7 那组唯一的两边同口径实测**跑的是预训练**。所以不是「数少」，是**一组都没有**。
  · TCO **全课没出现过这个词**。P-17 甲③ 和 P-14 ④ 只承认了每美元和每瓦这两个
    分量，而 TCO 还要再叠利用率、运维和排队损耗 —— 不能拿那一格冒充已经承认过。

出处（逐条可回查，均在本课件内）：
  · ① P-18 底带（「要推翻这一节最省事的办法…是去测 128 个」）／
    §4.5 danger note（「那是推论，不是我们测出来的」）／P-8（三笔只有 TPU 侧）／
    P-15（EP16 的 882.3 没跟进复测，所以全节倍数写成下限）
  · ② P-15 乙格（「所以差距全在软件」这一句，我们没有证明，也不打算说）／
    P-17 乙格 ⚠️ 行（算力翻倍而 HBM 带宽没翻倍，那是硅片）／
    P-7 落点（「留白会被读成『不存在』，明写『没量』不会」）／P-8／P-10 甲格
  · ③ P-17 甲③（第三根条、末端打问号）／P-14 第 ④ 档（「价格是谈出来的，不是牌价」）／
    P-20 底带（软件成熟度、FLOP 公式 1.2%）
  · ④ §4.3 note（「查不到就明写查不到」）／`topic02-verified-specs.md`（148 未能官方核实）／
    P-18 ⑥ 注（没考据过 GB300 用的 B300）／大纲「还没想清楚的」两条
"""
