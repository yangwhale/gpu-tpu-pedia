# -*- coding: utf-8 -*-
"""图 P-35 —— 同一对硬件，三把尺子：16 倍、128 倍、512 倍量的是三件不同的事。

**这张图是被本课自己的一个错逼出来的。** 3.4 的标题原本写着「这里出那个 128 倍」，
可整节从头到尾只算出两个比值：收缩维差 <b>16 倍</b>、head_dim 是 K 的 8 倍。
<b>128 从来没在这一节出现过</b> —— 它在 3.7 的账表里，是「单个单元每周期多少乘加」
那一行（131,072 ÷ 1,024）。<b>那是硬件单元的吞吐密度比，不是指令粒度比。</b>

**最讽刺的地方在于**：3.7 那段注释本身就在警告「两个比值必须分开看，
否则会算出第三个数」—— 它成功挡住了 592 ÷ 4 ＝ 148 那个坑，
<b>自己却在上一级又踩了一次</b>，把单元大小比说成了指令粒度比。

**所以这张图不改口径，改的是「把三把尺子同时摆出来」。** 三个数全都对，
错的是随手抓一个当「那个 128 倍」。摆在一起之后，
「这一节交付 16 倍、128 倍在 3.7」就变成看一眼就知道的事。

**⚠️ 出处口径。** K ＝ 16 与三条指令的 M×N 出自 PTX ISA；MXU 256×256 与
262,144 FLOP/周期出自公开工程博客；<b>GPU 单核 1,024 乘加/周期是「官方 ＋ 推导」</b>，
3.7 的账表里就是这么标的，这里照搬同一个口径，不升级成引用。
"""
from common import Fig, para, BL, GN, RD, YL, PU, TL, INK, SUB, GREY, FILL

W = 1400

ROW_Y, ROW_H, ROW_G = 84, 120, 10
NROW = 3
WARN_Y = ROW_Y + NROW * (ROW_H + ROW_G) + 12
WARN_H = 104
LAND_Y, LAND_H = WARN_Y + WARN_H + 22, 100
SRC_Y, SRC_H = LAND_Y + LAND_H + 22, 86
H = SRC_Y + SRC_H + 20

NX, NW = 20, 250          # 尺子名
BX, BW = 286, 700         # 条形
RX, RW = 1000, 380        # 倍数 + 这个数在哪儿用

FULL = 340                # TPU 那根条固定这么长，GPU 按比例缩
BARX = BX + 80            # 条形起点。左边留给数字，右边留给标签 —— 
                          # 标签最长的是尺子三那三行，实测到 x≈960，
                          # 再长就会撞进 RX=1000 那一栏。改 FULL 前先量这个。
MINW = 6                  # 缩到看不见时的下限，画出来才知道「小到画不出」
                          # ⚠️ 一旦钳到 MINW，那根条的长度就**不再代表比例**了。
                          #    这张图整篇在讲「别混口径」，自己更不能默默作弊 ——
                          #    所以 _clamp_note() 把这件事写在条形栏里。别删。


def build():
    f = Fig(W, H, "同一对硬件的三个比值：收缩维差 16 倍、单个计算单元的每周期吞吐差 "
                  "128 倍、一条指令的输出块最多差 512 倍。三者量的不是同一件事")
    f.title("同一对硬件，<tspan font-weight=\"700\">三把尺子</tspan>"
            "　—— 16 倍、128 倍、512 倍，量的是三件不同的事", "3.4 的自查")
    f.legend([(BL, "GPU 侧"), (GN, "TPU v7 侧"),
              (RD, "本课反复说的那个「128 倍」在这一行")])
    _r1(f)
    _r2(f)
    _r3(f)
    _clamp_note(f)
    _warn(f)
    _land(f)
    _src(f)
    return f.out()


# ══════════════════════════════════════════════════════════════════════
def _frame(f, i, c, name, what):
    y = ROW_Y + i * (ROW_H + ROW_G)
    f.rect(20, y, 1360, ROW_H, "#fff", c, 1.8, 10)
    f.rect(20, y, 6, ROW_H, c, rx=0)
    f.t(NX + 20, y + 28, name, "sec", c)
    para(f, NX + 20, y + 50, NW - 30, what, "xs", 16, max_lines=4)
    return y


def _bar(f, x, y, w, c, lab, num):
    f.rect(x, y, max(w, MINW), 22, FILL[c], c, 1.5, 3)
    f.t(x + max(w, MINW) + 10, y + 16, lab, "lbl", c)
    f.t(x - 10, y + 16, num, "xs", SUB, anchor="end")


def _ratio(f, y, c, big, sub, where):
    f.t(RX + 10, y + 38, big, "numb", c)
    f.t(RX + 10, y + 56, sub, "xxs", SUB)
    para(f, RX + 10, y + 78, RW - 20, where, "xs", 15, max_lines=3)


# ── 尺子一：收缩维 ────────────────────────────────────────────────────
def _r1(f):
    y = _frame(f, 0, BL, "尺子一　收缩维 K",
               "一条指令<b>一次能吃多深</b>。它决定 <code>head_dim</code> 撞不撞墙。")
    _bar(f, BARX, y + 30, FULL / 16.0, BL, "GPU Tensor Core　K ＝ 16", "16")
    _bar(f, BARX, y + 68, FULL, GN, "TPU MXU 的收缩边 ＝ 256", "256")
    _ratio(f, y, BL, "16 ×", "256 ÷ 16",
           "<b>这一节真正算出来的就是这个数。</b>"
           "head_dim ＝ 128 打 TPU 不打 GPU，全从这一行来。")


# ── 尺子二：单元吞吐 ──────────────────────────────────────────────────
def _r2(f):
    y = _frame(f, 1, RD, "尺子二　单个单元多大",
               "<b>一个</b> Tensor Core／MXU <b>每个周期</b>能做多少次乘加。"
               "量的是硬件，不是指令。")
    _bar(f, BARX, y + 30, FULL / 128.0, BL,
         "GPU 一个 Tensor Core　1,024 乘加/周期", "1,024")
    _bar(f, BARX, y + 68, FULL, GN,
         "TPU 一个 MXU　131,072 乘加/周期（256×256×2）", "131,072")
    _ratio(f, y, RD, "128 ×", "131,072 ÷ 1,024",
           "<r>本课反复说的 128 倍是这一行。</r>"
           "它出自 3.7 的账表，<b>不是 3.4 算出来的。</b>")


# ── 尺子三：一条指令的输出块 ──────────────────────────────────────────
def _r3(f):
    y = _frame(f, 2, YL, "尺子三　一条指令的输出块",
               "M × N 有多少个位置。<b>这把尺子最容易被当成前两把</b> —— "
               "而它<r>随指令变，一个数都钉不住</r>。")
    tot = 65536.0
    f.rect(BARX, y + 22, FULL, 18, FILL[GN], GN, 1.5, 3)
    f.t(BARX + FULL + 10, y + 35, "TPU MXU　256 × 256 ＝ 65,536", "lbl", GN)
    for k, (lab, m, n) in enumerate([("tcgen05.mma　128 × 256", 128, 256),
                                     ("wgmma　64 × 256", 64, 256),
                                     ("mma.sync　16 × 8", 16, 8)]):
        w = FULL * (m * n) / tot
        yy = y + 44 + k * 23
        f.rect(BARX, yy, max(w, MINW), 18, FILL[BL], BL, 1.4, 3)
        f.t(BARX + max(w, MINW) + 10, yy + 13,
            "%s　%s 个位置　→ %d 倍" % (lab, format(m * n, ","), int(tot // (m * n))),
            "xs", BL)
    _ratio(f, y, YL, "512 ×  ~  2 ×", "同一对硬件，三个答案",
           "<b>取决于你拿哪条指令来比。</b>"
           "<g>所以这把尺子适合讲道理，不适合报数字。</g>")


# ══════════════════════════════════════════════════════════════════════
def _clamp_note(f):
    """两根条短到画不出来，被钳到了 6 px —— 必须说明，否则这张图自己在作弊。"""
    f.t(BARX, ROW_Y + 2 * (ROW_H + ROW_G) + ROW_H - 4,
        "* 尺子二的 GPU 条与尺子三的 mma.sync 条真实长度不足 3 px，"
        "已钳到 6 px 才画得出来 —— 这两根<tspan fill=\"#d93025\">不按比例</tspan>，看数字。",
        "xxs")


# ══════════════════════════════════════════════════════════════════════
# ⚠️ 这一带是这张图存在的理由，别删。删了就退回成一张普通的对比图。
def _warn(f):
    f.rect(20, WARN_Y, 1360, WARN_H, FILL[RD], RD, 1.8, 10)
    f.t(38, WARN_Y + 28, "⚠️ 三个数都是对的 —— 错的是随手抓一个当「那个 128 倍」",
        "sec", RD)
    y = para(f, 38, WARN_Y + 54, 1324,
             "<b>它们量的东西根本不同</b>：尺子一量<b>指令能吃多深</b>，"
             "尺子二量<b>硬件一个周期能做多少</b>，尺子三量<b>一条指令产出多大一块</b>。"
             "<r>把任意两把混起来，都会算出一个不存在的结论。</r>", "xs", 19)
    para(f, 38, y + 2, 1324,
         "<b>这门课自己踩过一次</b>：3.4 的标题一度写着「这里出那个 128 倍」，"
         "而这一节从头到尾只产出 16 倍。<g>已改。留在这里当例子 —— "
         "这类错读起来完全通顺，只有把三把尺子摆在一起才看得见。</g>", "xs", 19)


# ══════════════════════════════════════════════════════════════════════
def _land(f):
    f.rect(20, LAND_Y, 1360, LAND_H, FILL[BL], BL, 1.8, 10)
    f.t(38, LAND_Y + 28, "⭐ 落点：报比值之前，先说清楚你在量什么", "sec", BL)
    y = para(f, 38, LAND_Y + 54, 1324,
             "<b>「GPU 和 TPU 差多少倍」这个问题，没有单一答案 —— "
             "它取决于你量的是哪一维。</b>同一对硬件，换把尺子就换个数，"
             "而三个数都能拿出出处。", "xs", 19)
    para(f, 38, y + 2, 1324,
         "<b>能带走的一条习惯</b>：<r>看到一个倍数，先问它的分子分母各是什么单位。</r>"
         "<g>这条习惯比记住 16、128、512 这三个数有用得多 —— 数字会换代，问法不会。</g>",
         "xs", 19)


# ══════════════════════════════════════════════════════════════════════
def _src(f):
    f.rect(20, SRC_Y, 1360, SRC_H, "#fff", GREY, 1.4, 10)
    f.t(38, SRC_Y + 26, "⚠️ 出处分层", "sec")
    y = para(f, 38, SRC_Y + 50, 1324,
             "<b>查到的</b>：K ＝ 16 与三条指令的 M×N 出自 PTX ISA；"
             "MXU 256×256、262,144 FLOP/周期/MXU 出自公开工程博客。", "xs", 18)
    para(f, 38, y + 2, 1324,
         "<r>口径要照搬、不要升级</r>：GPU 单核 1,024 乘加/周期在 3.7 的账表里标的是"
         "<b>「官方 ＋ 推导」</b>，这里沿用同一个标注。"
         "<g>它是 128 倍那一行的分母，分母的成色决定整行的成色。</g>", "xxs", 17)


if __name__ == "__main__":
    import io
    io.open("out/fig_p35_three_rulers.svg", "w",
            encoding="utf-8").write(build())
    print("ok fig_p35_three_rulers")
