def _dots(f, cx, cy, n, c):
    """犯过几笔：实心点计数；零笔画一个空心圈，不留白也不假装安全。"""
    if n == 0:
        f.raw('<circle cx="%.1f" cy="%d" r="5.5" fill="#fff" '
              'stroke="%s" stroke-width="1.6"/>' % (cx, cy, GREY))
        f.t(cx, cy + 22, "0 笔", "xxs", GREY, "middle")
        return
    per = 2 if n > 2 else n                 # 超过两个折成两行，别把列撑宽
    rows = [min(per, n - i) for i in range(0, n, per)]
    yy = cy - (len(rows) - 1) * 7
    for k in rows:
        x0 = cx - (k - 1) * 7.5
        for i in range(k):
            f.raw('<circle cx="%.1f" cy="%.1f" r="5.5" fill="%s"/>'
                  % (x0 + i * 15, yy, c))
        yy += 14
    f.t(cx, cy + 26, "%d 笔" % n, "xxs", c, "middle")


